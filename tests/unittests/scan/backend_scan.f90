      PROGRAM TEST_SCAN_BACKEND
      USE PAW_SKALA_MODULE, ONLY: TINITIALIZED
      IMPLICIT NONE
      INTEGER,PARAMETER :: NP=2
      REAL(8) :: RHO(NP,2),G(NP,3,2),T(NP,2),W(NP),X(NP,3),C(1,3),DW(NP),DESC(NP)
      REAL(8) :: E,REF,DR(NP,2),DG(NP,3,2),DT(NP,2),DX(NP,3),DC(1,3),DD(NP)
      REAL(8) :: RR(NP,2),RG(NP,3,2),RT(NP,2),RW(NP),ERROR
      INTEGER(8) :: SIZES(1)
      INTEGER :: I,FIRST,LAST
      REAL(8) :: SPLIT_ENERGY
      LOGICAL :: AVAILABLE,CUDA
      CALL MPE$INIT
      CALL TEST_SCAN_CORE_REFERENCE
      CALL SKALA$SETCH('FUNCTIONAL','SCAN')
      CALL SKALA$SETL4('ON',.TRUE.)
      CALL SKALA$SETL4('APPLY',.TRUE.)
      CALL SKALA$AVAILABLE(AVAILABLE)
      IF(.NOT.AVAILABLE) ERROR STOP 'Native SCAN unavailable without Torch'
      CALL SKALA$GETL4('CUDA',CUDA)
      IF(CUDA) ERROR STOP 'Native SCAN selected a Torch CUDA model'
      RHO=RESHAPE([0.3D0,0.2D0,0.13D0,0.4D0],[NP,2])
      G(:,:,1)=RESHAPE([0.14D0,-0.13D0,0.08D0,0.21D0,-0.17D0,0.03D0],[NP,3])
      G(:,:,2)=RESHAPE([-0.07D0,0.18D0,0.05D0,-0.11D0,0.03D0,0.12D0],[NP,3])
      T=RESHAPE([0.8D0,0.7D0,0.4D0,1.2D0],[NP,2])
      W=[0.7D0,1.3D0]
      X=0.D0
      C=0.D0
      DESC=[0.3D0,0.9D0]
      SIZES=NP
      CALL SCAN$BLOCK(NP,RHO,G,T,W,REF,RR,RG,RT,RW)
      CALL SKALA$EVALUATE(NP,1,RHO,G,T,X,W,C,DESC,SIZES,E,DR,DG,DT,DX,DW,DC,DD)
      ERROR=MAX(ABS(E-REF),MAXVAL(ABS(DR-RR)),MAXVAL(ABS(DG-RG)),MAXVAL(ABS(DT-RT)))
      ERROR=MAX(ERROR,MAXVAL(ABS(DW-RW)),MAXVAL(ABS(DX)),MAXVAL(ABS(DC)),MAXVAL(ABS(DD)))
      IF(ERROR.GT.1.D-13) ERROR STOP 'Native SCAN backend changes primitive adjoints'
      IF(.NOT.TINITIALIZED) ERROR STOP 'Native SCAN backend was not initialized'
      ! Include an empty range, as on layouts with more ranks than points.
      SPLIT_ENERGY=0.D0
      DO I=1,3
        FIRST=1+(I-1)*NP/3
        LAST=I*NP/3
        SIZES=LAST-FIRST+1
        CALL SKALA$EVALUATE(LAST-FIRST+1,1,RHO(FIRST:LAST,:),G(FIRST:LAST,:,:) &
     &     ,T(FIRST:LAST,:),X(FIRST:LAST,:),W(FIRST:LAST),C,DESC(FIRST:LAST),SIZES &
     &     ,E,DR(FIRST:LAST,:),DG(FIRST:LAST,:,:),DT(FIRST:LAST,:) &
     &     ,DX(FIRST:LAST,:),DW(FIRST:LAST),DC,DD(FIRST:LAST))
        SPLIT_ENERGY=SPLIT_ENERGY+E
      END DO
      ERROR=MAX(ABS(SPLIT_ENERGY-REF),MAXVAL(ABS(DR-RR)),MAXVAL(ABS(DG-RG)) &
     &         ,MAXVAL(ABS(DT-RT)),MAXVAL(ABS(DW-RW)),MAXVAL(ABS(DX)),MAXVAL(ABS(DC)))
      IF(ERROR.GT.1.D-13) ERROR STOP 'Native SCAN row partition changes energy or adjoints'
      SIZES=NP
      ! A local functional does not depend on coordinates or descriptor windows.
      X=2.1D0
      C=-3.D0
      DESC=0.D0
      CALL SKALA$EVALUATE(NP,1,RHO,G,T,X,W,C,DESC,SIZES,E,DR,DG,DT,DX,DW,DC,DD)
      IF(ABS(E-REF).GT.1.D-13.OR.ANY(DD.NE.0.D0)) ERROR STOP 'Native SCAN uses descriptor window weights'
      CALL SKALA$FINALIZE
      IF(TINITIALIZED) ERROR STOP 'Native SCAN backend was not finalized'
      CALL SKALA$SETCH('FUNCTIONAL','SKALA')
      CALL SKALA$SETL4('ON',.FALSE.)
      WRITE(*,'(A)') 'NATIVE SCAN PAW BACKEND CHECKS PASSED'
      CALL MPE$EXIT
      END PROGRAM TEST_SCAN_BACKEND

      SUBROUTINE TEST_SCAN_CORE_REFERENCE
      IMPLICIT NONE
      INTEGER,PARAMETER :: NR=2401
      REAL(8),PARAMETER :: PI=4.D0*ATAN(1.D0),SQ4PI=SQRT(4.D0*PI)
      REAL(8) :: R(NR),N(NR),CORE(NR),TAU(NR),E
      INTEGER :: GID
      CALL RADIAL$NEW('LOG',GID)
      CALL RADIAL$SETI4(GID,'NR',NR)
      CALL RADIAL$SETR8(GID,'R1',1.D-7)
      CALL RADIAL$SETR8(GID,'DEX',LOG(3.D8)/REAL(NR-1,8))
      CALL RADIAL$R(GID,NR,R)
      N=2.D0*EXP(-2.D0*R)/PI
      CORE=SQ4PI*N
      TAU=0.5D0*CORE
      CALL SKALA_SCAN_CORE_REFERENCE(GID,NR,CORE,TAU,E)
      WRITE(*,'(A,ES24.14)') 'SCAN SPHERICAL CORE XC ENERGY ',E
      ! Independent polarized LibXC 5.2.3 (263+267), Gauss-Legendre 256/512/1024.
      IF(ABS(E+0.66018837989858D0).GT.5.D-9) ERROR STOP 'SCAN frozen-core normalization/reference mismatch'
      CORE=0.D0
      TAU=0.D0
      CALL SKALA_SCAN_CORE_REFERENCE(GID,NR,CORE,TAU,E)
      IF(E.NE.0.D0) ERROR STOP 'SCAN core-free setup has a nonzero core reference'
      WRITE(*,'(A)') 'NATIVE SCAN FROZEN-CORE REFERENCE CHECKS PASSED'
      END SUBROUTINE TEST_SCAN_CORE_REFERENCE
