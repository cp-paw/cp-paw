PROGRAM DESCRIPTOR_GRID
  USE PAW_SKALA_MODULE, ONLY: GRID_ATOMS,GRID_CELL,BLOCK_GRID,CONFIG_RADIALPOINTS, &
       CONFIG_LEBEDEVEXACTNESS,CONFIG_LEBEDEVORIENTATIONS
  USE PAW_SKALA_GRID_MODULE, ONLY: PAW_SKALA_LOCAL_GRID_SIZE
  IMPLICIT NONE
  INTEGER :: REP,I,NP,NANG
  REAL(8) :: MOMENT,EXPECTED,ERROR,TEMP
  REAL(8),ALLOCATABLE :: REFERENCE(:),R2(:)
  CALL MPE__INIT
  CONFIG_RADIALPOINTS=80
  CONFIG_LEBEDEVEXACTNESS=17
  CONFIG_LEBEDEVORIENTATIONS=1
  CALL PAW_SKALA_LOCAL_GRID_SIZE(CONFIG_RADIALPOINTS,CONFIG_LEBEDEVEXACTNESS,NANG,NP)
  TEMP=2.D0
  EXPECTED=1.5D0*(4.D0*ATAN(1.D0))**1.5D0*TEMP**2.5D0
  ERROR=0.D0
  DO REP=1,2
    ALLOCATE(GRID_ATOMS(REP,3),BLOCK_GRID(REP))
    GRID_ATOMS=0.D0
    DO I=1,REP
      GRID_ATOMS(I,1)=6.D0*(I-1)
    END DO
    GRID_CELL=0.D0
    GRID_CELL(1,1)=6.D0*REP
    GRID_CELL(2,2)=6.D0
    GRID_CELL(3,3)=6.D0
    CALL SKALA_BUILDGRID(1)
    IF(SIZE(BLOCK_GRID(1)%D).NE.NP) STOP 1
    IF(ANY(BLOCK_GRID(1)%D.NE.BLOCK_GRID(1)%BASEW)) STOP 2
    IF(REP.EQ.1) THEN
      REFERENCE=BLOCK_GRID(1)%D
    ELSE
      IF(ANY(BLOCK_GRID(1)%D.NE.REFERENCE)) STOP 3
    END IF
    R2=SUM(BLOCK_GRID(1)%X**2,DIM=2)
    MOMENT=SUM(BLOCK_GRID(1)%D*R2*EXP(-R2/TEMP))
    ERROR=MAX(ERROR,ABS(MOMENT-EXPECTED)/EXPECTED)
    DEALLOCATE(GRID_ATOMS,BLOCK_GRID)
  END DO
  WRITE(*,'(A,ES16.7)') 'DESCRIPTOR GAUSSIAN MOMENT RELATIVE ERROR ',ERROR
  IF(ERROR.GT.1.D-9) STOP 4
  CALL MPE__EXIT
END PROGRAM DESCRIPTOR_GRID
