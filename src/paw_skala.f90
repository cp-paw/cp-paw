      SUBROUTINE SKALA$SMOOTHFIELDSGET(NR1START,NR1L,NR1,NR2,NR3 &
     &                                 ,NDIMD,RHO,GRHO,TAU,DVOL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NR1START,NR1L,NR1,NR2,NR3,NDIMD
      REAL(8),INTENT(OUT) :: RHO(NR1L*NR2*NR3,NDIMD)
      REAL(8),INTENT(OUT) :: GRHO(NR1L*NR2*NR3,3,NDIMD)
      REAL(8),INTENT(OUT) :: TAU(NR1L*NR2*NR3,NDIMD),DVOL
      INTEGER(4) :: IEND,IDIM,ICART

      IF(.NOT.TSMOOTHREADY) THEN
        CALL ERROR$MSG('SKALA SMOOTH FIELDS ARE NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$SMOOTHFIELDSGET')
      END IF
      IEND=NR1START+NR1L-1
      IF(NR1.NE.SMOOTH_NR1.OR.NR2.NE.SMOOTH_NR2 &
     &   .OR.NR3.NE.SMOOTH_NR3.OR.NDIMD.NE.SMOOTH_NDIMD &
     &   .OR.NR1START.LT.1.OR.IEND.GT.NR1) THEN
        CALL ERROR$MSG('SKALA SMOOTH FIELD GRID IS INCONSISTENT')
        CALL ERROR$STOP('SKALA$SMOOTHFIELDSGET')
      END IF
      DO IDIM=1,NDIMD
        RHO(:,IDIM)=RESHAPE(SMOOTH_RHO(NR1START:IEND,:,:,IDIM) &
     &                     ,(/NR1L*NR2*NR3/))
        TAU(:,IDIM)=RESHAPE(SMOOTH_TAU(NR1START:IEND,:,:,IDIM) &
     &                     ,(/NR1L*NR2*NR3/))
        DO ICART=1,3
          GRHO(:,ICART,IDIM)=RESHAPE &
     &       (SMOOTH_GRHO(NR1START:IEND,:,:,ICART,IDIM) &
     &       ,(/NR1L*NR2*NR3/))
        END DO
      END DO
      DVOL=SMOOTH_DVOL
      RETURN
      END

