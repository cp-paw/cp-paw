      SUBROUTINE SKALA$EVALUATE(NPOINT,NATOM,DENSITY,GRAD,KIN &
     &                         ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS &
     &                         ,ATOMICGRIDWEIGHTS,ATOMICGRIDSIZES,ENERGY &
     &                         ,DDENSITY,DGRAD,DKIN,DGRIDCOORDS &
     &                         ,DGRIDWEIGHTS,DATOMCOORDS,DATOMICGRIDWEIGHTS)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)  :: NPOINT
      INTEGER(4),INTENT(IN)  :: NATOM
      REAL(8)   ,INTENT(IN)  :: DENSITY(NPOINT,2)
      REAL(8)   ,INTENT(IN)  :: GRAD(NPOINT,3,2)
      REAL(8)   ,INTENT(IN)  :: KIN(NPOINT,2)
      REAL(8)   ,INTENT(IN)  :: GRIDCOORDS(NPOINT,3)
      REAL(8)   ,INTENT(IN)  :: GRIDWEIGHTS(NPOINT)
      REAL(8)   ,INTENT(IN)  :: ATOMCOORDS(NATOM,3)
      REAL(8)   ,INTENT(IN)  :: ATOMICGRIDWEIGHTS(NPOINT)
      INTEGER(8),INTENT(IN)  :: ATOMICGRIDSIZES(NATOM)
      REAL(8)   ,INTENT(OUT) :: ENERGY
      REAL(8)   ,INTENT(OUT) :: DDENSITY(NPOINT,2)
      REAL(8)   ,INTENT(OUT) :: DGRAD(NPOINT,3,2)
      REAL(8)   ,INTENT(OUT) :: DKIN(NPOINT,2)
      REAL(8)   ,INTENT(OUT) :: DGRIDCOORDS(NPOINT,3)
      REAL(8)   ,INTENT(OUT) :: DGRIDWEIGHTS(NPOINT)
      REAL(8)   ,INTENT(OUT) :: DATOMCOORDS(NATOM,3)
      REAL(8)   ,INTENT(OUT) :: DATOMICGRIDWEIGHTS(NPOINT)
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      INTEGER(4)             :: STATUS
      CHARACTER(2048)        :: MESSAGE

      IF(.NOT.TINITIALIZED) CALL SKALA$ENSUREINITIALIZED
      CALL PAW_SKALA_EVALUATE(MODEL,DENSITY,GRAD,KIN,GRIDCOORDS,GRIDWEIGHTS &
     &                       ,ATOMCOORDS,ATOMICGRIDWEIGHTS,ATOMICGRIDSIZES &
     &                       ,ENERGY,DDENSITY,DGRAD,DKIN,STATUS,MESSAGE &
     &                       ,DGRIDCOORDS,DGRIDWEIGHTS,DATOMCOORDS &
     &                       ,DATOMICGRIDWEIGHTS)
      IF(STATUS.NE.0) THEN
        CALL ERROR$MSG('SKALA 1.1 EVALUATION FAILED')
        CALL ERROR$CHVAL('DETAIL',TRIM(MESSAGE))
        CALL ERROR$STOP('SKALA$EVALUATE')
      END IF
#ELSE
      CALL ERROR$MSG('CP-PAW WAS BUILT WITHOUT THE SKALA/FTORCH BRIDGE')
      CALL ERROR$STOP('SKALA$EVALUATE')
#ENDIF
      RETURN
      END
