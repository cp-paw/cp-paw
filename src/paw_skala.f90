      SUBROUTINE SKALA$ATOMFORWARD(IAT)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE
      USE PAW_SKALA_PARTITION_MODULE
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_SOURCE_BACK_BATCH &
     &     ,PAW_SKALA_SOURCE_FORWARD_ACTIVE
      USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
      IMPLICIT NONE
      INTEGER,INTENT(IN) :: IAT
      INTEGER :: NPOINT,IP,D,IC,J,JD,NDIMD
      INTEGER :: SOURCE_ROWS(SIZE(SOURCES))
      TYPE(PAW_SKALA_PERIODIC_LAYOUT) :: ENERGY_LAYOUT,SELF_LAYOUT
      REAL(8),ALLOCATABLE :: X(:,:),RHO(:,:),GRAD(:,:,:),TAU(:,:)
      REAL(8),ALLOCATABLE :: ARHO(:,:),AGRAD(:,:,:),ATAU(:,:)
      REAL(8),ALLOCATABLE :: AX(:,:),AW(:),AD(:),DE(:,:),DD(:,:)
      REAL(8) :: AC(1,3),ATOM(1,3),ENERGY,POINT(3),V(5,2),BAR(5,2)
      REAL(8) :: RV(2),GV(3,2),TV(2),DR(3,2),DG(3,3,2),DT(3,2)
      REAL(8) :: PRIM(3),MOVE(3),S,WE,WD,BASEW,DC(3)
      REAL(8) :: ME(3,3),MD(3,3)
#IF DEFINED(CPPVAR_OPENACC)
      REAL(8),ALLOCATABLE :: SOURCE_BAR(:,:,:),SOURCE_VALUE(:,:,:)
      REAL(8) :: SOURCE_CONTRACTION
      INTEGER :: SOURCE_STATUS
#ENDIF
      INTEGER(8) :: SIZES(1)
      INTEGER(8) :: CACHE_AVAILABLE
      LOGICAL :: CACHE_HIT,LAYOUT_READY
      INTEGER :: EMPTYINDEX(0)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      REAL(8) :: T0,T1,TP,TNEXT,TADJOINT(4)
      CALL ACCELPROFILE$NOW(T0)
      TADJOINT=0.D0
#ENDIF
      CALL SKALA_BUILDGRID(IAT)
      NPOINT=SIZE(BLOCK_GRID(IAT)%W)
      NDIMD=SMOOTH_NDIMD
      ALLOCATE(X(NPOINT,3),RHO(NPOINT,2),GRAD(NPOINT,3,2),TAU(NPOINT,2))
      ALLOCATE(ARHO(NPOINT,2),AGRAD(NPOINT,3,2),ATAU(NPOINT,2))
      ALLOCATE(AX(NPOINT,3),AW(NPOINT),AD(NPOINT))
      ATOM=GRID_ATOMS(IAT:IAT,:)
      DO IC=1,3
        X(:,IC)=BLOCK_GRID(IAT)%X(:,IC)+ATOM(1,IC)
      END DO
      BAR=0.D0
      SOURCE_ROWS=0
      CALL TIMING$CLOCKON('SKALA:RECONSTRUCT')
      CALL SKALA_PREPARE_SOURCE_CACHE(IAT,NPOINT,X)
#IF DEFINED(CPPVAR_OPENACC)
      IF(PAW_SKALA_SOURCE_FORWARD_ACTIVE()) THEN
        ALLOCATE(SOURCE_VALUE(5,2,NPOINT),STAT=SOURCE_STATUS)
        IF(SOURCE_STATUS.EQ.0) CALL SKALA_RECONSTRUCT_BATCH(IAT,NPOINT,X,SOURCE_VALUE)
      END IF
#ENDIF
      DO IP=1,NPOINT
        POINT=X(IP,:)
        CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
     &       (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS,NDIMD &
     &       ,SMOOTH_RHO,SMOOTH_GRHO,SMOOTH_TAU,POINT &
     &       ,RV(1:NDIMD),GV(:,1:NDIMD),TV(1:NDIMD))
        DO D=1,2
          RHO(IP,D)=0.5D0*RV(1)
          GRAD(IP,:,D)=0.5D0*GV(:,1)
          TAU(IP,D)=0.5D0*TV(1)
          IF(NDIMD.EQ.2) THEN
            S=MERGE(0.5D0,-0.5D0,D.EQ.1)
            RHO(IP,D)=RHO(IP,D)+S*RV(2)
            GRAD(IP,:,D)=GRAD(IP,:,D)+S*GV(:,2)
            TAU(IP,D)=TAU(IP,D)+S*TV(2)
          END IF
        END DO
        FORWARD_SMOOTH_ELECTRONS=FORWARD_SMOOTH_ELECTRONS &
     &       +BLOCK_GRID(IAT)%W(IP)*SUM(RHO(IP,:))
        FORWARD_SMOOTH_TAU=FORWARD_SMOOTH_TAU &
     &       +BLOCK_GRID(IAT)%W(IP)*SUM(TAU(IP,:))
#IF DEFINED(CPPVAR_OPENACC)
        IF(ALLOCATED(SOURCE_VALUE)) THEN
          V=SOURCE_VALUE(:,:,IP)
        ELSE
#ENDIF
          CALL SKALA_RECONSTRUCT(IAT,IP,POINT,BAR,.FALSE.,V,SOURCE_ROWS)
#IF DEFINED(CPPVAR_OPENACC)
        END IF
#ENDIF
        RHO(IP,:)=RHO(IP,:)+V(1,:)
        GRAD(IP,:,:)=GRAD(IP,:,:)+V(2:4,:)
        TAU(IP,:)=TAU(IP,:)+V(5,:)
        FORWARD_CORRECTION_ELECTRONS=FORWARD_CORRECTION_ELECTRONS &
     &       +BLOCK_GRID(IAT)%W(IP)*SUM(V(1,:))
        FORWARD_CORRECTION_TAU=FORWARD_CORRECTION_TAU &
     &       +BLOCK_GRID(IAT)%W(IP)*SUM(V(5,:))
      END DO
#IF DEFINED(CPPVAR_OPENACC)
      IF(ALLOCATED(SOURCE_VALUE)) DEALLOCATE(SOURCE_VALUE)
#ENDIF
      CALL TIMING$CLOCKOFF('SKALA:RECONSTRUCT')
      SIZES(1)=INT(NPOINT,KIND=8)
      CALL TIMING$CLOCKON('SKALA:MODEL')
      CALL SKALA$EVALUATE(NPOINT,1,RHO,GRAD,TAU,X,BLOCK_GRID(IAT)%W &
     &     ,ATOM,BLOCK_GRID(IAT)%D,SIZES,ENERGY &
     &     ,ARHO,AGRAD,ATAU,AX,AW,AC,AD)
      CALL TIMING$CLOCKOFF('SKALA:MODEL')
      IF(.NOT.IEEE_IS_FINITE(ENERGY).OR.ANY(.NOT.IEEE_IS_FINITE(ARHO)) &
     &   .OR.ANY(.NOT.IEEE_IS_FINITE(AGRAD)).OR.ANY(.NOT.IEEE_IS_FINITE(ATAU)) &
     &   .OR.ANY(.NOT.IEEE_IS_FINITE(AX)).OR.ANY(.NOT.IEEE_IS_FINITE(AW)) &
     &   .OR.ANY(.NOT.IEEE_IS_FINITE(AC)).OR.ANY(.NOT.IEEE_IS_FINITE(AD))) THEN
        CALL ERROR$MSG('NONFINITE SKALA ENERGY OR ADJOINT')
        CALL ERROR$I4VAL('ATOM',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(ALLOCATED(FORWARD_DERIV)) THEN
        CACHE_AVAILABLE=PAW_SKALA_PARTITION_CACHE_LIMIT()
        DO J=1,SIZE(BLOCK_GRID)
          IF(J.EQ.IAT) CYCLE
          CACHE_AVAILABLE=CACHE_AVAILABLE &
     &                   -PAW_SKALA_PARTITION_CACHE_BYTES(BLOCK_GRID(J)%PARTITION)
        END DO
        CALL PAW_SKALA_PARTITION_CACHE_PREPARE(BLOCK_GRID(IAT)%PARTITION &
     &       ,GRID_ATOMS,GRID_CELL,CONFIG_IMAGESHELLS,IAT,X &
     &       ,CONFIG_NEEDSTRESS,MAX(0_8,CACHE_AVAILABLE))
        FORWARD_PARTITION_CACHE(3)=FORWARD_PARTITION_CACHE(3) &
     &       +REAL(PAW_SKALA_PARTITION_CACHE_BYTES(BLOCK_GRID(IAT)%PARTITION),KIND=8)
        LAYOUT_READY=.FALSE.
        ALLOCATE(DE(3,SIZE(GRID_ATOMS,1)),DD(3,1))
        FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+AC(1,:)
        FORWARD_DERIV_MODEL_ATOM(:,IAT)= &
     &      FORWARD_DERIV_MODEL_ATOM(:,IAT)+AC(1,:)
        IF(CONFIG_NEEDSTRESS) THEN
          DO JD=1,3
            FORWARD_STRESS_COORDINATE(:,JD)=FORWARD_STRESS_COORDINATE(:,JD) &
     &                                      +AC(1,:)*ATOM(1,JD)
          END DO
        END IF
      END IF
      CALL TIMING$CLOCKON('SKALA:ADJOINT')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(TP)
#ENDIF
#IF DEFINED(CPPVAR_OPENACC)
      ALLOCATE(SOURCE_BAR(5,2,NPOINT))
      DO IP=1,NPOINT
        SOURCE_BAR(1,:,IP)=ARHO(IP,:)
        SOURCE_BAR(2:4,:,IP)=AGRAD(IP,:,:)
        SOURCE_BAR(5,:,IP)=ATAU(IP,:)
      END DO
      DO J=1,SIZE(SOURCES)
        CALL PAW_SKALA_SOURCE_BACK_BATCH(BLOCK_GRID(IAT)%SOURCE(J),SOURCES(J) &
     &       ,SOURCE_BAR,ALLOCATED(FORWARD_DERIV),CONFIG_NEEDSTRESS &
     &       ,DC,ME,SOURCE_CONTRACTION,SOURCE_ROWS(J))
        FORWARD_SOURCE_CONTRACTION=FORWARD_SOURCE_CONTRACTION+SOURCE_CONTRACTION
        FORWARD_SOURCE_CACHE(1)=FORWARD_SOURCE_CACHE(1)+REAL(SOURCE_ROWS(J),KIND=8)
        FORWARD_SOURCE_CACHE(4)=FORWARD_SOURCE_CACHE(4)+REAL(SOURCE_ROWS(J),KIND=8)
        IF(ALLOCATED(FORWARD_DERIV)) THEN
          FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+DC
          FORWARD_DERIV(:,J)=FORWARD_DERIV(:,J)-DC
          FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)=FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)+DC
          FORWARD_DERIV_LOCAL_PRIMITIVE(:,J)=FORWARD_DERIV_LOCAL_PRIMITIVE(:,J)-DC
          IF(CONFIG_NEEDSTRESS) THEN
            DO JD=1,3
              FORWARD_STRESS_PRIMITIVE(:,JD)=FORWARD_STRESS_PRIMITIVE(:,JD) &
     &                                      +DC*GRID_ATOMS(IAT,JD)-ME(:,JD)
            END DO
          END IF
        END IF
      END DO
      DEALLOCATE(SOURCE_BAR)
#ENDIF
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(TNEXT)
      TADJOINT(1)=TNEXT-TP
#ENDIF
      DO IP=1,NPOINT
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
        CALL ACCELPROFILE$NOW(TP)
#ENDIF
        POINT=X(IP,:)
        BAR(1,:)=ARHO(IP,:)
        BAR(2:4,:)=AGRAD(IP,:,:)
        BAR(5,:)=ATAU(IP,:)
        CALL SKALA_RECONSTRUCT(IAT,IP,POINT,BAR,.TRUE.,V,SOURCE_ROWS)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
        CALL ACCELPROFILE$NOW(TNEXT)
        TADJOINT(1)=TADJOINT(1)+(TNEXT-TP)
        TP=TNEXT
#ENDIF
        IF(.NOT.ALLOCATED(FORWARD_DERIV)) CYCLE
        CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
     &       (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS,NDIMD &
     &       ,SMOOTH_RHO,SMOOTH_GRHO,SMOOTH_TAU,POINT &
     &       ,RV(1:NDIMD),GV(:,1:NDIMD),TV(1:NDIMD) &
     &       ,DR(:,1:NDIMD),DG(:,:,1:NDIMD),DT(:,1:NDIMD))
        PRIM=0.D0
        DO D=1,NDIMD
          S=MERGE(1.D0,-1.D0,D.EQ.1)
          PRIM=PRIM+0.5D0*(ARHO(IP,1)+S*ARHO(IP,2))*DR(:,D) &
     &             +0.5D0*(ATAU(IP,1)+S*ATAU(IP,2))*DT(:,D)
          DO IC=1,3
            PRIM=PRIM+0.5D0*(AGRAD(IP,IC,1)+S*AGRAD(IP,IC,2))*DG(IC,:,D)
          END DO
        END DO
        MOVE=AX(IP,:)+PRIM
        FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+MOVE
        FORWARD_DERIV_LOCAL_GRID(:,IAT)=FORWARD_DERIV_LOCAL_GRID(:,IAT)+AX(IP,:)
        FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)= &
     &      FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)+PRIM
        IF(CONFIG_NEEDSTRESS) THEN
          DO JD=1,3
            FORWARD_STRESS_COORDINATE(:,JD)=FORWARD_STRESS_COORDINATE(:,JD) &
     &                                    +AX(IP,:)*ATOM(1,JD)
            FORWARD_STRESS_PRIMITIVE(:,JD)=FORWARD_STRESS_PRIMITIVE(:,JD) &
     &                                    -PRIM*BLOCK_GRID(IAT)%X(IP,JD)
          END DO
        END IF
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
        CALL ACCELPROFILE$NOW(TNEXT)
        TADJOINT(2)=TADJOINT(2)+(TNEXT-TP)
        TP=TNEXT
#ENDIF
        CALL PAW_SKALA_PARTITION_CACHE_GET(BLOCK_GRID(IAT)%PARTITION &
     &       ,IP,DE,ME,WD,DD,MD,CACHE_HIT)
        IF(CACHE_HIT) THEN
          FORWARD_PARTITION_CACHE(1)=FORWARD_PARTITION_CACHE(1)+1.D0
        ELSE
          FORWARD_PARTITION_CACHE(2)=FORWARD_PARTITION_CACHE(2)+1.D0
          IF(.NOT.LAYOUT_READY) THEN
            CALL PAW_SKALA_PERIODIC_INIT(ENERGY_LAYOUT,SIZE(GRID_ATOMS,1) &
     &                                 ,GRID_ATOMS,GRID_CELL,CONFIG_IMAGESHELLS)
            IF(CONFIG_NEEDSTRESS) CALL PAW_SKALA_PERIODIC_INIT(SELF_LAYOUT,1 &
     &                                 ,ATOM,GRID_CELL,CONFIG_IMAGESHELLS)
            LAYOUT_READY=.TRUE.
          END IF
          CALL PAW_SKALA_PERIODIC_WEIGHT(ENERGY_LAYOUT,IAT,POINT,WE,DE,ME)
          IF(CONFIG_NEEDSTRESS) CALL PAW_SKALA_PERIODIC_WEIGHT(SELF_LAYOUT,1,POINT,WD,DD,MD)
          CALL PAW_SKALA_PARTITION_CACHE_PUT(BLOCK_GRID(IAT)%PARTITION,IP,DE,ME,WD,DD,MD)
        END IF
        BASEW=BLOCK_GRID(IAT)%BASEW(IP)
        DO J=1,SIZE(GRID_ATOMS,1)
          DC=BASEW*AW(IP)*DE(:,J)
          FORWARD_DERIV(:,J)=FORWARD_DERIV(:,J)+DC
          FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)-DC
          FORWARD_DERIV_LOCAL_PARTITION(:,J)=FORWARD_DERIV_LOCAL_PARTITION(:,J)+DC
          FORWARD_DERIV_LOCAL_PARTITION(:,IAT)=FORWARD_DERIV_LOCAL_PARTITION(:,IAT)-DC
        END DO
        IF(CONFIG_NEEDSTRESS) THEN
          DO JD=1,3
            FORWARD_STRESS_PARTITION(:,JD)=FORWARD_STRESS_PARTITION(:,JD) &
     &        +BASEW*AW(IP)*(ME(:,JD)-SUM(DE,DIM=2)*ATOM(1,JD)) &
     &        +BASEW*AD(IP)*PAW_SKALA_PARTITION_TAPER_DERIVATIVE(WD) &
     &                    *(MD(:,JD)-DD(:,1)*ATOM(1,JD))
          END DO
        END IF
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
        CALL ACCELPROFILE$NOW(TNEXT)
        TADJOINT(3)=TADJOINT(3)+(TNEXT-TP)
#ENDIF
      END DO
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(TP)
#ENDIF
      CALL PAW_SKALA_GRID_BACKPROJECT &
     &     (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS,NDIMD &
     &     ,0,NPOINT,EMPTYINDEX,X,ARHO,AGRAD,ATAU &
     &     ,SMOOTH_ADJ_RHO,SMOOTH_ADJ_GRHO,SMOOTH_ADJ_TAU,TGRIDBACKACC)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(TNEXT)
      TADJOINT(4)=TNEXT-TP
#ENDIF
      CALL TIMING$CLOCKOFF('SKALA:ADJOINT')
      FORWARD_ENERGY=FORWARD_ENERGY+ENERGY
      FORWARD_ATOM_ENERGY(IAT)=ENERGY
      FORWARD_ATOM_NPOINT(IAT)=NPOINT
      FORWARD_ELECTRONS=FORWARD_ELECTRONS+SUM(BLOCK_GRID(IAT)%W*SUM(RHO,DIM=2))
      FORWARD_TAU=FORWARD_TAU+SUM(BLOCK_GRID(IAT)%W*SUM(TAU,DIM=2))
      FORWARD_NPOINT=FORWARD_NPOINT+NPOINT
      FORWARD_VOLUME=FORWARD_VOLUME+SUM(BLOCK_GRID(IAT)%W)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(T1)
      CALL ACCELPROFILE$ADD('SKALA_ATOM_COMPOSITE' &
     &     ,INT(NPOINT,KIND=8),INT(IAT,KIND=8),0_8,0_8,0.D0,0.D0,T1-T0)
      CALL ACCELPROFILE$ADD('SKALA_ADJOINT_SOURCE' &
     &     ,INT(NPOINT,KIND=8),INT(IAT,KIND=8),0_8,0_8,0.D0,0.D0,TADJOINT(1))
      IF(ALLOCATED(FORWARD_DERIV)) THEN
        CALL ACCELPROFILE$ADD('SKALA_ADJOINT_INTERPOLATION' &
     &     ,INT(NPOINT,KIND=8),INT(IAT,KIND=8),0_8,0_8,0.D0,0.D0,TADJOINT(2))
        CALL ACCELPROFILE$ADD('SKALA_ADJOINT_PARTITION' &
     &     ,INT(NPOINT,KIND=8),INT(IAT,KIND=8),0_8,0_8,0.D0,0.D0,TADJOINT(3))
      END IF
      CALL ACCELPROFILE$ADD('SKALA_ADJOINT_SCATTER' &
     &     ,INT(NPOINT,KIND=8),INT(IAT,KIND=8),0_8,0_8,0.D0,0.D0,TADJOINT(4))
#ENDIF
      END SUBROUTINE SKALA$ATOMFORWARD

!     ..................................................................

!     ..................................................................
      SUBROUTINE SKALA$FORWARDEND
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE, ONLY: PAW_SKALA_GRID_BACK_END
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) :: NTASKS,THISTASK,NFIL,NAT,I,IDIR,JDIR
      REAL(8) :: RHONORM,GRADNORM,TAUNORM,NETFORCE(3)
      REAL(8) :: PRIMITIVECONTRACTION,CELLVOLUME,VOLUMEERROR
      REAL(8),ALLOCATABLE :: FORCE(:,:)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      REAL(8) :: ACCEL_T0,ACCEL_T1,GRID_BACK_BYTES
#ENDIF

      IF(.NOT.TON) RETURN
      IF(TGRIDBACKACC) THEN
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
        CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF
        CALL PAW_SKALA_GRID_BACK_END(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                              ,SMOOTH_NDIMD,SMOOTH_ADJ_RHO &
     &                              ,SMOOTH_ADJ_GRHO,SMOOTH_ADJ_TAU &
     &                              ,TGRIDBACKACC)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
        CALL ACCELPROFILE$NOW(ACCEL_T1)
        GRID_BACK_BYTES=40.D0*REAL(SMOOTH_NR1,KIND=8) &
     &                         *REAL(SMOOTH_NR2,KIND=8) &
     &                         *REAL(SMOOTH_NR3,KIND=8) &
     &                         *REAL(SMOOTH_NDIMD,KIND=8)
        CALL ACCELPROFILE$ADD('ACC_COPY_SKALA_GRID_BACK_OUT' &
     &      ,INT(SMOOTH_NR1,KIND=8),INT(SMOOTH_NR2,KIND=8) &
     &      ,INT(SMOOTH_NR3,KIND=8),INT(SMOOTH_NDIMD,KIND=8) &
     &      ,0.D0,GRID_BACK_BYTES,ACCEL_T1-ACCEL_T0)
#ENDIF
      END IF
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ENERGY)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SMOOTH_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_CORRECTION_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SMOOTH_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_CORRECTION_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ONECENTER_ADJOINT_NORM2)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ONECENTER_CONTRACTION)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SOURCE_CONTRACTION)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_NPOINT)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_PARTITION_CACHE)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SOURCE_CACHE)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_VOLUME)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ATOM_ENERGY)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ATOM_NPOINT)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_RHO)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_GRHO)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_TAU)
      CALL MPE$QUERY('MONOMER',NTASKS,THISTASK)
      ONECENTER_CONTRACTION=FORWARD_ONECENTER_CONTRACTION
      TONECENTERCONTRACTIONREADY=.TRUE.
      IF(ALLOCATED(FORWARD_DERIV)) THEN
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_MODEL_ATOM)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_LOCAL_GRID)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_LOCAL_PRIMITIVE)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_LOCAL_PARTITION)
        IF(CONFIG_NEEDSTRESS) THEN
          CALL MPE$COMBINE('MONOMER','+',FORWARD_STRESS_WEIGHT)
          CALL MPE$COMBINE('MONOMER','+',FORWARD_STRESS_PRIMITIVE)
          CALL MPE$COMBINE('MONOMER','+',FORWARD_STRESS_COORDINATE)
          CALL MPE$COMBINE('MONOMER','+',FORWARD_STRESS_PARTITION)
          CALL MPE$COMBINE('MONOMER','+',FORWARD_STRESS_BLEND)
        END IF
        NAT=SIZE(FORWARD_DERIV,2)
        IF(THISTASK.EQ.1) THEN
          IF(CONFIG_NEEDSTRESS) THEN
            PRIMITIVECONTRACTION=SUM(SMOOTH_ADJ_RHO*SMOOTH_RHO) &
     &                          +SUM(SMOOTH_ADJ_GRHO*SMOOTH_GRHO) &
     &                          +SUM(SMOOTH_ADJ_TAU*SMOOTH_TAU)
            DO IDIR=1,3
              FORWARD_STRESS_PRIMITIVE(IDIR,IDIR)= &
     &          FORWARD_STRESS_PRIMITIVE(IDIR,IDIR) &
     &         -PRIMITIVECONTRACTION
              DO JDIR=1,3
                FORWARD_STRESS_PRIMITIVE(IDIR,JDIR)= &
     &            FORWARD_STRESS_PRIMITIVE(IDIR,JDIR) &
     &           -SUM(SMOOTH_ADJ_GRHO(:,:,:,JDIR,:) &
     &               *SMOOTH_GRHO(:,:,:,IDIR,:))
              END DO
            END DO
          END IF
        END IF
        CALL MPE$BROADCAST('MONOMER',1,FORWARD_DERIV)
        IF(CONFIG_NEEDFORCE) THEN
          ALLOCATE(FORCE(3,NAT))
          CALL ATOMLIST$GETR8A('FORCE',0,3*NAT,FORCE)
          FORCE=FORCE-FORWARD_DERIV
          CALL ATOMLIST$SETR8A('FORCE',0,3*NAT,FORCE)
          DEALLOCATE(FORCE)
        END IF
        IF(CONFIG_NEEDSTRESS) THEN
          CALL MPE$BROADCAST('MONOMER',1,FORWARD_STRESS_WEIGHT)
          CALL MPE$BROADCAST('MONOMER',1,FORWARD_STRESS_PRIMITIVE)
          CALL MPE$BROADCAST('MONOMER',1,FORWARD_STRESS_COORDINATE)
          CALL MPE$BROADCAST('MONOMER',1,FORWARD_STRESS_PARTITION)
          CALL MPE$BROADCAST('MONOMER',1,FORWARD_STRESS_BLEND)
          FORWARD_STRESS=FORWARD_STRESS_WEIGHT+FORWARD_STRESS_PRIMITIVE &
     &                  +FORWARD_STRESS_COORDINATE &
     &                  +FORWARD_STRESS_PARTITION+FORWARD_STRESS_BLEND
          TSTRESSREADY=.TRUE.
        END IF
      END IF
      IF(SMOOTH_DVOL.LE.0.D0) THEN
        CALL ERROR$MSG('SKALA SMOOTH GRID VOLUME IS INVALID')
        CALL ERROR$STOP('SKALA$FORWARDEND')
      END IF
      SMOOTH_ADJ_RHO=SMOOTH_ADJ_RHO/SMOOTH_DVOL
      SMOOTH_ADJ_GRHO=SMOOTH_ADJ_GRHO/SMOOTH_DVOL
      SMOOTH_ADJ_TAU=SMOOTH_ADJ_TAU/SMOOTH_DVOL
      RHONORM=SQRT(SUM(SMOOTH_ADJ_RHO**2))
      GRADNORM=SQRT(SUM(SMOOTH_ADJ_GRHO**2))
      TAUNORM=SQRT(SUM(SMOOTH_ADJ_TAU**2))
      IF(CONFIG_APPLY) THEN
        CALL ENERGYLIST$ADD('TOTAL ENERGY',FORWARD_ENERGY)
        CALL ENERGYLIST$ADD('AE  EXCHANGE-CORRELATION',FORWARD_ENERGY)
        CALL ENERGYLIST$ADD('PS  EXCHANGE-CORRELATION',FORWARD_ENERGY)
      END IF
      IF(THISTASK.EQ.1.AND.(CONFIG_CHECK.OR..NOT.TFORWARDREPORTED)) THEN
        CALL FILEHANDLER$UNIT('PROT',NFIL)
        WRITE(NFIL,FMT='(/"SKALA COMPLETE PAW ATOM BLOCKS"/30("="))')
        WRITE(NFIL,FMT='("ATOM-GRID ROWS",T34,I12)')FORWARD_NPOINT
        IF(CONFIG_CHECK) THEN
          WRITE(NFIL,'(A,T34,I18)')'PARTITION CACHE HITS',INT(FORWARD_PARTITION_CACHE(1),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'PARTITION CACHE MISSES',INT(FORWARD_PARTITION_CACHE(2),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'PARTITION CACHE BYTES ALL RANKS',INT(FORWARD_PARTITION_CACHE(3),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'SOURCE CACHE HITS',INT(FORWARD_SOURCE_CACHE(1),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'SOURCE CACHE MISSES',INT(FORWARD_SOURCE_CACHE(2),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'SOURCE CACHE BYTES ALL RANKS',INT(FORWARD_SOURCE_CACHE(3),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'SOURCE GPU REVERSE ROWS',INT(FORWARD_SOURCE_CACHE(4),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'SOURCE GPU FORWARD ROWS',INT(FORWARD_SOURCE_CACHE(5),KIND=8)
          WRITE(NFIL,'(A,T34,I18)')'SOURCE GPU REUSED ROWS',INT(FORWARD_SOURCE_CACHE(6),KIND=8)
        END IF
        WRITE(NFIL,FMT='("SOURCE RECONSTRUCTION",T34,A)')'ALL ATOMS AND IMAGES'
        WRITE(NFIL,FMT='("DESCRIPTOR WINDOW",T34,A)')'SELF IMAGES ONLY'
        WRITE(NFIL,FMT='("PERIODIC PARTITION",T34,A)')'COMPACT PERIODIZED BECKE'
        CELLVOLUME=SMOOTH_DVOL*REAL(SMOOTH_NR1,KIND=8) &
     &                       *REAL(SMOOTH_NR2,KIND=8)*REAL(SMOOTH_NR3,KIND=8)
        VOLUMEERROR=(FORWARD_VOLUME-CELLVOLUME)/CELLVOLUME
        WRITE(NFIL,FMT='("PARTITION VOLUME",T34,ES24.14)')FORWARD_VOLUME
        WRITE(NFIL,FMT='("EXACT CELL VOLUME",T34,ES24.14)')CELLVOLUME
        WRITE(NFIL,FMT='("PARTITION VOLUME RELATIVE ERROR",T34,ES24.14)')VOLUMEERROR
        IF(ABS(VOLUMEERROR).GT.1.D-4) THEN
          WRITE(NFIL,FMT='(A)')'WARNING: SKALA PERIODIC QUADRATURE IS NOT CONVERGED'
          WRITE(NFIL,FMT='(A)')'CONVERGE IMAGESHELLS AND RADIAL/ANGULAR GRID INDEPENDENTLY'
        END IF
        WRITE(NFIL,FMT='("SMOOTH ELECTRONS",T34,ES24.14)') &
     &       FORWARD_SMOOTH_ELECTRONS
        WRITE(NFIL,FMT='("AE-PS ELECTRONS",T34,ES24.14)') &
     &       FORWARD_CORRECTION_ELECTRONS
        WRITE(NFIL,FMT='("COMPOSITE ELECTRONS",T34,ES24.14)')FORWARD_ELECTRONS
        IF(CONFIG_CHECK.AND.TELECTRONREFERENCE) THEN
          WRITE(NFIL,'(A,T34,ES24.14)')'PAW ALL ELECTRON TRACE',ELECTRON_REFERENCE
          WRITE(NFIL,'(A,T34,ES24.14)')'COMPOSITE MINUS TRACE' &
     &                             ,FORWARD_ELECTRONS-ELECTRON_REFERENCE
        END IF
        WRITE(NFIL,FMT='("SMOOTH POSITIVE TAU",T34,ES24.14)')FORWARD_SMOOTH_TAU
        WRITE(NFIL,FMT='("AE-PS POSITIVE TAU",T34,ES24.14)') &
     &       FORWARD_CORRECTION_TAU
        WRITE(NFIL,FMT='("COMPOSITE POSITIVE TAU",T34,ES24.14)')FORWARD_TAU
        WRITE(NFIL,FMT='("MODEL XC ENERGY",T34,ES24.14)')FORWARD_ENERGY
        IF(CONFIG_CHECK) THEN
          DO I=1,SIZE(FORWARD_ATOM_ENERGY)
            WRITE(NFIL,FMT='("ATOM BLOCK",I6," ROWS",I10 &
     &                    ," ENERGY",ES24.14)') &
     &           I,FORWARD_ATOM_NPOINT(I),FORWARD_ATOM_ENERGY(I)
          END DO
        END IF
        WRITE(NFIL,FMT='("SMOOTH GRID DVOL",T34,ES24.14)')SMOOTH_DVOL
        WRITE(NFIL,FMT='("SMOOTH RHO ADJOINT L2",T34,ES24.14)')RHONORM
