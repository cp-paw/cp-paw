      SUBROUTINE SKALA$FORWARDBEGIN
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      INTEGER(4) :: NAT
      IF(.NOT.TON) RETURN
      IF(.NOT.TSMOOTHREADY) THEN
        CALL ERROR$MSG('SKALA SMOOTH FIELDS ARE NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$FORWARDBEGIN')
      END IF
      FORWARD_ENERGY=0.D0
      FORWARD_ELECTRONS=0.D0
      FORWARD_TAU=0.D0
      FORWARD_SMOOTH_ELECTRONS=0.D0
      FORWARD_CORRECTION_ELECTRONS=0.D0
      FORWARD_SMOOTH_TAU=0.D0
      FORWARD_CORRECTION_TAU=0.D0
      FORWARD_ONECENTER_ADJOINT_NORM2=0.D0
      FORWARD_ONECENTER_CONTRACTION=0.D0
      FORWARD_NPOINT=0
      CALL ATOMLIST$NATOM(NAT)
      IF(ALLOCATED(FORWARD_ATOM_ENERGY)) DEALLOCATE(FORWARD_ATOM_ENERGY)
      IF(ALLOCATED(FORWARD_ATOM_NPOINT)) DEALLOCATE(FORWARD_ATOM_NPOINT)
      ALLOCATE(FORWARD_ATOM_ENERGY(NAT),FORWARD_ATOM_NPOINT(NAT))
      FORWARD_ATOM_ENERGY=0.D0
      FORWARD_ATOM_NPOINT=0
      IF(ALLOCATED(SMOOTH_ADJ_RHO)) DEALLOCATE(SMOOTH_ADJ_RHO)
      IF(ALLOCATED(SMOOTH_ADJ_GRHO)) DEALLOCATE(SMOOTH_ADJ_GRHO)
      IF(ALLOCATED(SMOOTH_ADJ_TAU)) DEALLOCATE(SMOOTH_ADJ_TAU)
      ALLOCATE(SMOOTH_ADJ_RHO(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                       ,SMOOTH_NDIMD))
      ALLOCATE(SMOOTH_ADJ_GRHO(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,3 &
     &                        ,SMOOTH_NDIMD))
      ALLOCATE(SMOOTH_ADJ_TAU(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                       ,SMOOTH_NDIMD))
      SMOOTH_ADJ_RHO=0.D0
      SMOOTH_ADJ_GRHO=0.D0
      SMOOTH_ADJ_TAU=0.D0
      IF(ALLOCATED(FORWARD_DERIV)) DEALLOCATE(FORWARD_DERIV)
      IF(ALLOCATED(FORWARD_DERIV_MODEL_ATOM)) &
     &  DEALLOCATE(FORWARD_DERIV_MODEL_ATOM)
      IF(ALLOCATED(FORWARD_DERIV_LOCAL_GRID)) &
     &  DEALLOCATE(FORWARD_DERIV_LOCAL_GRID)
      IF(ALLOCATED(FORWARD_DERIV_LOCAL_PRIMITIVE)) &
     &  DEALLOCATE(FORWARD_DERIV_LOCAL_PRIMITIVE)
      IF(ALLOCATED(FORWARD_DERIV_LOCAL_PARTITION)) &
     &  DEALLOCATE(FORWARD_DERIV_LOCAL_PARTITION)
      IF(ALLOCATED(FORWARD_DERIV_SMOOTH_PARTITION)) &
     &  DEALLOCATE(FORWARD_DERIV_SMOOTH_PARTITION)
      IF(ALLOCATED(FORWARD_DERIV_RADIAL_BLEND)) &
     &  DEALLOCATE(FORWARD_DERIV_RADIAL_BLEND)
      IF(ALLOCATED(SMOOTH_PARTITION_SENSITIVITY)) &
     &  DEALLOCATE(SMOOTH_PARTITION_SENSITIVITY)
      IF(CONFIG_APPLY.AND.CONFIG_NEEDFORCE) THEN
        ALLOCATE(FORWARD_DERIV(3,NAT))
        ALLOCATE(FORWARD_DERIV_MODEL_ATOM(3,NAT))
        ALLOCATE(FORWARD_DERIV_LOCAL_GRID(3,NAT))
        ALLOCATE(FORWARD_DERIV_LOCAL_PRIMITIVE(3,NAT))
        ALLOCATE(FORWARD_DERIV_LOCAL_PARTITION(3,NAT))
        ALLOCATE(FORWARD_DERIV_SMOOTH_PARTITION(3,NAT))
        ALLOCATE(FORWARD_DERIV_RADIAL_BLEND(3,NAT))
        ALLOCATE(SMOOTH_PARTITION_SENSITIVITY &
     &          (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,NAT))
        FORWARD_DERIV=0.D0
        FORWARD_DERIV_MODEL_ATOM=0.D0
        FORWARD_DERIV_LOCAL_GRID=0.D0
        FORWARD_DERIV_LOCAL_PRIMITIVE=0.D0
        FORWARD_DERIV_LOCAL_PARTITION=0.D0
        FORWARD_DERIV_SMOOTH_PARTITION=0.D0
        FORWARD_DERIV_RADIAL_BLEND=0.D0
        SMOOTH_PARTITION_SENSITIVITY=0.D0
      END IF
      TTAUCONTRACTIONREADY=.FALSE.
      SMOOTH_TAU_CONTRACTION=0.D0
      TSCALARCONTRACTIONREADY=.FALSE.
      SMOOTH_SCALAR_CONTRACTION=0.D0
      TONECENTERCONTRACTIONREADY=.FALSE.
      ONECENTER_CONTRACTION=0.D0
      CALL SKALA_BUILDPARTITIONCACHE
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA_BUILDPARTITIONCACHE
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE, ONLY: PAW_SKALA_SMOOTH_PARTITION &
     &                                ,PAW_SKALA_INVERSE3 &
     &                                ,PAW_SKALA_LOCAL_GRID_SIZE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) :: NAT,I1,I2,I3,NTASKS,THISTASK
      INTEGER(4) :: I,J,K,L,NANG,NLOCAL
      REAL(8),PARAMETER :: CLASS_TOL=1.D-10
      REAL(8) :: POINT(3),AINV(3,3),SHIFT(3),DELTA(3)
      LOGICAL(4) :: TEQUIVALENT,TFOUND
      REAL(8),ALLOCATABLE :: ATOMCOORD(:,:),ATOMCOORD3(:,:),PARTITION(:)
      REAL(8),ALLOCATABLE :: FRACTIONAL(:,:)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      REAL(8) :: ACCEL_T0,ACCEL_T1
#ENDIF

#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF
      CALL TIMING$CLOCKON('SKALA:PARTITION')
      CALL ATOMLIST$NATOM(NAT)
      ALLOCATE(ATOMCOORD(NAT,3),ATOMCOORD3(3,NAT),PARTITION(NAT))
      CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,ATOMCOORD3)
      ATOMCOORD=TRANSPOSE(ATOMCOORD3)
      CALL PAW_SKALA_INVERSE3(SMOOTH_RBAS,AINV)
      ALLOCATE(FRACTIONAL(NAT,3))
      DO I=1,NAT
        FRACTIONAL(I,:)=MODULO(MATMUL(AINV,ATOMCOORD(I,:)),1.D0)
      END DO
      IF(ALLOCATED(SMOOTH_ATOM_CLASS)) DEALLOCATE(SMOOTH_ATOM_CLASS)
      ALLOCATE(SMOOTH_ATOM_CLASS(NAT))
      SMOOTH_ATOM_CLASS=0
      SMOOTH_PARTITION_NCLASS=0
      DO I=1,NAT
        DO J=1,I-1
          SHIFT=FRACTIONAL(I,:)-FRACTIONAL(J,:)
          TEQUIVALENT=.TRUE.
          DO K=1,NAT
            TFOUND=.FALSE.
            DO L=1,NAT
              DELTA=FRACTIONAL(K,:)+SHIFT-FRACTIONAL(L,:)
              DELTA=DELTA-ANINT(DELTA)
              IF(MAXVAL(ABS(DELTA)).LE.CLASS_TOL) THEN
                TFOUND=.TRUE.
                EXIT
              END IF
            END DO
            IF(.NOT.TFOUND) THEN
              TEQUIVALENT=.FALSE.
              EXIT
            END IF
          END DO
          IF(TEQUIVALENT) THEN
            SMOOTH_ATOM_CLASS(I)=SMOOTH_ATOM_CLASS(J)
            EXIT
          END IF
        END DO
        IF(SMOOTH_ATOM_CLASS(I).EQ.0) THEN
          SMOOTH_PARTITION_NCLASS=SMOOTH_PARTITION_NCLASS+1
          SMOOTH_ATOM_CLASS(I)=SMOOTH_PARTITION_NCLASS
        END IF
      END DO
      CALL PAW_SKALA_LOCAL_GRID_SIZE(LOCAL_NRADIAL,LOCAL_LEBEDEV_L &
     &                              ,NANG,NLOCAL)
      IF(ALLOCATED(LOCAL_PARTITION_READY)) DEALLOCATE(LOCAL_PARTITION_READY)
      IF(ALLOCATED(LOCAL_PARTITION_RCUT)) DEALLOCATE(LOCAL_PARTITION_RCUT)
      IF(ALLOCATED(LOCAL_PARTITION_CACHE)) DEALLOCATE(LOCAL_PARTITION_CACHE)
      ALLOCATE(LOCAL_PARTITION_READY(NAT),LOCAL_PARTITION_RCUT(NAT))
      ALLOCATE(LOCAL_PARTITION_CACHE(NLOCAL,NAT))
      LOCAL_PARTITION_READY=.FALSE.
      LOCAL_PARTITION_RCUT=0.D0
      IF(ALLOCATED(SMOOTH_PARTITION)) DEALLOCATE(SMOOTH_PARTITION)
      ALLOCATE(SMOOTH_PARTITION(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,NAT))
      SMOOTH_PARTITION=0.D0
      CALL MPE$QUERY('MONOMER',NTASKS,THISTASK)
      IF(THISTASK.EQ.1) THEN
        DO I3=1,SMOOTH_NR3
          DO I2=1,SMOOTH_NR2
            DO I1=1,SMOOTH_NR1
              POINT=MATMUL(SMOOTH_RBAS &
     &              ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &                ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &                ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
              CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                        ,SMOOTH_RBAS,PARTITION)
              SMOOTH_PARTITION(I1,I2,I3,:)=PARTITION
            END DO
          END DO
        END DO
      END IF
      CALL MPE$BROADCAST('MONOMER',1,SMOOTH_PARTITION)
      DEALLOCATE(ATOMCOORD,ATOMCOORD3,PARTITION,FRACTIONAL)
      CALL TIMING$CLOCKOFF('SKALA:PARTITION')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T1)
      CALL ACCELPROFILE$ADD('SKALA_PARTITION' &
     &    ,INT(SMOOTH_NR1*SMOOTH_NR2*SMOOTH_NR3,KIND=8),INT(NAT,KIND=8) &
     &    ,0_8,0_8,0.D0,0.D0,ACCEL_T1-ACCEL_T0)
#ENDIF
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$ATOMFORWARD(IAT,GID,NR,LNX,LOX,LMNX,NDIMD &
     &                            ,DENMAT,AEPHI,PSPHI,AECORE,PSCORE,RCUT &
     &                            ,DHSKALA)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE, ONLY: PAW_SKALA_SMOOTH_PARTITION &
     &                                ,PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES &
     &                                ,PAW_SKALA_NEAREST_IMAGE &
     &                                ,PAW_SKALA_INVERSE3 &
     &                                ,PAW_SKALA_PARTITION_TAPER &
     &                                ,PAW_SKALA_PARTITION_TAPER_DERIVATIVE &
     &                                ,PAW_SKALA_RADIAL_BLEND &
     &                                ,PAW_SKALA_RADIAL_BLEND_DERIVATIVE &
     &                                ,PAW_SKALA_LOCAL_GRID_SIZE &
     &                                ,PAW_SKALA_LOCAL_GRID &
     &                                ,PAW_SKALA_GRID_INTERPOLATE &
     &                                ,PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
     &                                ,PAW_SKALA_GRID_PRIMITIVES_ADJOINT
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_ONECENTER_POINTS &
     &                                      ,PAW_SKALA_ONECENTER_ADJOINT_POINTS
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: IAT,GID,NR,LNX,LOX(LNX),LMNX,NDIMD
      COMPLEX(8),INTENT(IN) :: DENMAT(LMNX,LMNX,NDIMD)
      REAL(8),INTENT(IN) :: AEPHI(NR,LNX),PSPHI(NR,LNX)
      REAL(8),INTENT(IN) :: AECORE(NR),PSCORE(NR),RCUT
      COMPLEX(8),INTENT(OUT) :: DHSKALA(LMNX,LMNX,NDIMD)
      REAL(8),PARAMETER :: PARTITION_EPS=1.D-12
      INTEGER(4) :: NAT,NPOINT,NLOCAL,NANG,I1,I2,I3,IP,IDIM,ICART,ILOC
      INTEGER(4) :: NGRID,NSMOOTH,ISMOOTH,IWORK,J,ISOURCE
      INTEGER(8) :: ATOMICGRIDSIZES(1)
      REAL(8) :: MODELATOM(1,3),POINT(3),IMAGE(3),RELATIVE(3),DISTANCE
      REAL(8) :: CELLVOL,DVOL,FACTOR,ENERGY
      REAL(8) :: CELL_INVERSE(3,3)
      REAL(8) :: PARTWEIGHT,BLEND,SMOOTHSCALE,BLENDDERIV
      REAL(8) :: RHOCOMP(2),TAUCOMP(2),GRADCOMP(3,2)
      REAL(8) :: DRHOCOMP(3,2),DTAUCOMP(3,2),DGRADCOMP(3,3,2)
      REAL(8) :: ADJRHO(2),ADJTAU(2),ADJGRAD(3,2)
      REAL(8) :: MOVINGDERIV(3),PRIMITIVEDERIV(3),WEIGHTSENSITIVITY
      REAL(8) :: BLENDSENSITIVITY
      REAL(8),ALLOCATABLE :: ATOMCOORD(:,:),ATOMCOORD3(:,:),PARTITION(:)
      REAL(8),ALLOCATABLE :: DPARTITION_DATOM(:,:,:)
      REAL(8),ALLOCATABLE :: DPARTITION_DPOINT(:,:)
      REAL(8),ALLOCATABLE :: LOCALCOORD(:,:),LOCALWEIGHT(:)
      REAL(8),ALLOCATABLE :: LOCALPARTWEIGHT(:)
      INTEGER(4),ALLOCATABLE :: SMOOTHINDEX(:)
      REAL(8),ALLOCATABLE :: SMOOTHREL(:,:)
      REAL(8),ALLOCATABLE :: RELCOORD(:,:),GRIDCOORDS(:,:),GRIDWEIGHTS(:)
      REAL(8),ALLOCATABLE :: ATOMICGRIDWEIGHTS(:)
      REAL(8),ALLOCATABLE :: DENSITY(:,:),GRAD(:,:,:),KIN(:,:)
      REAL(8),ALLOCATABLE :: AERHO(:,:),PSRHO(:,:),AETAU(:,:),PSTAU(:,:)
      REAL(8),ALLOCATABLE :: AEGRAD(:,:,:),PSGRAD(:,:,:)
      REAL(8),ALLOCATABLE :: DDENSITY(:,:),DGRAD(:,:,:),DKIN(:,:)
      REAL(8),ALLOCATABLE :: DGRIDCOORDS(:,:),DGRIDWEIGHTS(:)
      REAL(8),ALLOCATABLE :: DATOMCOORDS(:,:),DATOMICGRIDWEIGHTS(:)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      REAL(8) :: ACCEL_T0,ACCEL_T1
#ENDIF

      DHSKALA=CMPLX(0.D0,0.D0,KIND=8)
      IF(.NOT.TON) RETURN
      IF(.NOT.TSMOOTHREADY) THEN
        CALL ERROR$MSG('SKALA SMOOTH FIELDS ARE NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(NDIMD.NE.SMOOTH_NDIMD) THEN
        CALL ERROR$MSG('SKALA SMOOTH AND ONE-CENTER SPINS DIFFER')
        CALL ERROR$I4VAL('SMOOTH NDIMD',SMOOTH_NDIMD)
        CALL ERROR$I4VAL('ONE-CENTER NDIMD',NDIMD)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(.NOT.ALLOCATED(SMOOTH_PARTITION)) THEN
        CALL ERROR$MSG('SKALA SMOOTH PARTITION CACHE IS NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(ALLOCATED(FORWARD_DERIV).AND.CONFIG_INTERPOLATEPARTITION) THEN
        CALL ERROR$MSG('SKALA FORCES REQUIRE THE EXACT PARTITION')
        CALL ERROR$MSG('SET INTERPOLATEPARTITION=F FOR FORCE CALCULATIONS')
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF
      CALL TIMING$CLOCKON('SKALA:ATOMGRID')
      CALL ATOMLIST$NATOM(NAT)
      IF(IAT.LT.1.OR.IAT.GT.NAT) THEN
        CALL ERROR$MSG('INVALID ATOM INDEX FOR SKALA FORWARD EVALUATION')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      ALLOCATE(ATOMCOORD(NAT,3),ATOMCOORD3(3,NAT))
      IF(.NOT.CONFIG_INTERPOLATEPARTITION) ALLOCATE(PARTITION(NAT))
      IF(ALLOCATED(FORWARD_DERIV)) THEN
        ALLOCATE(DPARTITION_DATOM(3,NAT,NAT))
        ALLOCATE(DPARTITION_DPOINT(3,NAT))
      END IF
      CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,ATOMCOORD3)
      ATOMCOORD=TRANSPOSE(ATOMCOORD3)

      CELLVOL=ABS(SMOOTH_RBAS(1,1)*(SMOOTH_RBAS(2,2)*SMOOTH_RBAS(3,3) &
     &                              -SMOOTH_RBAS(2,3)*SMOOTH_RBAS(3,2)) &
     &           -SMOOTH_RBAS(1,2)*(SMOOTH_RBAS(2,1)*SMOOTH_RBAS(3,3) &
     &                              -SMOOTH_RBAS(2,3)*SMOOTH_RBAS(3,1)) &
     &           +SMOOTH_RBAS(1,3)*(SMOOTH_RBAS(2,1)*SMOOTH_RBAS(3,2) &
     &                              -SMOOTH_RBAS(2,2)*SMOOTH_RBAS(3,1)))
      DVOL=CELLVOL/REAL(SMOOTH_NR1*SMOOTH_NR2*SMOOTH_NR3,KIND=8)
      CALL PAW_SKALA_INVERSE3(SMOOTH_RBAS,CELL_INVERSE)
      CALL PAW_SKALA_LOCAL_GRID_SIZE(LOCAL_NRADIAL,LOCAL_LEBEDEV_L &
     &                              ,NANG,NLOCAL)
      ALLOCATE(LOCALCOORD(NLOCAL,3),LOCALWEIGHT(NLOCAL))
      ALLOCATE(LOCALPARTWEIGHT(NLOCAL))
      CALL PAW_SKALA_LOCAL_GRID(LOCAL_NRADIAL,RCUT,LOCAL_LEBEDEV_L &
     &                          ,NLOCAL,LOCALCOORD,LOCALWEIGHT)
      ISOURCE=0
      IF(.NOT.CONFIG_INTERPOLATEPARTITION) THEN
        DO J=1,NAT
          IF(.NOT.LOCAL_PARTITION_READY(J)) CYCLE
          IF(SMOOTH_ATOM_CLASS(J).NE.SMOOTH_ATOM_CLASS(IAT)) CYCLE
          IF(ABS(LOCAL_PARTITION_RCUT(J)-RCUT) &
     &       .GT.1.D-12*MAX(1.D0,ABS(RCUT))) CYCLE
          ISOURCE=J
          EXIT
        END DO
      END IF
      IF(ISOURCE.GT.0) THEN
        LOCALPARTWEIGHT=LOCAL_PARTITION_CACHE(:,ISOURCE)
      ELSE
        DO ILOC=1,NLOCAL
          POINT=ATOMCOORD(IAT,:)+LOCALCOORD(ILOC,:)
          IF(CONFIG_INTERPOLATEPARTITION) THEN
          CALL PAW_SKALA_GRID_INTERPOLATE &
     &         (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS &
     &         ,SMOOTH_PARTITION(:,:,:,IAT),POINT &
     &         ,LOCALPARTWEIGHT(ILOC))
          LOCALPARTWEIGHT(ILOC)=MAX(0.D0,MIN(1.D0 &
     &                                    ,LOCALPARTWEIGHT(ILOC)))
          ELSE
            CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                    ,SMOOTH_RBAS,PARTITION)
            LOCALPARTWEIGHT(ILOC)=PARTITION(IAT)
          END IF
        END DO
      END IF
      IF(.NOT.CONFIG_INTERPOLATEPARTITION) THEN
        LOCAL_PARTITION_CACHE(:,IAT)=LOCALPARTWEIGHT
        LOCAL_PARTITION_RCUT(IAT)=RCUT
        LOCAL_PARTITION_READY(IAT)=.TRUE.
      END IF
      NGRID=SMOOTH_NR1*SMOOTH_NR2*SMOOTH_NR3
      ALLOCATE(SMOOTHINDEX(NGRID),SMOOTHREL(NGRID,3))
      NSMOOTH=0
      DO I3=1,SMOOTH_NR3
        DO I2=1,SMOOTH_NR2
          DO I1=1,SMOOTH_NR1
            POINT=MATMUL(SMOOTH_RBAS &
     &                  ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &                    ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &                    ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
            PARTWEIGHT=SMOOTH_PARTITION(I1,I2,I3,IAT)
            IF(PARTWEIGHT.LE.PARTITION_EPS) CYCLE
            CALL PAW_SKALA_NEAREST_IMAGE(POINT,ATOMCOORD(IAT,:) &
     &                                   ,SMOOTH_RBAS,IMAGE,DISTANCE &
     &                                   ,CELL_INVERSE)
            SMOOTHSCALE=1.D0-PAW_SKALA_RADIAL_BLEND(DISTANCE,RCUT)
            IF(SMOOTHSCALE.LE.PARTITION_EPS) CYCLE
            NSMOOTH=NSMOOTH+1
            SMOOTHINDEX(NSMOOTH)=I1+SMOOTH_NR1 &
     &                   *((I2-1)+SMOOTH_NR2*(I3-1))
            SMOOTHREL(NSMOOTH,:)=POINT-IMAGE
          END DO
        END DO
      END DO
      NPOINT=NSMOOTH
      DO ILOC=1,NLOCAL
        DISTANCE=SQRT(SUM(LOCALCOORD(ILOC,:)**2))
        BLEND=PAW_SKALA_RADIAL_BLEND(DISTANCE,RCUT)
        IF(LOCALPARTWEIGHT(ILOC).GT.PARTITION_EPS.AND.BLEND.GT.0.D0) &
     &    NPOINT=NPOINT+1
      END DO
      IF(NPOINT.EQ.0) THEN
        CALL ERROR$MSG('SKALA ATOM BLOCK HAS NO GRID POINTS')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF

      ALLOCATE(RELCOORD(NPOINT,3),GRIDCOORDS(NPOINT,3))
      ALLOCATE(GRIDWEIGHTS(NPOINT),ATOMICGRIDWEIGHTS(NPOINT))
      ALLOCATE(DENSITY(NPOINT,2),GRAD(NPOINT,3,2),KIN(NPOINT,2))
      IP=0
      DO ISMOOTH=1,NSMOOTH
            IWORK=SMOOTHINDEX(ISMOOTH)-1
            I1=MOD(IWORK,SMOOTH_NR1)+1
            IWORK=IWORK/SMOOTH_NR1
            I2=MOD(IWORK,SMOOTH_NR2)+1
            I3=IWORK/SMOOTH_NR2+1
            POINT=MATMUL(SMOOTH_RBAS &
     &            ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &              ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &              ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
            IP=IP+1
            RELATIVE=SMOOTHREL(ISMOOTH,:)
            RELCOORD(IP,:)=RELATIVE
            GRIDCOORDS(IP,:)=POINT
            PARTWEIGHT=SMOOTH_PARTITION(I1,I2,I3,IAT)
            DISTANCE=SQRT(SUM(RELATIVE**2))
            SMOOTHSCALE=1.D0-PAW_SKALA_RADIAL_BLEND(DISTANCE,RCUT)
            GRIDWEIGHTS(IP)=DVOL*PARTWEIGHT*SMOOTHSCALE
            ATOMICGRIDWEIGHTS(IP)=DVOL &
     &          *PAW_SKALA_PARTITION_TAPER(PARTWEIGHT)*SMOOTHSCALE
            IF(NDIMD.EQ.1) THEN
              DENSITY(IP,:)=0.5D0*SMOOTH_RHO(I1,I2,I3,1)
              KIN(IP,:)=0.5D0*SMOOTH_TAU(I1,I2,I3,1)
              DO ICART=1,3
                GRAD(IP,ICART,:)=0.5D0*SMOOTH_GRHO(I1,I2,I3,ICART,1)
              END DO
            ELSE
              DO IDIM=1,2
                FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
                DENSITY(IP,IDIM)=0.5D0*(SMOOTH_RHO(I1,I2,I3,1) &
     &                                      +FACTOR*SMOOTH_RHO(I1,I2,I3,2))
                KIN(IP,IDIM)=0.5D0*(SMOOTH_TAU(I1,I2,I3,1) &
     &                                      +FACTOR*SMOOTH_TAU(I1,I2,I3,2))
                DO ICART=1,3
                  GRAD(IP,ICART,IDIM)=0.5D0 &
     &                         *(SMOOTH_GRHO(I1,I2,I3,ICART,1) &
     &                    +FACTOR*SMOOTH_GRHO(I1,I2,I3,ICART,2))
                END DO
              END DO
            END IF
      END DO

      DO ILOC=1,NLOCAL
        RELATIVE=LOCALCOORD(ILOC,:)
        POINT=ATOMCOORD(IAT,:)+RELATIVE
        PARTWEIGHT=LOCALPARTWEIGHT(ILOC)
        DISTANCE=SQRT(SUM(RELATIVE**2))
        BLEND=PAW_SKALA_RADIAL_BLEND(DISTANCE,RCUT)
        IF(PARTWEIGHT.LE.PARTITION_EPS.OR.BLEND.LE.0.D0) CYCLE
        IP=IP+1
        RELCOORD(IP,:)=RELATIVE
        GRIDCOORDS(IP,:)=POINT
        GRIDWEIGHTS(IP)=LOCALWEIGHT(ILOC)*PARTWEIGHT*BLEND
        ATOMICGRIDWEIGHTS(IP)=LOCALWEIGHT(ILOC) &
     &        *PAW_SKALA_PARTITION_TAPER(PARTWEIGHT)*BLEND
        CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
     &       (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS,NDIMD &
     &       ,SMOOTH_RHO,SMOOTH_GRHO,SMOOTH_TAU,POINT &
     &       ,RHOCOMP(1:NDIMD),GRADCOMP(:,1:NDIMD),TAUCOMP(1:NDIMD))
        IF(NDIMD.EQ.1) THEN
          DENSITY(IP,:)=0.5D0*RHOCOMP(1)
          KIN(IP,:)=0.5D0*TAUCOMP(1)
          DO ICART=1,3
            GRAD(IP,ICART,:)=0.5D0*GRADCOMP(ICART,1)
          END DO
        ELSE
          DO IDIM=1,2
            FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
            DENSITY(IP,IDIM)=0.5D0*(RHOCOMP(1)+FACTOR*RHOCOMP(2))
            KIN(IP,IDIM)=0.5D0*(TAUCOMP(1)+FACTOR*TAUCOMP(2))
            DO ICART=1,3
              GRAD(IP,ICART,IDIM)=0.5D0 &
     &                            *(GRADCOMP(ICART,1) &
     &                              +FACTOR*GRADCOMP(ICART,2))
            END DO
          END DO
        END IF
      END DO
      IF(IP.NE.NPOINT) THEN
        CALL ERROR$MSG('SKALA HYBRID GRID COUNT CHANGED WHILE BUILDING')
        CALL ERROR$I4VAL('COUNTED',NPOINT)
        CALL ERROR$I4VAL('BUILT',IP)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      CALL TIMING$CLOCKOFF('SKALA:ATOMGRID')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T1)
      CALL ACCELPROFILE$ADD('SKALA_ATOM_GRID' &
     &    ,INT(NPOINT,KIND=8),INT(NLOCAL,KIND=8),INT(NAT,KIND=8) &
     &    ,INT(IAT,KIND=8),0.D0,0.D0,ACCEL_T1-ACCEL_T0)
      CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF

      CALL TIMING$CLOCKON('SKALA:1CENTER')
      ALLOCATE(AERHO(NPOINT,2),PSRHO(NPOINT,2))
      ALLOCATE(AEGRAD(NPOINT,3,2),PSGRAD(NPOINT,3,2))
      ALLOCATE(AETAU(NPOINT,2),PSTAU(NPOINT,2))
      CALL PAW_SKALA_ONECENTER_POINTS(GID,NR,LNX,LOX,LMNX,NDIMD &
     &                                ,DENMAT,AEPHI,PSPHI,AECORE,PSCORE &
     &                                ,RCUT,NPOINT,RELCOORD &
     &                                ,AERHO,AEGRAD,AETAU &
     &                                ,PSRHO,PSGRAD,PSTAU)
      IF(NSMOOTH.GT.0) THEN
        AERHO(1:NSMOOTH,:)=0.D0
        PSRHO(1:NSMOOTH,:)=0.D0
        AEGRAD(1:NSMOOTH,:,:)=0.D0
        PSGRAD(1:NSMOOTH,:,:)=0.D0
        AETAU(1:NSMOOTH,:)=0.D0
        PSTAU(1:NSMOOTH,:)=0.D0
      END IF
      FORWARD_SMOOTH_ELECTRONS=FORWARD_SMOOTH_ELECTRONS &
     &                 +SUM(GRIDWEIGHTS*SUM(DENSITY,DIM=2))
      FORWARD_CORRECTION_ELECTRONS=FORWARD_CORRECTION_ELECTRONS &
     &                 +SUM(GRIDWEIGHTS*SUM(AERHO-PSRHO,DIM=2))
      FORWARD_SMOOTH_TAU=FORWARD_SMOOTH_TAU &
     &                 +SUM(GRIDWEIGHTS*SUM(KIN,DIM=2))
      FORWARD_CORRECTION_TAU=FORWARD_CORRECTION_TAU &
     &                 +SUM(GRIDWEIGHTS*SUM(AETAU-PSTAU,DIM=2))
      DENSITY=DENSITY+AERHO-PSRHO
      GRAD=GRAD+AEGRAD-PSGRAD
      KIN=KIN+AETAU-PSTAU
      CALL TIMING$CLOCKOFF('SKALA:1CENTER')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T1)
      CALL ACCELPROFILE$ADD('SKALA_ONECENTER' &
     &    ,INT(NPOINT,KIND=8),INT(LMNX,KIND=8),INT(NR,KIND=8) &
     &    ,INT(IAT,KIND=8),0.D0,0.D0,ACCEL_T1-ACCEL_T0)
#ENDIF

      ALLOCATE(DDENSITY(NPOINT,2),DGRAD(NPOINT,3,2),DKIN(NPOINT,2))
      ALLOCATE(DGRIDCOORDS(NPOINT,3),DGRIDWEIGHTS(NPOINT))
      ALLOCATE(DATOMCOORDS(1,3),DATOMICGRIDWEIGHTS(NPOINT))
      MODELATOM(1,:)=ATOMCOORD(IAT,:)
      ATOMICGRIDSIZES(1)=INT(NPOINT,KIND=8)
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF
      CALL TIMING$CLOCKON('SKALA:MODEL')
      CALL SKALA$EVALUATE(NPOINT,1,DENSITY,GRAD,KIN &
     &                   ,GRIDCOORDS,GRIDWEIGHTS,MODELATOM &
     &                   ,ATOMICGRIDWEIGHTS,ATOMICGRIDSIZES,ENERGY &
     &                   ,DDENSITY,DGRAD,DKIN,DGRIDCOORDS &
     &                   ,DGRIDWEIGHTS,DATOMCOORDS,DATOMICGRIDWEIGHTS)
      CALL TIMING$CLOCKOFF('SKALA:MODEL')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T1)
      CALL ACCELPROFILE$ADD('SKALA_MODEL' &
     &    ,INT(NPOINT,KIND=8),INT(IAT,KIND=8),0_8,0_8 &
     &    ,0.D0,0.D0,ACCEL_T1-ACCEL_T0)
#ENDIF
      IF(ENERGY.NE.ENERGY.OR.ABS(ENERGY).GT.0.5D0*HUGE(ENERGY)) THEN
        CALL ERROR$MSG('SKALA FORWARD ENERGY IS NOT FINITE')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(ANY(DDENSITY.NE.DDENSITY).OR.ANY(DGRAD.NE.DGRAD) &
     &   .OR.ANY(DKIN.NE.DKIN).OR.ANY(DGRIDCOORDS.NE.DGRIDCOORDS) &
     &   .OR.ANY(DGRIDWEIGHTS.NE.DGRIDWEIGHTS) &
     &   .OR.ANY(DATOMCOORDS.NE.DATOMCOORDS) &
     &   .OR.ANY(DATOMICGRIDWEIGHTS.NE.DATOMICGRIDWEIGHTS)) THEN
        CALL ERROR$MSG('SKALA PRIMITIVE ADJOINTS ARE NOT FINITE')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(ALLOCATED(FORWARD_DERIV)) THEN
        FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+DATOMCOORDS(1,:)
        FORWARD_DERIV_MODEL_ATOM(:,IAT)= &
     &      FORWARD_DERIV_MODEL_ATOM(:,IAT)+DATOMCOORDS(1,:)
      END IF
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF
      CALL TIMING$CLOCKON('SKALA:1CADJOINT')
      CALL PAW_SKALA_ONECENTER_ADJOINT_POINTS(GID,NR,LNX,LOX,LMNX &
     &                                        ,NDIMD,AEPHI,PSPHI,RCUT &
     &                                        ,NPOINT-NSMOOTH &
     &                                        ,RELCOORD(NSMOOTH+1:NPOINT,:) &
     &                                        ,DDENSITY(NSMOOTH+1:NPOINT,:) &
     &                                        ,DGRAD(NSMOOTH+1:NPOINT,:,:) &
     &                                        ,DKIN(NSMOOTH+1:NPOINT,:) &
     &                                        ,DHSKALA)
      CALL TIMING$CLOCKOFF('SKALA:1CADJOINT')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T1)
      CALL ACCELPROFILE$ADD('SKALA_ONECENTER_ADJOINT' &
     &    ,INT(NPOINT,KIND=8),INT(LMNX,KIND=8),INT(NR,KIND=8) &
     &    ,INT(IAT,KIND=8),0.D0,0.D0,ACCEL_T1-ACCEL_T0)
#ENDIF
      IF(CONFIG_CHECK.AND..NOT.TONECENTERCHECKED) THEN
        CALL SKALA_ONECENTER_MODELCHECK(GID,NR,LNX,LOX,LMNX,NDIMD &
     &       ,DENMAT,AEPHI,PSPHI,RCUT,NPOINT,NSMOOTH,RELCOORD &
     &       ,DENSITY,GRAD,KIN &
     &       ,GRIDCOORDS,GRIDWEIGHTS,MODELATOM,ATOMICGRIDWEIGHTS &
     &       ,ATOMICGRIDSIZES,DDENSITY,DGRAD,DKIN,DHSKALA)
        TONECENTERCHECKED=.TRUE.
      END IF
      FORWARD_ONECENTER_ADJOINT_NORM2=FORWARD_ONECENTER_ADJOINT_NORM2 &
     &                               +SUM(ABS(DHSKALA)**2)
      FORWARD_ONECENTER_CONTRACTION=FORWARD_ONECENTER_CONTRACTION &
     &       +REAL(SUM(CONJG(DENMAT)*DHSKALA),KIND=8)

#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T0)
#ENDIF
      CALL TIMING$CLOCKON('SKALA:GRIDBACK')
      IP=0
      DO ISMOOTH=1,NSMOOTH
            IWORK=SMOOTHINDEX(ISMOOTH)-1
            I1=MOD(IWORK,SMOOTH_NR1)+1
            IWORK=IWORK/SMOOTH_NR1
            I2=MOD(IWORK,SMOOTH_NR2)+1
            I3=IWORK/SMOOTH_NR2+1
            IP=IP+1
            IF(ALLOCATED(FORWARD_DERIV)) THEN
              RELATIVE=SMOOTHREL(ISMOOTH,:)
              DISTANCE=SQRT(SUM(RELATIVE**2))
              SMOOTHSCALE=1.D0-PAW_SKALA_RADIAL_BLEND(DISTANCE,RCUT)
              PARTWEIGHT=SMOOTH_PARTITION(I1,I2,I3,IAT)
              WEIGHTSENSITIVITY=DVOL*SMOOTHSCALE*(DGRIDWEIGHTS(IP) &
     &            +DATOMICGRIDWEIGHTS(IP) &
     &             *PAW_SKALA_PARTITION_TAPER_DERIVATIVE(PARTWEIGHT))
              SMOOTH_PARTITION_SENSITIVITY(I1,I2,I3,IAT)= &
     &          SMOOTH_PARTITION_SENSITIVITY(I1,I2,I3,IAT) &
     &          +WEIGHTSENSITIVITY
              BLENDSENSITIVITY=DVOL*(DGRIDWEIGHTS(IP)*PARTWEIGHT &
     &          +DATOMICGRIDWEIGHTS(IP) &
     &           *PAW_SKALA_PARTITION_TAPER(PARTWEIGHT))
              BLENDDERIV=PAW_SKALA_RADIAL_BLEND_DERIVATIVE &
     &                   (DISTANCE,RCUT)
              IF(DISTANCE.GT.0.D0.AND.BLENDDERIV.NE.0.D0) THEN
                MOVINGDERIV=BLENDSENSITIVITY*BLENDDERIV &
     &                     *RELATIVE/DISTANCE
                FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+MOVINGDERIV
                FORWARD_DERIV_RADIAL_BLEND(:,IAT)= &
     &            FORWARD_DERIV_RADIAL_BLEND(:,IAT)+MOVINGDERIV
              END IF
            END IF
            DO IDIM=1,NDIMD
              FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
              SMOOTH_ADJ_RHO(I1,I2,I3,IDIM)= &
     &          SMOOTH_ADJ_RHO(I1,I2,I3,IDIM) &
     &          +0.5D0*(DDENSITY(IP,1)+FACTOR*DDENSITY(IP,2))
              SMOOTH_ADJ_TAU(I1,I2,I3,IDIM)= &
     &          SMOOTH_ADJ_TAU(I1,I2,I3,IDIM) &
     &          +0.5D0*(DKIN(IP,1)+FACTOR*DKIN(IP,2))
              DO ICART=1,3
                SMOOTH_ADJ_GRHO(I1,I2,I3,ICART,IDIM)= &
     &            SMOOTH_ADJ_GRHO(I1,I2,I3,ICART,IDIM) &
     &            +0.5D0*(DGRAD(IP,ICART,1) &
     &                    +FACTOR*DGRAD(IP,ICART,2))
              END DO
            END DO
      END DO
      DO ILOC=1,NLOCAL
        POINT=ATOMCOORD(IAT,:)+LOCALCOORD(ILOC,:)
        DISTANCE=SQRT(SUM(LOCALCOORD(ILOC,:)**2))
        BLEND=PAW_SKALA_RADIAL_BLEND(DISTANCE,RCUT)
        IF(LOCALPARTWEIGHT(ILOC).LE.PARTITION_EPS.OR.BLEND.LE.0.D0) CYCLE
        IP=IP+1
        IF(ALLOCATED(FORWARD_DERIV)) THEN
          CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
     &         (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS,NDIMD &
     &         ,SMOOTH_RHO,SMOOTH_GRHO,SMOOTH_TAU,POINT &
     &         ,RHOCOMP(1:NDIMD),GRADCOMP(:,1:NDIMD),TAUCOMP(1:NDIMD) &
     &         ,DRHOCOMP(:,1:NDIMD),DGRADCOMP(:,:,1:NDIMD) &
     &         ,DTAUCOMP(:,1:NDIMD))
        END IF
        DO IDIM=1,NDIMD
          FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
          ADJRHO(IDIM)=0.5D0*(DDENSITY(IP,1)+FACTOR*DDENSITY(IP,2))
          ADJTAU(IDIM)=0.5D0*(DKIN(IP,1)+FACTOR*DKIN(IP,2))
          DO ICART=1,3
            ADJGRAD(ICART,IDIM)=0.5D0*(DGRAD(IP,ICART,1) &
     &                                     +FACTOR*DGRAD(IP,ICART,2))
          END DO
        END DO
        IF(ALLOCATED(FORWARD_DERIV)) THEN
          MOVINGDERIV=DGRIDCOORDS(IP,:)
          PRIMITIVEDERIV=0.D0
          DO IDIM=1,NDIMD
            PRIMITIVEDERIV=PRIMITIVEDERIV &
     &                  +ADJRHO(IDIM)*DRHOCOMP(:,IDIM) &
     &                  +ADJTAU(IDIM)*DTAUCOMP(:,IDIM)
            DO ICART=1,3
              PRIMITIVEDERIV=PRIMITIVEDERIV &
     &                   +ADJGRAD(ICART,IDIM)*DGRADCOMP(ICART,:,IDIM)
            END DO
          END DO
          MOVINGDERIV=MOVINGDERIV+PRIMITIVEDERIV
          FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+MOVINGDERIV
          FORWARD_DERIV_LOCAL_GRID(:,IAT)= &
     &        FORWARD_DERIV_LOCAL_GRID(:,IAT)+DGRIDCOORDS(IP,:)
          FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)= &
     &        FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)+PRIMITIVEDERIV
          CALL PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES &
     &         (POINT,NAT,ATOMCOORD,SMOOTH_RBAS,PARTITION &
     &         ,DPARTITION_DATOM,DPARTITION_DPOINT)
          PARTWEIGHT=PARTITION(IAT)
          WEIGHTSENSITIVITY=LOCALWEIGHT(ILOC)*BLEND*(DGRIDWEIGHTS(IP) &
     &        +DATOMICGRIDWEIGHTS(IP) &
     &         *PAW_SKALA_PARTITION_TAPER_DERIVATIVE(PARTWEIGHT))
          DO J=1,NAT
            FORWARD_DERIV(:,J)=FORWARD_DERIV(:,J) &
     &            +WEIGHTSENSITIVITY*DPARTITION_DATOM(:,J,IAT)
            FORWARD_DERIV_LOCAL_PARTITION(:,J)= &
     &          FORWARD_DERIV_LOCAL_PARTITION(:,J) &
     &          +WEIGHTSENSITIVITY*DPARTITION_DATOM(:,J,IAT)
          END DO
          FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT) &
     &            +WEIGHTSENSITIVITY*DPARTITION_DPOINT(:,IAT)
          FORWARD_DERIV_LOCAL_PARTITION(:,IAT)= &
     &        FORWARD_DERIV_LOCAL_PARTITION(:,IAT) &
     &        +WEIGHTSENSITIVITY*DPARTITION_DPOINT(:,IAT)
        END IF
        CALL PAW_SKALA_GRID_PRIMITIVES_ADJOINT &
     &       (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS,NDIMD &
     &       ,SMOOTH_ADJ_RHO,SMOOTH_ADJ_GRHO,SMOOTH_ADJ_TAU,POINT &
     &       ,ADJRHO(1:NDIMD),ADJGRAD(:,1:NDIMD),ADJTAU(1:NDIMD))
      END DO
      IF(IP.NE.NPOINT) THEN
        CALL ERROR$MSG('SKALA ADJOINT GRID COUNT CHANGED')
        CALL ERROR$I4VAL('COUNTED',NPOINT)
        CALL ERROR$I4VAL('MAPPED',IP)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      CALL TIMING$CLOCKOFF('SKALA:GRIDBACK')
#IF DEFINED(CPPVAR_ACCEL_PROFILE)
      CALL ACCELPROFILE$NOW(ACCEL_T1)
      CALL ACCELPROFILE$ADD('SKALA_GRID_BACK' &
     &    ,INT(NPOINT,KIND=8),INT(NLOCAL,KIND=8),INT(NAT,KIND=8) &
     &    ,INT(IAT,KIND=8),0.D0,0.D0,ACCEL_T1-ACCEL_T0)
#ENDIF
      FORWARD_ENERGY=FORWARD_ENERGY+ENERGY
      FORWARD_ATOM_ENERGY(IAT)=FORWARD_ATOM_ENERGY(IAT)+ENERGY
      FORWARD_ATOM_NPOINT(IAT)=FORWARD_ATOM_NPOINT(IAT)+NPOINT
      FORWARD_ELECTRONS=FORWARD_ELECTRONS &
     &                 +SUM(GRIDWEIGHTS*SUM(DENSITY,DIM=2))
      FORWARD_TAU=FORWARD_TAU+SUM(GRIDWEIGHTS*SUM(KIN,DIM=2))
      FORWARD_NPOINT=FORWARD_NPOINT+NPOINT

      DEALLOCATE(ATOMCOORD,ATOMCOORD3,RELCOORD,GRIDCOORDS)
      IF(ALLOCATED(PARTITION)) DEALLOCATE(PARTITION)
      IF(ALLOCATED(DPARTITION_DATOM)) DEALLOCATE(DPARTITION_DATOM)
      IF(ALLOCATED(DPARTITION_DPOINT)) DEALLOCATE(DPARTITION_DPOINT)
      DEALLOCATE(LOCALCOORD,LOCALWEIGHT,LOCALPARTWEIGHT,GRIDWEIGHTS)
      DEALLOCATE(SMOOTHINDEX,SMOOTHREL)
      DEALLOCATE(ATOMICGRIDWEIGHTS,DENSITY,GRAD,KIN)
      DEALLOCATE(AERHO,PSRHO,AEGRAD,PSGRAD,AETAU,PSTAU)
      DEALLOCATE(DDENSITY,DGRAD,DKIN,DGRIDCOORDS,DGRIDWEIGHTS)
      DEALLOCATE(DATOMCOORDS,DATOMICGRIDWEIGHTS)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA_ONECENTER_MODELCHECK(GID,NR,LNX,LOX,LMNX,NDIMD &
     &       ,DENMAT,AEPHI,PSPHI,RCUT,NPOINT,NSMOOTH,RELCOORD &
     &       ,DENSITY,GRAD,KIN &
     &       ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS,ATOMICGRIDWEIGHTS &
     &       ,ATOMICGRIDSIZES,DDENSITY,DGRAD,DKIN,DHDM)
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_ONECENTER_POINTS
      IMPLICIT NONE
      REAL(8),PARAMETER :: EPSLIST(3)=(/1.D-2,3.D-3,1.D-3/)
      INTEGER(4),INTENT(IN) :: GID,NR,LNX,LOX(LNX),LMNX,NDIMD,NPOINT
      INTEGER(4),INTENT(IN) :: NSMOOTH
      COMPLEX(8),INTENT(IN) :: DENMAT(LMNX,LMNX,NDIMD)
      COMPLEX(8),INTENT(IN) :: DHDM(LMNX,LMNX,NDIMD)
      REAL(8),INTENT(IN) :: AEPHI(NR,LNX),PSPHI(NR,LNX),RCUT
      REAL(8),INTENT(IN) :: RELCOORD(NPOINT,3),DENSITY(NPOINT,2)
      REAL(8),INTENT(IN) :: GRAD(NPOINT,3,2),KIN(NPOINT,2)
      REAL(8),INTENT(IN) :: GRIDCOORDS(NPOINT,3),GRIDWEIGHTS(NPOINT)
      REAL(8),INTENT(IN) :: ATOMCOORDS(1,3),ATOMICGRIDWEIGHTS(NPOINT)
      INTEGER(8),INTENT(IN) :: ATOMICGRIDSIZES(1)
      REAL(8),INTENT(IN) :: DDENSITY(NPOINT,2),DGRAD(NPOINT,3,2)
      REAL(8),INTENT(IN) :: DKIN(NPOINT,2)
      COMPLEX(8),ALLOCATABLE :: DENMATR(:,:,:)
      REAL(8),ALLOCATABLE :: ZEROCORE(:),AERHO(:,:),PSRHO(:,:)
      REAL(8),ALLOCATABLE :: AEGRAD(:,:,:),PSGRAD(:,:,:)
      REAL(8),ALLOCATABLE :: AETAU(:,:),PSTAU(:,:)
      REAL(8),ALLOCATABLE :: DENSITY1(:,:),GRAD1(:,:,:),KIN1(:,:)
      REAL(8),ALLOCATABLE :: DDUMMY(:,:),GDUMMY(:,:,:),TDUMMY(:,:)
      REAL(8),ALLOCATABLE :: XCDUMMY(:,:),XWDUMMY(:),ACDUMMY(:,:)
      REAL(8),ALLOCATABLE :: AWDUMMY(:)
      REAL(8),ALLOCATABLE :: HMAT(:,:),EIG(:),EIGVEC(:,:)
      REAL(8) :: EPLUS,EMINUS,FD,PRIMITIVE,MATRIX,ERROR,EPS
      INTEGER(4) :: NFIL,IDIM,ISTEP

      ALLOCATE(DENMATR(LMNX,LMNX,NDIMD),ZEROCORE(NR))
      ALLOCATE(AERHO(NPOINT,2),PSRHO(NPOINT,2))
      ALLOCATE(AEGRAD(NPOINT,3,2),PSGRAD(NPOINT,3,2))
      ALLOCATE(AETAU(NPOINT,2),PSTAU(NPOINT,2))
      DENMATR=CMPLX(REAL(DENMAT,KIND=8),0.D0,KIND=8)
      ZEROCORE=0.D0
      CALL PAW_SKALA_ONECENTER_POINTS(GID,NR,LNX,LOX,LMNX,NDIMD &
     &       ,DENMATR,AEPHI,PSPHI,ZEROCORE,ZEROCORE,RCUT,NPOINT &
     &       ,RELCOORD,AERHO,AEGRAD,AETAU,PSRHO,PSGRAD,PSTAU)
      IF(NSMOOTH.GT.0) THEN
        AERHO(1:NSMOOTH,:)=0.D0
        PSRHO(1:NSMOOTH,:)=0.D0
        AEGRAD(1:NSMOOTH,:,:)=0.D0
        PSGRAD(1:NSMOOTH,:,:)=0.D0
        AETAU(1:NSMOOTH,:)=0.D0
        PSTAU(1:NSMOOTH,:)=0.D0
      END IF
      ALLOCATE(DENSITY1(NPOINT,2),GRAD1(NPOINT,3,2),KIN1(NPOINT,2))
      ALLOCATE(DDUMMY(NPOINT,2),GDUMMY(NPOINT,3,2),TDUMMY(NPOINT,2))
      ALLOCATE(XCDUMMY(NPOINT,3),XWDUMMY(NPOINT),ACDUMMY(1,3))
      ALLOCATE(AWDUMMY(NPOINT))
      PRIMITIVE=SUM(DDENSITY*(AERHO-PSRHO)) &
     &         +SUM(DGRAD*(AEGRAD-PSGRAD))+SUM(DKIN*(AETAU-PSTAU))
      MATRIX=REAL(SUM(CONJG(DENMATR)*DHDM),KIND=8)
      ERROR=ABS(PRIMITIVE-MATRIX)
      CALL FILEHANDLER$UNIT('PROT',NFIL)
      WRITE(NFIL,FMT='(/"SKALA ONE-CENTER MODEL CHECK"/28("="))')
      WRITE(NFIL,FMT='("PRIMITIVE ADJOINT CONTRACTION",T36,ES24.14)')PRIMITIVE
      WRITE(NFIL,FMT='("DENSITY-MATRIX CONTRACTION",T36,ES24.14)')MATRIX
      WRITE(NFIL,FMT='("ONE-CENTER MATRIX DIFFERENCE",T36,ES24.14)') &
     &     MATRIX-PRIMITIVE
      DO ISTEP=1,SIZE(EPSLIST)
        EPS=EPSLIST(ISTEP)
        DENSITY1=DENSITY+EPS*(AERHO-PSRHO)
        GRAD1=GRAD+EPS*(AEGRAD-PSGRAD)
        KIN1=KIN+EPS*(AETAU-PSTAU)
        CALL SKALA$EVALUATE(NPOINT,1,DENSITY1,GRAD1,KIN1 &
     &         ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS,ATOMICGRIDWEIGHTS &
     &         ,ATOMICGRIDSIZES,EPLUS,DDUMMY,GDUMMY,TDUMMY,XCDUMMY &
     &         ,XWDUMMY,ACDUMMY,AWDUMMY)
        DENSITY1=DENSITY-EPS*(AERHO-PSRHO)
        GRAD1=GRAD-EPS*(AEGRAD-PSGRAD)
        KIN1=KIN-EPS*(AETAU-PSTAU)
        CALL SKALA$EVALUATE(NPOINT,1,DENSITY1,GRAD1,KIN1 &
     &         ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS,ATOMICGRIDWEIGHTS &
     &         ,ATOMICGRIDSIZES,EMINUS,DDUMMY,GDUMMY,TDUMMY,XCDUMMY &
     &         ,XWDUMMY,ACDUMMY,AWDUMMY)
        FD=(EPLUS-EMINUS)/(2.D0*EPS)
        ERROR=MAX(ERROR,ABS(FD-PRIMITIVE))
        WRITE(NFIL,FMT='("FD STEP AND DERIVATIVE",T31,ES12.4,ES24.14)') &
     &       EPS,FD
        WRITE(NFIL,FMT='("FD-ADJOINT DIFFERENCE",T36,ES24.14)') &
     &       FD-PRIMITIVE
      END DO
      WRITE(NFIL,FMT='("MAXIMUM DIFFERENCE",T36,ES24.14)')ERROR
      ALLOCATE(HMAT(LMNX,LMNX),EIG(LMNX),EIGVEC(LMNX,LMNX))
      DO IDIM=1,NDIMD
        HMAT=REAL(DHDM(:,:,IDIM),KIND=8)
        CALL LIB$DIAGR8(LMNX,HMAT,EIG,EIGVEC)
        WRITE(NFIL,FMT='("ONE-CENTER CHANNEL",T36,I8)')IDIM
        WRITE(NFIL,FMT='("MATRIX MAX ABS",T36,ES24.14)')MAXVAL(ABS(HMAT))
        WRITE(NFIL,FMT='("EIGENVALUE MIN",T36,ES24.14)')MINVAL(EIG)
        WRITE(NFIL,FMT='("EIGENVALUE MAX",T36,ES24.14)')MAXVAL(EIG)
      END DO
      DEALLOCATE(HMAT,EIG,EIGVEC)
      DEALLOCATE(DENMATR,ZEROCORE,AERHO,PSRHO,AEGRAD,PSGRAD,AETAU,PSTAU)
      DEALLOCATE(DENSITY1,GRAD1,KIN1,DDUMMY,GDUMMY,TDUMMY)
      DEALLOCATE(XCDUMMY,XWDUMMY,ACDUMMY,AWDUMMY)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$FORWARDEND
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE, ONLY: &
     &     PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) :: NTASKS,THISTASK,NFIL,NAT,I1,I2,I3,I,J
      REAL(8) :: RHONORM,GRADNORM,TAUNORM,POINT(3),NETFORCE(3)
      REAL(8),ALLOCATABLE :: ATOMCOORD(:,:),ATOMCOORD3(:,:)
      REAL(8),ALLOCATABLE :: PARTITION(:),DPARTITION_DATOM(:,:,:)
      REAL(8),ALLOCATABLE :: DPARTITION_DPOINT(:,:),FORCE(:,:)

      IF(.NOT.TON) RETURN
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ENERGY)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SMOOTH_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_CORRECTION_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SMOOTH_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_CORRECTION_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ONECENTER_ADJOINT_NORM2)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ONECENTER_CONTRACTION)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_NPOINT)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ATOM_ENERGY)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ATOM_NPOINT)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_RHO)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_GRHO)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_TAU)
      CALL MPE$QUERY('MONOMER',NTASKS,THISTASK)
      ONECENTER_CONTRACTION=FORWARD_ONECENTER_CONTRACTION
      TONECENTERCONTRACTIONREADY=.TRUE.
      IF(ALLOCATED(FORWARD_DERIV)) THEN
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_MODEL_ATOM)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_LOCAL_GRID)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_LOCAL_PRIMITIVE)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_LOCAL_PARTITION)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_SMOOTH_PARTITION)
        CALL MPE$COMBINE('MONOMER','+',FORWARD_DERIV_RADIAL_BLEND)
        CALL MPE$COMBINE('MONOMER','+',SMOOTH_PARTITION_SENSITIVITY)
        NAT=SIZE(FORWARD_DERIV,2)
        IF(THISTASK.EQ.1) THEN
          ALLOCATE(ATOMCOORD(NAT,3),ATOMCOORD3(3,NAT),PARTITION(NAT))
          ALLOCATE(DPARTITION_DATOM(3,NAT,NAT))
          ALLOCATE(DPARTITION_DPOINT(3,NAT))
          CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,ATOMCOORD3)
          ATOMCOORD=TRANSPOSE(ATOMCOORD3)
          DO I3=1,SMOOTH_NR3
            DO I2=1,SMOOTH_NR2
              DO I1=1,SMOOTH_NR1
                IF(MAXVAL(ABS(SMOOTH_PARTITION_SENSITIVITY(I1,I2,I3,:))) &
     &             .EQ.0.D0) CYCLE
                POINT=MATMUL(SMOOTH_RBAS &
     &              ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &                ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &                ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
                CALL PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES &
     &               (POINT,NAT,ATOMCOORD,SMOOTH_RBAS,PARTITION &
     &               ,DPARTITION_DATOM,DPARTITION_DPOINT)
                DO I=1,NAT
                  DO J=1,NAT
                    FORWARD_DERIV(:,J)=FORWARD_DERIV(:,J) &
     &                +SMOOTH_PARTITION_SENSITIVITY(I1,I2,I3,I) &
     &                 *DPARTITION_DATOM(:,J,I)
                    FORWARD_DERIV_SMOOTH_PARTITION(:,J)= &
     &                FORWARD_DERIV_SMOOTH_PARTITION(:,J) &
     &                +SMOOTH_PARTITION_SENSITIVITY(I1,I2,I3,I) &
     &                 *DPARTITION_DATOM(:,J,I)
                  END DO
                END DO
              END DO
            END DO
          END DO
          DEALLOCATE(ATOMCOORD,ATOMCOORD3,PARTITION)
          DEALLOCATE(DPARTITION_DATOM,DPARTITION_DPOINT)
        END IF
        CALL MPE$BROADCAST('MONOMER',1,FORWARD_DERIV)
        ALLOCATE(FORCE(3,NAT))
        CALL ATOMLIST$GETR8A('FORCE',0,3*NAT,FORCE)
        FORCE=FORCE-FORWARD_DERIV
        CALL ATOMLIST$SETR8A('FORCE',0,3*NAT,FORCE)
        DEALLOCATE(FORCE)
      END IF
      IF(SMOOTH_DVOL.LE.0.D0) THEN
        CALL ERROR$MSG('SKALA SMOOTH GRID VOLUME IS INVALID')
        CALL ERROR$STOP('SKALA$FORWARDEND')
      END IF
      SMOOTH_ADJ_RHO=SMOOTH_ADJ_RHO/SMOOTH_DVOL
      SMOOTH_ADJ_GRHO=SMOOTH_ADJ_GRHO/SMOOTH_DVOL
      SMOOTH_ADJ_TAU=SMOOTH_ADJ_TAU/SMOOTH_DVOL
      RHONORM=SQRT(SUM(SMOOTH_ADJ_RHO**2))
      GRADNORM=SQRT(SUM(SMOOTH_ADJ_GRHO**2))
      TAUNORM=SQRT(SUM(SMOOTH_ADJ_TAU**2))
      IF(CONFIG_APPLY) THEN
        CALL ENERGYLIST$ADD('TOTAL ENERGY',FORWARD_ENERGY)
        CALL ENERGYLIST$ADD('AE  EXCHANGE-CORRELATION',FORWARD_ENERGY)
        CALL ENERGYLIST$ADD('PS  EXCHANGE-CORRELATION',FORWARD_ENERGY)
      END IF
      IF(THISTASK.EQ.1.AND..NOT.TFORWARDREPORTED) THEN
        CALL FILEHANDLER$UNIT('PROT',NFIL)
        WRITE(NFIL,FMT='(/"SKALA COMPLETE PAW ATOM BLOCKS"/30("="))')
        WRITE(NFIL,FMT='("HYBRID-GRID ROWS",T34,I12)')FORWARD_NPOINT
        WRITE(NFIL,FMT='("PARTITION TRANSLATION CLASSES",T34,I12)') &
     &       SMOOTH_PARTITION_NCLASS
        WRITE(NFIL,FMT='("SMOOTH ELECTRONS",T34,ES24.14)') &
     &       FORWARD_SMOOTH_ELECTRONS
        WRITE(NFIL,FMT='("AE-PS ELECTRONS",T34,ES24.14)') &
     &       FORWARD_CORRECTION_ELECTRONS
        WRITE(NFIL,FMT='("COMPOSITE ELECTRONS",T34,ES24.14)')FORWARD_ELECTRONS
        WRITE(NFIL,FMT='("SMOOTH POSITIVE TAU",T34,ES24.14)')FORWARD_SMOOTH_TAU
        WRITE(NFIL,FMT='("AE-PS POSITIVE TAU",T34,ES24.14)') &
     &       FORWARD_CORRECTION_TAU
        WRITE(NFIL,FMT='("COMPOSITE POSITIVE TAU",T34,ES24.14)')FORWARD_TAU
