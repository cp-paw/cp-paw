!     ..................................................................
      SUBROUTINE SKALA$SETL4(ID,VAL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: ID
      LOGICAL(4),INTENT(IN)   :: VAL
      IF(ID.EQ.'ON') THEN
        TON=VAL
      ELSE IF(ID.EQ.'APPLY') THEN
        CONFIG_APPLY=VAL
      ELSE IF(ID.EQ.'APPLYSMOOTH') THEN
        CONFIG_APPLYSMOOTH=VAL
      ELSE IF(ID.EQ.'APPLYTAU') THEN
        CONFIG_APPLYTAU=VAL
      ELSE IF(ID.EQ.'APPLYONECENTER') THEN
        CONFIG_APPLYONECENTER=VAL
      ELSE IF(ID.EQ.'INTERPOLATEPARTITION') THEN
        IF(VAL) THEN
          CALL ERROR$MSG('INTERPOLATEPARTITION=T IS INCOMPATIBLE WITH JOINT SKALA RECONSTRUCTION')
          CALL ERROR$STOP('SKALA$SETL4')
        END IF
        CONFIG_INTERPOLATEPARTITION=VAL
      ELSE IF(ID.EQ.'DISTRIBUTEGPU') THEN
        CONFIG_DISTRIBUTEGPU=VAL
      ELSE IF(ID.EQ.'CHECK') THEN
        CONFIG_CHECK=VAL
      ELSE IF(ID.EQ.'NEEDFORCE') THEN
        CONFIG_NEEDFORCE=VAL
      ELSE IF(ID.EQ.'NEEDSTRESS') THEN
        CONFIG_NEEDSTRESS=VAL
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$SETL4')
      END IF
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$GETL4(ID,VAL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: ID
      LOGICAL(4),INTENT(OUT)  :: VAL
      IF(ID.EQ.'ON') THEN
        VAL=TON
      ELSE IF(ID.EQ.'APPLY') THEN
        VAL=CONFIG_APPLY
      ELSE IF(ID.EQ.'APPLYSMOOTH') THEN
        VAL=CONFIG_APPLYSMOOTH
      ELSE IF(ID.EQ.'APPLYTAU') THEN
        VAL=CONFIG_APPLYTAU
      ELSE IF(ID.EQ.'APPLYONECENTER') THEN
        VAL=CONFIG_APPLYONECENTER
      ELSE IF(ID.EQ.'INTERPOLATEPARTITION') THEN
        VAL=CONFIG_INTERPOLATEPARTITION
      ELSE IF(ID.EQ.'DISTRIBUTEGPU') THEN
        VAL=CONFIG_DISTRIBUTEGPU
      ELSE IF(ID.EQ.'CUDA') THEN
        IF(TINITIALIZED) THEN
          VAL=TDEVICECUDA
        ELSE IF(TRIM(CONFIG_DEVICE).EQ.'CUDA'.OR. &
     &          TRIM(CONFIG_DEVICE).EQ.'cuda') THEN
          VAL=.TRUE.
        ELSE IF(TRIM(CONFIG_DEVICE).EQ.'AUTO'.OR. &
     &          TRIM(CONFIG_DEVICE).EQ.'auto') THEN
#IF DEFINED(CPPVAR_SKALA_FTORCH)
          VAL=PAW_SKALA_CUDA_AVAILABLE()
#ELSE
          VAL=.FALSE.
#ENDIF
        ELSE
          VAL=.FALSE.
        END IF
      ELSE IF(ID.EQ.'CHECK') THEN
        VAL=CONFIG_CHECK
      ELSE IF(ID.EQ.'NEEDFORCE') THEN
        VAL=CONFIG_NEEDFORCE
      ELSE IF(ID.EQ.'NEEDSTRESS') THEN
        VAL=CONFIG_NEEDSTRESS
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$GETL4')
      END IF
      RETURN
      END

