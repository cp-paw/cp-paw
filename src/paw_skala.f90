      IF(ID.EQ.'ON') THEN
        VAL=TON
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$GETL4')
      END IF
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$SETCH(ID,VAL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
