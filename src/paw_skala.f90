!     ..................................................................
      SUBROUTINE SKALA$SETI4(ID,VAL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: ID
      INTEGER(4),INTENT(IN)   :: VAL
      IF(ID.EQ.'DEVICEINDEX') THEN
        CONFIG_DEVICEINDEX=VAL
      ELSE IF(ID.EQ.'RADIALPOINTS') THEN
        IF(VAL.LE.0) THEN
          CALL ERROR$MSG('SKALA RADIALPOINTS MUST BE POSITIVE')
          CALL ERROR$I4VAL('RADIALPOINTS',VAL)
          CALL ERROR$STOP('SKALA$SETI4')
        END IF
        CONFIG_RADIALPOINTS=VAL
      ELSE IF(ID.EQ.'LEBEDEVEXACTNESS') THEN
        IF(VAL.LE.0) THEN
          CALL ERROR$MSG('SKALA LEBEDEVEXACTNESS MUST BE POSITIVE')
          CALL ERROR$I4VAL('LEBEDEVEXACTNESS',VAL)
          CALL ERROR$STOP('SKALA$SETI4')
        END IF
        CONFIG_LEBEDEVEXACTNESS=VAL
      ELSE IF(ID.EQ.'LEBEDEVORIENTATIONS') THEN
        IF(VAL.LE.0) THEN
          CALL ERROR$MSG('SKALA LEBEDEVORIENTATIONS MUST BE POSITIVE')
          CALL ERROR$I4VAL('LEBEDEVORIENTATIONS',VAL)
          CALL ERROR$STOP('SKALA$SETI4')
        END IF
        CONFIG_LEBEDEVORIENTATIONS=VAL
      ELSE IF(ID.EQ.'IMAGESHELLS') THEN
        IF(VAL.LT.1) THEN
          CALL ERROR$MSG('SKALA IMAGESHELLS MUST BE POSITIVE')
          CALL ERROR$I4VAL('IMAGESHELLS',VAL)
          CALL ERROR$STOP('SKALA$SETI4')
        END IF
        CONFIG_IMAGESHELLS=VAL
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$SETI4')
      END IF
      IF(ID.NE.'DEVICEINDEX') THEN
        IF(ALLOCATED(BLOCK_GRID)) DEALLOCATE(BLOCK_GRID)
        IF(ALLOCATED(GRID_ATOMS)) DEALLOCATE(GRID_ATOMS)
      END IF
      RETURN
      END

