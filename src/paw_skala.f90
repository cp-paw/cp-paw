      SUBROUTINE SKALA$PREPARE(NAT,ISP,LMNXX,NDIMD,DENMAT)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_SOLID_BASIS_INIT
      USE PAW_SKALA_GRID_MODULE, ONLY: PAW_SKALA_INVERSE3
      IMPLICIT NONE
      INTEGER,INTENT(IN) :: NAT,ISP(NAT),LMNXX,NDIMD
      COMPLEX(8),INTENT(IN) :: DENMAT(LMNXX,LMNXX,NDIMD,NAT)
      INTEGER :: I,GID,NR,LNX,LMNX,J,LAST
      REAL(8),ALLOCATABLE :: CORE(:),COORD(:,:)
      LOGICAL :: CHANGED
      IF(NDIMD.NE.1.AND.NDIMD.NE.2) THEN
        CALL ERROR$MSG('SKALA REQUIRES COLLINEAR DENSITIES')
        CALL ERROR$STOP('SKALA$PREPARE')
      END IF
      IF(.NOT.ALLOCATED(SOURCES)) THEN
        ALLOCATE(SOURCES(NAT))
        DO I=1,NAT
          CALL SETUP$ISELECT(ISP(I))
          CALL SETUP$GETI4('GID',GID)
          CALL RADIAL$GETI4(GID,'NR',NR)
          CALL SETUP$GETI4('LNX',LNX)
          SOURCES(I)%NR=NR
          SOURCES(I)%LNX=LNX
          SOURCES(I)%NDIMD=NDIMD
          ALLOCATE(SOURCES(I)%R(NR),SOURCES(I)%LOX(LNX))
          ALLOCATE(SOURCES(I)%PHI(NR,LNX,2),SOURCES(I)%CORE(NR,2))
          CALL RADIAL$R(GID,NR,SOURCES(I)%R)
          CALL SETUP$GETI4A('LOX',LNX,SOURCES(I)%LOX)
          LMNX=SUM(2*SOURCES(I)%LOX+1)
          SOURCES(I)%LMNX=LMNX
          ALLOCATE(SOURCES(I)%DM(LMNX,LMNX,NDIMD))
          ALLOCATE(SOURCES(I)%DH(LMNX,LMNX,NDIMD))
          CALL SETUP$GETR8A('AEPHI',NR*LNX,SOURCES(I)%PHI(:,:,1))
          CALL SETUP$GETR8A('PSPHI',NR*LNX,SOURCES(I)%PHI(:,:,2))
          ALLOCATE(CORE(NR))
          CALL SETUP$GETR8A('AECORE',NR,SOURCES(I)%CORE(:,1))
          CALL SETUP$GETR8A('PSCORE',NR,CORE)
          SOURCES(I)%CORE(:,1)=SOURCES(I)%CORE(:,1)-CORE
          CALL SETUP$GETR8A('TAUCORE',NR,SOURCES(I)%CORE(:,2))
          DEALLOCATE(CORE)
          CALL SETUP$UNSELECT()
          LAST=1
          DO J=1,NR
            IF(MAXVAL(ABS(SOURCES(I)%PHI(J,:,1)-SOURCES(I)%PHI(J,:,2))) &
     &         .GT.1.D-14.OR.MAXVAL(ABS(SOURCES(I)%CORE(J,:))).GT.1.D-14) LAST=J
          END DO
          SOURCES(I)%RCUT=SOURCES(I)%R(MIN(NR,LAST+3))
          CALL PAW_SKALA_SOLID_BASIS_INIT(SOURCES(I)%BASIS &
     &                                 ,MAXVAL(SOURCES(I)%LOX))
        END DO
      END IF
      DO I=1,NAT
        LMNX=SOURCES(I)%LMNX
        SOURCES(I)%DM=DENMAT(1:LMNX,1:LMNX,:,I)
        SOURCES(I)%DH=(0.D0,0.D0)
      END DO
      ALLOCATE(COORD(3,NAT))
      CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,COORD)
      CHANGED=.TRUE.
      IF(ALLOCATED(GRID_ATOMS)) THEN
        IF(SIZE(GRID_ATOMS,1).EQ.NAT) THEN
          CHANGED=ANY(TRANSPOSE(COORD).NE.GRID_ATOMS) &
     &           .OR.ANY(SMOOTH_RBAS.NE.GRID_CELL)
        END IF
      END IF
      IF(CHANGED) THEN
        IF(ALLOCATED(BLOCK_GRID)) DEALLOCATE(BLOCK_GRID)
        IF(ALLOCATED(GRID_ATOMS)) DEALLOCATE(GRID_ATOMS)
        ALLOCATE(BLOCK_GRID(NAT),GRID_ATOMS(NAT,3))
        GRID_ATOMS=TRANSPOSE(COORD)
        GRID_CELL=SMOOTH_RBAS
        CALL PAW_SKALA_INVERSE3(GRID_CELL,GRID_INVERSE)
      END IF
      END SUBROUTINE SKALA$PREPARE

      SUBROUTINE SKALA_BUILDGRID(IAT)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE
      USE PAW_SKALA_PARTITION_MODULE
      IMPLICIT NONE
      INTEGER,INTENT(IN) :: IAT
      TYPE(PAW_SKALA_PERIODIC_LAYOUT) :: ENERGY_LAYOUT,SELF_LAYOUT
      INTEGER :: NANG,NLOCAL,NPOINT,IP,I
      REAL(8),ALLOCATABLE :: X(:,:),W(:),E(:),D(:)
      REAL(8) :: POINT(3),WE,WD
      LOGICAL,ALLOCATABLE :: KEEP(:)
      IF(ALLOCATED(BLOCK_GRID(IAT)%W)) RETURN
      CALL PAW_SKALA_PERIODIC_INIT(ENERGY_LAYOUT,SIZE(GRID_ATOMS,1) &
     &                           ,GRID_ATOMS,GRID_CELL,CONFIG_IMAGESHELLS)
      CALL PAW_SKALA_PERIODIC_INIT(SELF_LAYOUT,1 &
     &                 ,GRID_ATOMS(IAT:IAT,:),GRID_CELL,CONFIG_IMAGESHELLS)
      CALL PAW_SKALA_LOCAL_GRID_SIZE(CONFIG_RADIALPOINTS &
     &     ,CONFIG_LEBEDEVEXACTNESS,NANG,NLOCAL,CONFIG_LEBEDEVORIENTATIONS)
      ALLOCATE(X(NLOCAL,3),W(NLOCAL),E(NLOCAL),D(NLOCAL),KEEP(NLOCAL))
      CALL PAW_SKALA_LOCAL_GRID(CONFIG_RADIALPOINTS,1.D0 &
     &     ,CONFIG_LEBEDEVEXACTNESS,NLOCAL,X,W &
     &     ,CONFIG_LEBEDEVORIENTATIONS,.TRUE.)
      DO IP=1,NLOCAL
        POINT=GRID_ATOMS(IAT,:)+X(IP,:)
        CALL PAW_SKALA_PERIODIC_WEIGHT(SELF_LAYOUT,1,POINT,WD)
        CALL PAW_SKALA_PERIODIC_WEIGHT(ENERGY_LAYOUT,IAT,POINT,WE)
        D(IP)=W(IP)*PAW_SKALA_PARTITION_TAPER(WD)
        E(IP)=W(IP)*WE
        KEEP(IP)=WD.GT.1.D-12.OR.WE.GT.0.D0
      END DO
      NPOINT=COUNT(KEEP)
      ALLOCATE(BLOCK_GRID(IAT)%X(NPOINT,3))
      ALLOCATE(BLOCK_GRID(IAT)%W(NPOINT),BLOCK_GRID(IAT)%D(NPOINT))
      ALLOCATE(BLOCK_GRID(IAT)%BASEW(NPOINT))
      DO I=1,3
        BLOCK_GRID(IAT)%X(:,I)=PACK(X(:,I),KEEP)
      END DO
      BLOCK_GRID(IAT)%W=PACK(E,KEEP)
      BLOCK_GRID(IAT)%D=PACK(D,KEEP)
      BLOCK_GRID(IAT)%BASEW=PACK(W,KEEP)
      END SUBROUTINE SKALA_BUILDGRID

      SUBROUTINE SKALA_PREPARE_SOURCE_CACHE(IAT,NPOINT,X)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_SOURCE_CACHE_PREPARE &
     &     ,PAW_SKALA_SOURCE_CACHE_BYTES,PAW_SKALA_SOURCE_CACHE_LIMIT
      IMPLICIT NONE
      INTEGER,INTENT(IN) :: IAT,NPOINT
      REAL(8),INTENT(IN) :: X(NPOINT,3)
      INTEGER :: J,K
      INTEGER(8) :: AVAILABLE,BYTES
      IF(.NOT.ALLOCATED(BLOCK_GRID(IAT)%SOURCE)) &
     &    ALLOCATE(BLOCK_GRID(IAT)%SOURCE(SIZE(SOURCES)))
      AVAILABLE=PAW_SKALA_SOURCE_CACHE_LIMIT()
      DO J=1,SIZE(BLOCK_GRID)
        IF(.NOT.ALLOCATED(BLOCK_GRID(J)%SOURCE)) CYCLE
        DO K=1,SIZE(BLOCK_GRID(J)%SOURCE)
          AVAILABLE=AVAILABLE-PAW_SKALA_SOURCE_CACHE_BYTES(BLOCK_GRID(J)%SOURCE(K))
        END DO
      END DO
      DO J=1,SIZE(SOURCES)
        AVAILABLE=AVAILABLE+PAW_SKALA_SOURCE_CACHE_BYTES(BLOCK_GRID(IAT)%SOURCE(J))
        CALL PAW_SKALA_SOURCE_CACHE_PREPARE(BLOCK_GRID(IAT)%SOURCE(J) &
     &       ,SOURCES(J),GRID_CELL,GRID_INVERSE,GRID_ATOMS(J,:),X &
     &       ,ALLOCATED(FORWARD_DERIV),MAX(0_8,AVAILABLE))
        BYTES=PAW_SKALA_SOURCE_CACHE_BYTES(BLOCK_GRID(IAT)%SOURCE(J))
        AVAILABLE=AVAILABLE-BYTES
        FORWARD_SOURCE_CACHE(3)=FORWARD_SOURCE_CACHE(3)+REAL(BYTES,KIND=8)
      END DO
      END SUBROUTINE SKALA_PREPARE_SOURCE_CACHE

      SUBROUTINE SKALA_RECONSTRUCT(IAT,IP,POINT,BAR,BACK,VALUE,SKIPROWS)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_SOURCE_IMAGES
      IMPLICIT NONE
      INTEGER,INTENT(IN) :: IAT,IP
      REAL(8),INTENT(IN) :: POINT(3),BAR(5,2)
      LOGICAL,INTENT(IN) :: BACK
      REAL(8),INTENT(OUT) :: VALUE(5,2)
      INTEGER,INTENT(IN) :: SKIPROWS(SIZE(SOURCES))
      REAL(8) :: V(5,2),DX(3),MOMENT(3,3),CONTRACTION
      INTEGER :: J,JD
      LOGICAL :: HIT
      VALUE=0.D0
      DO J=1,SIZE(SOURCES)
        IF(BACK.AND.IP.LE.SKIPROWS(J)) CYCLE
        IF(BACK) THEN
          IF(ALLOCATED(FORWARD_DERIV)) THEN
            IF(CONFIG_NEEDSTRESS) THEN
              CALL PAW_SKALA_SOURCE_IMAGES(SOURCES(J),GRID_CELL,GRID_INVERSE &
     &             ,GRID_ATOMS(J,:),POINT,V,BAR,DX,MOMENT,CONTRACTION &
     &             ,BLOCK_GRID(IAT)%SOURCE(J),IP,HIT)
            ELSE
              CALL PAW_SKALA_SOURCE_IMAGES(SOURCES(J),GRID_CELL,GRID_INVERSE &
     &             ,GRID_ATOMS(J,:),POINT,V,BAR,DX,DMCONTRACTION=CONTRACTION &
     &             ,CACHE=BLOCK_GRID(IAT)%SOURCE(J),IP=IP,HIT=HIT)
            END IF
            FORWARD_DERIV(:,IAT)=FORWARD_DERIV(:,IAT)+DX
            FORWARD_DERIV(:,J)=FORWARD_DERIV(:,J)-DX
            FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)= &
     &          FORWARD_DERIV_LOCAL_PRIMITIVE(:,IAT)+DX
            FORWARD_DERIV_LOCAL_PRIMITIVE(:,J)= &
     &          FORWARD_DERIV_LOCAL_PRIMITIVE(:,J)-DX
            IF(CONFIG_NEEDSTRESS) THEN
              DO JD=1,3
                FORWARD_STRESS_PRIMITIVE(:,JD)=FORWARD_STRESS_PRIMITIVE(:,JD) &
     &                  +DX*GRID_ATOMS(IAT,JD)-MOMENT(:,JD)
              END DO
            END IF
          ELSE
            CALL PAW_SKALA_SOURCE_IMAGES(SOURCES(J),GRID_CELL,GRID_INVERSE &
     &           ,GRID_ATOMS(J,:),POINT,V,BAR,DMCONTRACTION=CONTRACTION &
     &           ,CACHE=BLOCK_GRID(IAT)%SOURCE(J),IP=IP,HIT=HIT)
          END IF
          FORWARD_SOURCE_CONTRACTION=FORWARD_SOURCE_CONTRACTION+CONTRACTION
        ELSE
          CALL PAW_SKALA_SOURCE_IMAGES(SOURCES(J),GRID_CELL,GRID_INVERSE &
     &         ,GRID_ATOMS(J,:),POINT,V,CACHE=BLOCK_GRID(IAT)%SOURCE(J),IP=IP,HIT=HIT)
        END IF
        IF(HIT) THEN
          FORWARD_SOURCE_CACHE(1)=FORWARD_SOURCE_CACHE(1)+1.D0
        ELSE
          FORWARD_SOURCE_CACHE(2)=FORWARD_SOURCE_CACHE(2)+1.D0
        END IF
        VALUE=VALUE+V
      END DO
      END SUBROUTINE SKALA_RECONSTRUCT

