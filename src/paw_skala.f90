     &                           ,PAW_SKALA_EVALUATE, PAW_SKALA_RELEASE &
     &                           ,PAW_SKALA_CUDA_AVAILABLE
#ENDIF
      IMPLICIT NONE
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      TYPE(PAW_SKALA_MODEL),SAVE :: MODEL
