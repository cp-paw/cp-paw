!     ..................................................................
      SUBROUTINE SKALA$SETL4(ID,VAL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: ID
      LOGICAL(4),INTENT(IN)   :: VAL
      IF(ID.EQ.'ON') THEN
        TON=VAL
      ELSE IF(ID.EQ.'APPLY') THEN
        CONFIG_APPLY=VAL
      ELSE IF(ID.EQ.'APPLYSMOOTH') THEN
        CONFIG_APPLYSMOOTH=VAL
      ELSE IF(ID.EQ.'APPLYTAU') THEN
        CONFIG_APPLYTAU=VAL
      ELSE IF(ID.EQ.'APPLYONECENTER') THEN
        CONFIG_APPLYONECENTER=VAL
      ELSE IF(ID.EQ.'CHECK') THEN
        CONFIG_CHECK=VAL
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$SETL4')
      END IF
      RETURN
      END

