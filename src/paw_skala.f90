!     ..................................................................
      SUBROUTINE SKALA$INITIALIZE(MODELFILE,DEVICE,DEVICEINDEX)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: MODELFILE
      CHARACTER(*),INTENT(IN) :: DEVICE
      INTEGER(4)  ,INTENT(IN) :: DEVICEINDEX
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      INTEGER(4)              :: STATUS
      CHARACTER(2048)         :: MESSAGE
      CHARACTER(16)           :: DEVICE1

      IF(TINITIALIZED) CALL PAW_SKALA_RELEASE(MODEL)
      DEVICE1=DEVICE
      IF(TRIM(DEVICE1).EQ.'AUTO'.OR.TRIM(DEVICE1).EQ.'auto') THEN
        IF(PAW_SKALA_CUDA_AVAILABLE()) THEN
          DEVICE1='CUDA'
        ELSE
          DEVICE1='CPU'
        END IF
      END IF
      CALL PAW_SKALA_LOAD(MODEL,MODELFILE,DEVICE1,DEVICEINDEX,STATUS,MESSAGE)
      IF(STATUS.NE.0) THEN
        CALL ERROR$MSG('FAILED TO INITIALIZE SKALA 1.1')
        CALL ERROR$CHVAL('DETAIL',TRIM(MESSAGE))
        CALL ERROR$STOP('SKALA$INITIALIZE')
      END IF
      TINITIALIZED=.TRUE.
#ELSE
      CALL ERROR$MSG('CP-PAW WAS BUILT WITHOUT THE SKALA/FTORCH BRIDGE')
      CALL ERROR$STOP('SKALA$INITIALIZE')
#ENDIF
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$ENSUREINITIALIZED
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      IF(TINITIALIZED) RETURN
      IF(.NOT.TON) THEN
        CALL ERROR$MSG('SKALA FUNCTIONAL IS NOT ENABLED')
        CALL ERROR$STOP('SKALA$ENSUREINITIALIZED')
      END IF
      IF(LEN_TRIM(CONFIG_MODELFILE).EQ.0) THEN
        CALL ERROR$MSG('SKALA MODEL FILE HAS NOT BEEN SPECIFIED')
        CALL ERROR$STOP('SKALA$ENSUREINITIALIZED')
      END IF
      CALL SKALA$INITIALIZE(TRIM(CONFIG_MODELFILE),TRIM(CONFIG_DEVICE) &
     &                     ,CONFIG_DEVICEINDEX)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$FINALIZE
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      IF(TINITIALIZED) CALL PAW_SKALA_RELEASE(MODEL)
#ENDIF
      TINITIALIZED=.FALSE.
      TSMOOTHREPORTED=.FALSE.
      IF(ALLOCATED(TONECENTERREPORTED)) DEALLOCATE(TONECENTERREPORTED)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$SMOOTHVALIDATE(NRL,NDIMD,RHO,GRHO,TAUPOS &
     &                               ,NGRIDGLOBAL,CELLVOL)
      USE PAW_SKALA_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NRL,NDIMD,NGRIDGLOBAL
      REAL(8),INTENT(IN) :: RHO(NRL,NDIMD)
      REAL(8),INTENT(IN) :: GRHO(NRL,3,NDIMD)
      REAL(8),INTENT(IN) :: TAUPOS(NRL,NDIMD)
      REAL(8),INTENT(IN) :: CELLVOL
      REAL(8) :: RWEIGHT,RHOINT,SPININT,TAUINT,GRADNORM
      INTEGER(4) :: NTASKS,THISTASK,NFIL

      IF(.NOT.TON.OR.TSMOOTHREPORTED) RETURN
      IF(NDIMD.NE.1.AND.NDIMD.NE.2) THEN
        CALL ERROR$MSG('SKALA SMOOTH PRIMITIVES REQUIRE COLLINEAR SPIN')
        CALL ERROR$I4VAL('NDIMD',NDIMD)
        CALL ERROR$STOP('SKALA$SMOOTHVALIDATE')
      END IF
      RWEIGHT=CELLVOL/REAL(NGRIDGLOBAL,KIND=8)
      RHOINT=SUM(RHO(:,1))*RWEIGHT
      TAUINT=SUM(TAUPOS(:,1))*RWEIGHT
      GRADNORM=SUM(GRHO(:,:,1)**2)*RWEIGHT
      SPININT=0.D0
      IF(NDIMD.EQ.2) SPININT=SUM(RHO(:,2))*RWEIGHT
      CALL MPE$COMBINE('MONOMER','+',RHOINT)
      CALL MPE$COMBINE('MONOMER','+',TAUINT)
      CALL MPE$COMBINE('MONOMER','+',GRADNORM)
      CALL MPE$COMBINE('MONOMER','+',SPININT)
      CALL MPE$QUERY('MONOMER',NTASKS,THISTASK)
      IF(THISTASK.EQ.1) THEN
        CALL FILEHANDLER$UNIT('PROT',NFIL)
        WRITE(NFIL,FMT='(/"SKALA SMOOTH PRIMITIVES"/23("="))')
        WRITE(NFIL,FMT='("GRID POINTS",T34,I12)')NGRIDGLOBAL
        WRITE(NFIL,FMT='("SMOOTH ELECTRONS WITH CORE",T34,ES24.14)')RHOINT
        IF(NDIMD.EQ.2) THEN
          WRITE(NFIL,FMT='("SMOOTH SPIN",T34,ES24.14)')SPININT
        END IF
        WRITE(NFIL,FMT='("POSITIVE TAU",T34,ES24.14)')TAUINT
        WRITE(NFIL,FMT='("DENSITY GRADIENT L2",T34,ES24.14)')SQRT(GRADNORM)
      END IF
      TSMOOTHREPORTED=.TRUE.
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$ONECENTERVALIDATE(IAT,GID,NR,LNX,LOX,LMNX,LMRX &
     &                                  ,NDIMD,DENMAT,AEPHI,PSPHI &
     &                                  ,AECORE,PSCORE,AERHOL,PSRHOL &
     &                                  ,RCUT,EKINNL)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: &
     &     PAW_SKALA_ONECENTER_GRID_SIZE,PAW_SKALA_ONECENTER_PRIMITIVES
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: IAT,GID,NR,LNX,LOX(LNX),LMNX,LMRX,NDIMD
      COMPLEX(8),INTENT(IN) :: DENMAT(LMNX,LMNX,NDIMD)
      REAL(8),INTENT(IN) :: AEPHI(NR,LNX),PSPHI(NR,LNX)
      REAL(8),INTENT(IN) :: AECORE(NR),PSCORE(NR)
      REAL(8),INTENT(IN) :: AERHOL(NR,LMRX,NDIMD),PSRHOL(NR,LMRX,NDIMD)
      REAL(8),INTENT(IN) :: RCUT,EKINNL
      INTEGER(4),PARAMETER :: LEBEDEV_L=17
      REAL(8),PARAMETER :: PI=4.D0*ATAN(1.D0)
      LOGICAL(4),ALLOCATABLE :: TREPORTED1(:)
      REAL(8),ALLOCATABLE :: RELCOORD(:,:),WEIGHT(:)
      REAL(8),ALLOCATABLE :: AERHO(:,:),PSRHO(:,:),AETAU(:,:),PSTAU(:,:)
      REAL(8),ALLOCATABLE :: AEGRAD(:,:,:),PSGRAD(:,:,:)
      REAL(8) :: R(NR),WORK(NR),INTEGRAL(NR)
      REAL(8) :: AECOUNT,PSCOUNT,AECOUNTREF,PSCOUNTREF,TAUDIFF
      INTEGER(4) :: NRUSE,NANG,NPOINT,NFIL

      IF(.NOT.TON) RETURN
      IF(IAT.LE.0) RETURN
      IF(.NOT.ALLOCATED(TONECENTERREPORTED)) THEN
        ALLOCATE(TONECENTERREPORTED(IAT))
        TONECENTERREPORTED(:)=.FALSE.
      ELSE IF(SIZE(TONECENTERREPORTED).LT.IAT) THEN
        ALLOCATE(TREPORTED1(IAT))
        TREPORTED1(:)=.FALSE.
        TREPORTED1(1:SIZE(TONECENTERREPORTED))=TONECENTERREPORTED
        CALL MOVE_ALLOC(TREPORTED1,TONECENTERREPORTED)
      END IF
      IF(TONECENTERREPORTED(IAT)) RETURN

      CALL PAW_SKALA_ONECENTER_GRID_SIZE(GID,NR,RCUT,LEBEDEV_L &
     &                                  ,NRUSE,NANG,NPOINT)
      ALLOCATE(RELCOORD(NPOINT,3),WEIGHT(NPOINT))
      ALLOCATE(AERHO(NPOINT,2),PSRHO(NPOINT,2))
      ALLOCATE(AEGRAD(NPOINT,3,2),PSGRAD(NPOINT,3,2))
      ALLOCATE(AETAU(NPOINT,2),PSTAU(NPOINT,2))
      CALL PAW_SKALA_ONECENTER_PRIMITIVES(GID,NR,LNX,LOX,LMNX,NDIMD &
     &                                   ,DENMAT,AEPHI,PSPHI,AECORE,PSCORE &
     &                                   ,RCUT,LEBEDEV_L,NPOINT &
     &                                   ,RELCOORD,WEIGHT,AERHO,AEGRAD,AETAU &
     &                                   ,PSRHO,PSGRAD,PSTAU)

      AECOUNT=SUM(WEIGHT*(AERHO(:,1)+AERHO(:,2)))
      PSCOUNT=SUM(WEIGHT*(PSRHO(:,1)+PSRHO(:,2)))
      TAUDIFF=SUM(WEIGHT*(AETAU(:,1)+AETAU(:,2) &
     &                         -PSTAU(:,1)-PSTAU(:,2)))
      CALL RADIAL$R(GID,NR,R)
      WORK(:)=(AERHOL(:,1,1)+AECORE)*R**2
      CALL RADIAL$INTEGRATE(GID,NR,WORK,INTEGRAL)
      AECOUNTREF=SQRT(4.D0*PI)*INTEGRAL(NRUSE)
      WORK(:)=(PSRHOL(:,1,1)+PSCORE)*R**2
      CALL RADIAL$INTEGRATE(GID,NR,WORK,INTEGRAL)
      PSCOUNTREF=SQRT(4.D0*PI)*INTEGRAL(NRUSE)

      CALL FILEHANDLER$UNIT('PROT',NFIL)
      WRITE(NFIL,FMT='(/"SKALA PAW ONE-CENTER PRIMITIVES"/31("="))')
      WRITE(NFIL,FMT='("ATOM INDEX",T34,I10)')IAT
      WRITE(NFIL,FMT='("LEBEDEV EXACTNESS",T34,I10)')LEBEDEV_L
      WRITE(NFIL,FMT='("RADIAL POINTS",T34,I10)')NRUSE
      WRITE(NFIL,FMT='("ANGULAR POINTS",T34,I10)')NANG
      WRITE(NFIL,FMT='("TOTAL POINTS",T34,I10)')NPOINT
      WRITE(NFIL,FMT='("AE ELECTRONS",T34,ES24.14)')AECOUNT
      WRITE(NFIL,FMT='("AE ELECTRON ERROR",T34,ES24.14)')AECOUNT-AECOUNTREF
      WRITE(NFIL,FMT='("PS ELECTRONS",T34,ES24.14)')PSCOUNT
      WRITE(NFIL,FMT='("PS ELECTRON ERROR",T34,ES24.14)')PSCOUNT-PSCOUNTREF
      WRITE(NFIL,FMT='("POSITIVE TAU AE-PS",T34,ES24.14)')TAUDIFF
      WRITE(NFIL,FMT='("ONE-CENTER KINETIC",T34,ES24.14)')EKINNL
      WRITE(NFIL,FMT='("TAU-KINETIC DIFFERENCE",T34,ES24.14)')TAUDIFF-EKINNL
      TONECENTERREPORTED(IAT)=.TRUE.

      DEALLOCATE(RELCOORD,WEIGHT,AERHO,PSRHO,AEGRAD,PSGRAD,AETAU,PSTAU)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$EVALUATE(NPOINT,NATOM,DENSITY,GRAD,KIN &
     &                         ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS &
     &                         ,ATOMICGRIDWEIGHTS,ATOMICGRIDSIZES,ENERGY &
     &                         ,DDENSITY,DGRAD,DKIN,DGRIDCOORDS &
     &                         ,DGRIDWEIGHTS,DATOMCOORDS,DATOMICGRIDWEIGHTS)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)  :: NPOINT
      INTEGER(4),INTENT(IN)  :: NATOM
      REAL(8)   ,INTENT(IN)  :: DENSITY(NPOINT,2)
      REAL(8)   ,INTENT(IN)  :: GRAD(NPOINT,3,2)
      REAL(8)   ,INTENT(IN)  :: KIN(NPOINT,2)
      REAL(8)   ,INTENT(IN)  :: GRIDCOORDS(NPOINT,3)
      REAL(8)   ,INTENT(IN)  :: GRIDWEIGHTS(NPOINT)
      REAL(8)   ,INTENT(IN)  :: ATOMCOORDS(NATOM,3)
      REAL(8)   ,INTENT(IN)  :: ATOMICGRIDWEIGHTS(NPOINT)
      INTEGER(8),INTENT(IN)  :: ATOMICGRIDSIZES(NATOM)
      REAL(8)   ,INTENT(OUT) :: ENERGY
      REAL(8)   ,INTENT(OUT) :: DDENSITY(NPOINT,2)
      REAL(8)   ,INTENT(OUT) :: DGRAD(NPOINT,3,2)
      REAL(8)   ,INTENT(OUT) :: DKIN(NPOINT,2)
      REAL(8)   ,INTENT(OUT) :: DGRIDCOORDS(NPOINT,3)
      REAL(8)   ,INTENT(OUT) :: DGRIDWEIGHTS(NPOINT)
      REAL(8)   ,INTENT(OUT) :: DATOMCOORDS(NATOM,3)
      REAL(8)   ,INTENT(OUT) :: DATOMICGRIDWEIGHTS(NPOINT)
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      INTEGER(4)             :: STATUS
      CHARACTER(2048)        :: MESSAGE

      IF(.NOT.TINITIALIZED) CALL SKALA$ENSUREINITIALIZED
      CALL PAW_SKALA_EVALUATE(MODEL,DENSITY,GRAD,KIN,GRIDCOORDS,GRIDWEIGHTS &
     &                       ,ATOMCOORDS,ATOMICGRIDWEIGHTS,ATOMICGRIDSIZES &
     &                       ,ENERGY,DDENSITY,DGRAD,DKIN,STATUS,MESSAGE &
     &                       ,DGRIDCOORDS,DGRIDWEIGHTS,DATOMCOORDS &
     &                       ,DATOMICGRIDWEIGHTS)
      IF(STATUS.NE.0) THEN
        CALL ERROR$MSG('SKALA 1.1 EVALUATION FAILED')
        CALL ERROR$CHVAL('DETAIL',TRIM(MESSAGE))
        CALL ERROR$STOP('SKALA$EVALUATE')
      END IF
#ELSE
      CALL ERROR$MSG('CP-PAW WAS BUILT WITHOUT THE SKALA/FTORCH BRIDGE')
      CALL ERROR$STOP('SKALA$EVALUATE')
#ENDIF
      RETURN
      END
