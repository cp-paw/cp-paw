        CONFIG_DEVICE=TRIM(VAL)
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$SETCH')
      END IF
      RETURN
      END

