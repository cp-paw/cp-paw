      SUBROUTINE SKALA$REPORT(NFIL)
      USE PAW_SKALA_MODULE
      USE PAW_LEBEDEV_MODULE, ONLY: PAW_LEBEDEV_SIZE
      USE PAW_SKALA_PARTITION_MODULE, ONLY: PAW_SKALA_PARTITION_CACHE_LIMIT
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_SOURCE_CACHE_LIMIT &
     &     ,PAW_SKALA_SOURCE_RESIDENT_LIMIT
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NFIL
      INTEGER :: NANG,LEXACT
      INTEGER(8) :: CACHE_LIMIT
      IF(.NOT.TON) RETURN
      CACHE_LIMIT=PAW_SKALA_PARTITION_CACHE_LIMIT()
      WRITE(NFIL,FMT='(/"SKALA 1.1 PAW INTEGRATION"/25("="))')
      WRITE(NFIL,FMT='("STATUS",T30,A)')'JOINT PAW RECONSTRUCTION: UNDER VALIDATION'
      WRITE(NFIL,FMT='("MODEL FILE",T30,A)')TRIM(CONFIG_MODELFILE)
      WRITE(NFIL,FMT='("DEVICE",T30,A)')TRIM(CONFIG_DEVICE)
      WRITE(NFIL,FMT='("DEVICE INDEX",T30,I8)')CONFIG_DEVICEINDEX
      WRITE(NFIL,FMT='("PARTITION CACHE MiB/RANK",T30,I12)') &
     &     CACHE_LIMIT/1048576_8
      WRITE(NFIL,FMT='("SOURCE CACHE MiB/RANK",T30,I12)') &
     &     PAW_SKALA_SOURCE_CACHE_LIMIT()/1048576_8
      WRITE(NFIL,FMT='("SOURCE GPU CACHE MiB/RANK",T30,I12)') &
     &     PAW_SKALA_SOURCE_RESIDENT_LIMIT()/1048576_8
      WRITE(NFIL,FMT='("LOCAL RADIAL POINTS",T30,I8)')CONFIG_RADIALPOINTS
      WRITE(NFIL,FMT='("LEBEDEV EXACTNESS",T30,I8)')CONFIG_LEBEDEVEXACTNESS
      CALL PAW_LEBEDEV_SIZE(CONFIG_LEBEDEVEXACTNESS,NANG,LEXACT)
      WRITE(NFIL,FMT='("ACTUAL LEBEDEV EXACTNESS",T30,I8)')LEXACT
      WRITE(NFIL,FMT='("ANGULAR POINTS PER RULE",T30,I8)')NANG
      WRITE(NFIL,FMT='("LEBEDEV ORIENTATIONS",T30,I8)') &
     &     CONFIG_LEBEDEVORIENTATIONS
      WRITE(NFIL,FMT='("PERIODIC IMAGE SHELLS",T30,I8)')CONFIG_IMAGESHELLS
      WRITE(NFIL,FMT='("APPLY TO HAMILTONIAN",T30,L8)')CONFIG_APPLY
      WRITE(NFIL,FMT='("INTERPOLATE PARTITION",T30,L8)') &
     &     CONFIG_INTERPOLATEPARTITION
      WRITE(NFIL,FMT='("DISTRIBUTE CUDA MODEL",T30,L8)') &
     &     CONFIG_DISTRIBUTEGPU
      WRITE(NFIL,FMT='("CHECK MODEL ADJOINTS",T30,L8)')CONFIG_CHECK
      IF(CONFIG_APPLY) THEN
        WRITE(NFIL,FMT='("APPLY SMOOTH OPERATOR",T30,L8)')CONFIG_APPLYSMOOTH
        WRITE(NFIL,FMT='("APPLY TAU OPERATOR",T30,L8)')CONFIG_APPLYTAU
        WRITE(NFIL,FMT='("APPLY ONE-CENTER OPERATOR",T30,L8)') &
     &       CONFIG_APPLYONECENTER
        WRITE(NFIL,FMT='("ANALYTIC ATOMIC FORCES",T30,A)')'AVAILABLE'
        WRITE(NFIL,FMT='("ANALYTIC STRESS",T30,A)')'AVAILABLE'
      END IF
      RETURN
      END

