!     ..................................................................
      SUBROUTINE SKALA$INITIALIZE(MODELFILE,DEVICE,DEVICEINDEX)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: MODELFILE
      CHARACTER(*),INTENT(IN) :: DEVICE
      INTEGER(4)  ,INTENT(IN) :: DEVICEINDEX
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      INTEGER(4)              :: STATUS
      CHARACTER(2048)         :: MESSAGE
      CHARACTER(16)           :: DEVICE1

      IF(TINITIALIZED) CALL PAW_SKALA_RELEASE(MODEL)
      DEVICE1=DEVICE
      IF(TRIM(DEVICE1).EQ.'AUTO'.OR.TRIM(DEVICE1).EQ.'auto') THEN
        IF(PAW_SKALA_CUDA_AVAILABLE()) THEN
          DEVICE1='CUDA'
        ELSE
          DEVICE1='CPU'
        END IF
      END IF
      CALL PAW_SKALA_LOAD(MODEL,MODELFILE,DEVICE1,DEVICEINDEX,STATUS,MESSAGE)
      IF(STATUS.NE.0) THEN
        CALL ERROR$MSG('FAILED TO INITIALIZE SKALA 1.1')
        CALL ERROR$CHVAL('DETAIL',TRIM(MESSAGE))
        CALL ERROR$STOP('SKALA$INITIALIZE')
      END IF
      TINITIALIZED=.TRUE.
#ELSE
      CALL ERROR$MSG('CP-PAW WAS BUILT WITHOUT THE SKALA/FTORCH BRIDGE')
      CALL ERROR$STOP('SKALA$INITIALIZE')
#ENDIF
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$ENSUREINITIALIZED
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      IF(TINITIALIZED) RETURN
      IF(.NOT.TON) THEN
        CALL ERROR$MSG('SKALA FUNCTIONAL IS NOT ENABLED')
        CALL ERROR$STOP('SKALA$ENSUREINITIALIZED')
      END IF
      IF(LEN_TRIM(CONFIG_MODELFILE).EQ.0) THEN
        CALL ERROR$MSG('SKALA MODEL FILE HAS NOT BEEN SPECIFIED')
        CALL ERROR$STOP('SKALA$ENSUREINITIALIZED')
      END IF
      CALL SKALA$INITIALIZE(TRIM(CONFIG_MODELFILE),TRIM(CONFIG_DEVICE) &
     &                     ,CONFIG_DEVICEINDEX)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$FINALIZE
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
#IF DEFINED(CPPVAR_SKALA_FTORCH)
      IF(TINITIALIZED) CALL PAW_SKALA_RELEASE(MODEL)
#ENDIF
      TINITIALIZED=.FALSE.
      TSMOOTHREPORTED=.FALSE.
      TSMOOTHREADY=.FALSE.
      TFORWARDREPORTED=.FALSE.
      TOPERATORREPORTED=.FALSE.
      IF(ALLOCATED(TONECENTERREPORTED)) DEALLOCATE(TONECENTERREPORTED)
      IF(ALLOCATED(SMOOTH_RHO)) DEALLOCATE(SMOOTH_RHO)
      IF(ALLOCATED(SMOOTH_GRHO)) DEALLOCATE(SMOOTH_GRHO)
      IF(ALLOCATED(SMOOTH_TAU)) DEALLOCATE(SMOOTH_TAU)
      IF(ALLOCATED(SMOOTH_ADJ_RHO)) DEALLOCATE(SMOOTH_ADJ_RHO)
      IF(ALLOCATED(SMOOTH_ADJ_GRHO)) DEALLOCATE(SMOOTH_ADJ_GRHO)
      IF(ALLOCATED(SMOOTH_ADJ_TAU)) DEALLOCATE(SMOOTH_ADJ_TAU)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$FORWARDBEGIN
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      IF(.NOT.TON) RETURN
      IF(.NOT.TSMOOTHREADY) THEN
        CALL ERROR$MSG('SKALA SMOOTH FIELDS ARE NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$FORWARDBEGIN')
      END IF
      FORWARD_ENERGY=0.D0
      FORWARD_ELECTRONS=0.D0
      FORWARD_TAU=0.D0
      FORWARD_SMOOTH_ELECTRONS=0.D0
      FORWARD_CORRECTION_ELECTRONS=0.D0
      FORWARD_SMOOTH_TAU=0.D0
      FORWARD_CORRECTION_TAU=0.D0
      FORWARD_ONECENTER_ADJOINT_NORM2=0.D0
      FORWARD_NPOINT=0
      IF(ALLOCATED(SMOOTH_ADJ_RHO)) DEALLOCATE(SMOOTH_ADJ_RHO)
      IF(ALLOCATED(SMOOTH_ADJ_GRHO)) DEALLOCATE(SMOOTH_ADJ_GRHO)
      IF(ALLOCATED(SMOOTH_ADJ_TAU)) DEALLOCATE(SMOOTH_ADJ_TAU)
      ALLOCATE(SMOOTH_ADJ_RHO(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                       ,SMOOTH_NDIMD))
      ALLOCATE(SMOOTH_ADJ_GRHO(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,3 &
     &                        ,SMOOTH_NDIMD))
      ALLOCATE(SMOOTH_ADJ_TAU(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                       ,SMOOTH_NDIMD))
      SMOOTH_ADJ_RHO=0.D0
      SMOOTH_ADJ_GRHO=0.D0
      SMOOTH_ADJ_TAU=0.D0
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$ATOMFORWARD(IAT,GID,NR,LNX,LOX,LMNX,NDIMD &
     &                            ,DENMAT,AEPHI,PSPHI,AECORE,PSCORE,RCUT &
     &                            ,DHSKALA)
      USE PAW_SKALA_MODULE
      USE PAW_SKALA_GRID_MODULE, ONLY: PAW_SKALA_SMOOTH_PARTITION &
     &                                ,PAW_SKALA_NEAREST_IMAGE &
     &                                ,PAW_SKALA_PARTITION_TAPER &
     &                                ,PAW_SKALA_LOCAL_GRID_SIZE &
     &                                ,PAW_SKALA_LOCAL_GRID &
     &                                ,PAW_SKALA_GRID_INTERPOLATE &
     &                                ,PAW_SKALA_GRID_INTERPOLATION_ADJOINT
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_ONECENTER_POINTS &
     &                                      ,PAW_SKALA_ONECENTER_ADJOINT_POINTS
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: IAT,GID,NR,LNX,LOX(LNX),LMNX,NDIMD
      COMPLEX(8),INTENT(IN) :: DENMAT(LMNX,LMNX,NDIMD)
      REAL(8),INTENT(IN) :: AEPHI(NR,LNX),PSPHI(NR,LNX)
      REAL(8),INTENT(IN) :: AECORE(NR),PSCORE(NR),RCUT
      COMPLEX(8),INTENT(OUT) :: DHSKALA(LMNX,LMNX,NDIMD)
      REAL(8),PARAMETER :: PARTITION_EPS=1.D-12
      INTEGER(4),PARAMETER :: LOCAL_NRADIAL=100,LOCAL_LEBEDEV_L=17
      INTEGER(4) :: NAT,NPOINT,NLOCAL,NANG,I1,I2,I3,IP,IDIM,ICART,ILOC
      INTEGER(8) :: ATOMICGRIDSIZES(1)
      REAL(8) :: MODELATOM(1,3),POINT(3),IMAGE(3),RELATIVE(3),DISTANCE
      REAL(8) :: CELLVOL,DVOL,FACTOR,ENERGY
      REAL(8) :: RHOCOMP(2),TAUCOMP(2),GRADCOMP(3,2)
      REAL(8) :: ADJRHO(2),ADJTAU(2),ADJGRAD(3,2)
      REAL(8),ALLOCATABLE :: ATOMCOORD(:,:),ATOMCOORD3(:,:),PARTITION(:)
      REAL(8),ALLOCATABLE :: LOCALCOORD(:,:),LOCALWEIGHT(:)
      REAL(8),ALLOCATABLE :: RELCOORD(:,:),GRIDCOORDS(:,:),GRIDWEIGHTS(:)
      REAL(8),ALLOCATABLE :: ATOMICGRIDWEIGHTS(:)
      REAL(8),ALLOCATABLE :: DENSITY(:,:),GRAD(:,:,:),KIN(:,:)
      REAL(8),ALLOCATABLE :: AERHO(:,:),PSRHO(:,:),AETAU(:,:),PSTAU(:,:)
      REAL(8),ALLOCATABLE :: AEGRAD(:,:,:),PSGRAD(:,:,:)
      REAL(8),ALLOCATABLE :: DDENSITY(:,:),DGRAD(:,:,:),DKIN(:,:)
      REAL(8),ALLOCATABLE :: DGRIDCOORDS(:,:),DGRIDWEIGHTS(:)
      REAL(8),ALLOCATABLE :: DATOMCOORDS(:,:),DATOMICGRIDWEIGHTS(:)

      DHSKALA=CMPLX(0.D0,0.D0,KIND=8)
      IF(.NOT.TON) RETURN
      IF(.NOT.TSMOOTHREADY) THEN
        CALL ERROR$MSG('SKALA SMOOTH FIELDS ARE NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(NDIMD.NE.SMOOTH_NDIMD) THEN
        CALL ERROR$MSG('SKALA SMOOTH AND ONE-CENTER SPINS DIFFER')
        CALL ERROR$I4VAL('SMOOTH NDIMD',SMOOTH_NDIMD)
        CALL ERROR$I4VAL('ONE-CENTER NDIMD',NDIMD)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      CALL ATOMLIST$NATOM(NAT)
      IF(IAT.LT.1.OR.IAT.GT.NAT) THEN
        CALL ERROR$MSG('INVALID ATOM INDEX FOR SKALA FORWARD EVALUATION')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      ALLOCATE(ATOMCOORD(NAT,3),ATOMCOORD3(3,NAT),PARTITION(NAT))
      CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,ATOMCOORD3)
      ATOMCOORD=TRANSPOSE(ATOMCOORD3)

      CELLVOL=ABS(SMOOTH_RBAS(1,1)*(SMOOTH_RBAS(2,2)*SMOOTH_RBAS(3,3) &
     &                              -SMOOTH_RBAS(2,3)*SMOOTH_RBAS(3,2)) &
     &           -SMOOTH_RBAS(1,2)*(SMOOTH_RBAS(2,1)*SMOOTH_RBAS(3,3) &
     &                              -SMOOTH_RBAS(2,3)*SMOOTH_RBAS(3,1)) &
     &           +SMOOTH_RBAS(1,3)*(SMOOTH_RBAS(2,1)*SMOOTH_RBAS(3,2) &
     &                              -SMOOTH_RBAS(2,2)*SMOOTH_RBAS(3,1)))
      DVOL=CELLVOL/REAL(SMOOTH_NR1*SMOOTH_NR2*SMOOTH_NR3,KIND=8)
      CALL PAW_SKALA_LOCAL_GRID_SIZE(LOCAL_NRADIAL,LOCAL_LEBEDEV_L &
     &                              ,NANG,NLOCAL)
      ALLOCATE(LOCALCOORD(NLOCAL,3),LOCALWEIGHT(NLOCAL))
      CALL PAW_SKALA_LOCAL_GRID(LOCAL_NRADIAL,RCUT,LOCAL_LEBEDEV_L &
     &                          ,NLOCAL,LOCALCOORD,LOCALWEIGHT)
      NPOINT=0
      DO I3=1,SMOOTH_NR3
        DO I2=1,SMOOTH_NR2
          DO I1=1,SMOOTH_NR1
            POINT=MATMUL(SMOOTH_RBAS &
     &                  ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &                    ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &                    ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
            CALL PAW_SKALA_NEAREST_IMAGE(POINT,ATOMCOORD(IAT,:) &
     &                                   ,SMOOTH_RBAS,IMAGE,DISTANCE)
            IF(DISTANCE.LE.RCUT) CYCLE
            CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                      ,SMOOTH_RBAS,PARTITION)
            IF(PARTITION(IAT).GT.PARTITION_EPS) NPOINT=NPOINT+1
          END DO
        END DO
      END DO
      DO ILOC=1,NLOCAL
        POINT=ATOMCOORD(IAT,:)+LOCALCOORD(ILOC,:)
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                  ,SMOOTH_RBAS,PARTITION)
        IF(PARTITION(IAT).GT.PARTITION_EPS) NPOINT=NPOINT+1
      END DO
      IF(NPOINT.EQ.0) THEN
        CALL ERROR$MSG('SKALA ATOM BLOCK HAS NO GRID POINTS')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF

      ALLOCATE(RELCOORD(NPOINT,3),GRIDCOORDS(NPOINT,3))
      ALLOCATE(GRIDWEIGHTS(NPOINT),ATOMICGRIDWEIGHTS(NPOINT))
      ALLOCATE(DENSITY(NPOINT,2),GRAD(NPOINT,3,2),KIN(NPOINT,2))
      IP=0
      DO I3=1,SMOOTH_NR3
        DO I2=1,SMOOTH_NR2
          DO I1=1,SMOOTH_NR1
            POINT=MATMUL(SMOOTH_RBAS &
     &                  ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &                    ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &                    ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
            CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                      ,SMOOTH_RBAS,PARTITION)
            CALL PAW_SKALA_NEAREST_IMAGE(POINT,ATOMCOORD(IAT,:) &
     &                                   ,SMOOTH_RBAS,IMAGE,DISTANCE)
            IF(DISTANCE.LE.RCUT) CYCLE
            IF(PARTITION(IAT).LE.PARTITION_EPS) CYCLE
            IP=IP+1
            RELATIVE=POINT-IMAGE
            RELCOORD(IP,:)=RELATIVE
            GRIDCOORDS(IP,:)=ATOMCOORD(IAT,:)+RELATIVE
            GRIDWEIGHTS(IP)=DVOL*PARTITION(IAT)
            ATOMICGRIDWEIGHTS(IP)=DVOL &
     &          *PAW_SKALA_PARTITION_TAPER(PARTITION(IAT))
            IF(NDIMD.EQ.1) THEN
              DENSITY(IP,:)=0.5D0*SMOOTH_RHO(I1,I2,I3,1)
              KIN(IP,:)=0.5D0*SMOOTH_TAU(I1,I2,I3,1)
              DO ICART=1,3
                GRAD(IP,ICART,:)=0.5D0*SMOOTH_GRHO(I1,I2,I3,ICART,1)
              END DO
            ELSE
              DO IDIM=1,2
                FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
                DENSITY(IP,IDIM)=0.5D0*(SMOOTH_RHO(I1,I2,I3,1) &
     &                                      +FACTOR*SMOOTH_RHO(I1,I2,I3,2))
                KIN(IP,IDIM)=0.5D0*(SMOOTH_TAU(I1,I2,I3,1) &
     &                                      +FACTOR*SMOOTH_TAU(I1,I2,I3,2))
                DO ICART=1,3
                  GRAD(IP,ICART,IDIM)=0.5D0 &
     &                         *(SMOOTH_GRHO(I1,I2,I3,ICART,1) &
     &                    +FACTOR*SMOOTH_GRHO(I1,I2,I3,ICART,2))
                END DO
              END DO
            END IF
          END DO
        END DO
      END DO

      DO ILOC=1,NLOCAL
        RELATIVE=LOCALCOORD(ILOC,:)
        POINT=ATOMCOORD(IAT,:)+RELATIVE
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                  ,SMOOTH_RBAS,PARTITION)
        IF(PARTITION(IAT).LE.PARTITION_EPS) CYCLE
        IP=IP+1
        RELCOORD(IP,:)=RELATIVE
        GRIDCOORDS(IP,:)=POINT
        GRIDWEIGHTS(IP)=LOCALWEIGHT(ILOC)*PARTITION(IAT)
        ATOMICGRIDWEIGHTS(IP)=LOCALWEIGHT(ILOC) &
     &        *PAW_SKALA_PARTITION_TAPER(PARTITION(IAT))
        RHOCOMP=0.D0
        TAUCOMP=0.D0
        GRADCOMP=0.D0
        DO IDIM=1,NDIMD
          CALL PAW_SKALA_GRID_INTERPOLATE(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                                   ,SMOOTH_RBAS,SMOOTH_RHO(:,:,:,IDIM) &
     &                                   ,POINT,RHOCOMP(IDIM))
          CALL PAW_SKALA_GRID_INTERPOLATE(SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3 &
     &                                   ,SMOOTH_RBAS,SMOOTH_TAU(:,:,:,IDIM) &
     &                                   ,POINT,TAUCOMP(IDIM))
          DO ICART=1,3
            CALL PAW_SKALA_GRID_INTERPOLATE &
     &           (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS &
     &           ,SMOOTH_GRHO(:,:,:,ICART,IDIM),POINT,GRADCOMP(ICART,IDIM))
          END DO
        END DO
        IF(NDIMD.EQ.1) THEN
          DENSITY(IP,:)=0.5D0*RHOCOMP(1)
          KIN(IP,:)=0.5D0*TAUCOMP(1)
          DO ICART=1,3
            GRAD(IP,ICART,:)=0.5D0*GRADCOMP(ICART,1)
          END DO
        ELSE
          DO IDIM=1,2
            FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
            DENSITY(IP,IDIM)=0.5D0*(RHOCOMP(1)+FACTOR*RHOCOMP(2))
            KIN(IP,IDIM)=0.5D0*(TAUCOMP(1)+FACTOR*TAUCOMP(2))
            DO ICART=1,3
              GRAD(IP,ICART,IDIM)=0.5D0 &
     &                            *(GRADCOMP(ICART,1) &
     &                              +FACTOR*GRADCOMP(ICART,2))
            END DO
          END DO
        END IF
      END DO
      IF(IP.NE.NPOINT) THEN
        CALL ERROR$MSG('SKALA HYBRID GRID COUNT CHANGED WHILE BUILDING')
        CALL ERROR$I4VAL('COUNTED',NPOINT)
        CALL ERROR$I4VAL('BUILT',IP)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF

      ALLOCATE(AERHO(NPOINT,2),PSRHO(NPOINT,2))
      ALLOCATE(AEGRAD(NPOINT,3,2),PSGRAD(NPOINT,3,2))
      ALLOCATE(AETAU(NPOINT,2),PSTAU(NPOINT,2))
      CALL PAW_SKALA_ONECENTER_POINTS(GID,NR,LNX,LOX,LMNX,NDIMD &
     &                                ,DENMAT,AEPHI,PSPHI,AECORE,PSCORE &
     &                                ,RCUT,NPOINT,RELCOORD &
     &                                ,AERHO,AEGRAD,AETAU &
     &                                ,PSRHO,PSGRAD,PSTAU)
      FORWARD_SMOOTH_ELECTRONS=FORWARD_SMOOTH_ELECTRONS &
     &                 +SUM(GRIDWEIGHTS*SUM(DENSITY,DIM=2))
      FORWARD_CORRECTION_ELECTRONS=FORWARD_CORRECTION_ELECTRONS &
     &                 +SUM(GRIDWEIGHTS*SUM(AERHO-PSRHO,DIM=2))
      FORWARD_SMOOTH_TAU=FORWARD_SMOOTH_TAU &
     &                 +SUM(GRIDWEIGHTS*SUM(KIN,DIM=2))
      FORWARD_CORRECTION_TAU=FORWARD_CORRECTION_TAU &
     &                 +SUM(GRIDWEIGHTS*SUM(AETAU-PSTAU,DIM=2))
      DENSITY=DENSITY+AERHO-PSRHO
      GRAD=GRAD+AEGRAD-PSGRAD
      KIN=KIN+AETAU-PSTAU

      ALLOCATE(DDENSITY(NPOINT,2),DGRAD(NPOINT,3,2),DKIN(NPOINT,2))
      ALLOCATE(DGRIDCOORDS(NPOINT,3),DGRIDWEIGHTS(NPOINT))
      ALLOCATE(DATOMCOORDS(1,3),DATOMICGRIDWEIGHTS(NPOINT))
      MODELATOM(1,:)=ATOMCOORD(IAT,:)
      ATOMICGRIDSIZES(1)=INT(NPOINT,KIND=8)
      CALL SKALA$EVALUATE(NPOINT,1,DENSITY,GRAD,KIN &
     &                   ,GRIDCOORDS,GRIDWEIGHTS,MODELATOM &
     &                   ,ATOMICGRIDWEIGHTS,ATOMICGRIDSIZES,ENERGY &
     &                   ,DDENSITY,DGRAD,DKIN,DGRIDCOORDS &
     &                   ,DGRIDWEIGHTS,DATOMCOORDS,DATOMICGRIDWEIGHTS)
      IF(ENERGY.NE.ENERGY.OR.ABS(ENERGY).GT.0.5D0*HUGE(ENERGY)) THEN
        CALL ERROR$MSG('SKALA FORWARD ENERGY IS NOT FINITE')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      IF(ANY(DDENSITY.NE.DDENSITY).OR.ANY(DGRAD.NE.DGRAD) &
     &   .OR.ANY(DKIN.NE.DKIN)) THEN
        CALL ERROR$MSG('SKALA PRIMITIVE ADJOINTS ARE NOT FINITE')
        CALL ERROR$I4VAL('IAT',IAT)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      CALL PAW_SKALA_ONECENTER_ADJOINT_POINTS(GID,NR,LNX,LOX,LMNX &
     &                                        ,NDIMD,AEPHI,PSPHI,RCUT &
     &                                        ,NPOINT,RELCOORD &
     &                                        ,DDENSITY,DGRAD,DKIN,DHSKALA)
      IF(CONFIG_CHECK.AND..NOT.TONECENTERCHECKED) THEN
        CALL SKALA_ONECENTER_MODELCHECK(GID,NR,LNX,LOX,LMNX,NDIMD &
     &       ,DENMAT,AEPHI,PSPHI,RCUT,NPOINT,RELCOORD,DENSITY,GRAD,KIN &
     &       ,GRIDCOORDS,GRIDWEIGHTS,MODELATOM,ATOMICGRIDWEIGHTS &
     &       ,ATOMICGRIDSIZES,DDENSITY,DGRAD,DKIN,DHSKALA)
        TONECENTERCHECKED=.TRUE.
      END IF
      FORWARD_ONECENTER_ADJOINT_NORM2=FORWARD_ONECENTER_ADJOINT_NORM2 &
     &                               +SUM(ABS(DHSKALA)**2)

      IP=0
      DO I3=1,SMOOTH_NR3
        DO I2=1,SMOOTH_NR2
          DO I1=1,SMOOTH_NR1
            POINT=MATMUL(SMOOTH_RBAS &
     &                  ,(/REAL(I1-1,KIND=8)/REAL(SMOOTH_NR1,KIND=8) &
     &                    ,REAL(I2-1,KIND=8)/REAL(SMOOTH_NR2,KIND=8) &
     &                    ,REAL(I3-1,KIND=8)/REAL(SMOOTH_NR3,KIND=8)/))
            CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                      ,SMOOTH_RBAS,PARTITION)
            CALL PAW_SKALA_NEAREST_IMAGE(POINT,ATOMCOORD(IAT,:) &
     &                                   ,SMOOTH_RBAS,IMAGE,DISTANCE)
            IF(DISTANCE.LE.RCUT) CYCLE
            IF(PARTITION(IAT).LE.PARTITION_EPS) CYCLE
            IP=IP+1
            DO IDIM=1,NDIMD
              FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
              SMOOTH_ADJ_RHO(I1,I2,I3,IDIM)= &
     &          SMOOTH_ADJ_RHO(I1,I2,I3,IDIM) &
     &          +0.5D0*(DDENSITY(IP,1)+FACTOR*DDENSITY(IP,2))
              SMOOTH_ADJ_TAU(I1,I2,I3,IDIM)= &
     &          SMOOTH_ADJ_TAU(I1,I2,I3,IDIM) &
     &          +0.5D0*(DKIN(IP,1)+FACTOR*DKIN(IP,2))
              DO ICART=1,3
                SMOOTH_ADJ_GRHO(I1,I2,I3,ICART,IDIM)= &
     &            SMOOTH_ADJ_GRHO(I1,I2,I3,ICART,IDIM) &
     &            +0.5D0*(DGRAD(IP,ICART,1) &
     &                    +FACTOR*DGRAD(IP,ICART,2))
              END DO
            END DO
          END DO
        END DO
      END DO
      DO ILOC=1,NLOCAL
        POINT=ATOMCOORD(IAT,:)+LOCALCOORD(ILOC,:)
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD &
     &                                  ,SMOOTH_RBAS,PARTITION)
        IF(PARTITION(IAT).LE.PARTITION_EPS) CYCLE
        IP=IP+1
        DO IDIM=1,NDIMD
          FACTOR=MERGE(1.D0,-1.D0,IDIM.EQ.1)
          ADJRHO(IDIM)=0.5D0*(DDENSITY(IP,1)+FACTOR*DDENSITY(IP,2))
          ADJTAU(IDIM)=0.5D0*(DKIN(IP,1)+FACTOR*DKIN(IP,2))
          DO ICART=1,3
            ADJGRAD(ICART,IDIM)=0.5D0*(DGRAD(IP,ICART,1) &
     &                                     +FACTOR*DGRAD(IP,ICART,2))
          END DO
          CALL PAW_SKALA_GRID_INTERPOLATION_ADJOINT &
     &         (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS &
     &         ,SMOOTH_ADJ_RHO(:,:,:,IDIM),POINT,ADJRHO(IDIM))
          CALL PAW_SKALA_GRID_INTERPOLATION_ADJOINT &
     &         (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS &
     &         ,SMOOTH_ADJ_TAU(:,:,:,IDIM),POINT,ADJTAU(IDIM))
          DO ICART=1,3
            CALL PAW_SKALA_GRID_INTERPOLATION_ADJOINT &
     &           (SMOOTH_NR1,SMOOTH_NR2,SMOOTH_NR3,SMOOTH_RBAS &
     &           ,SMOOTH_ADJ_GRHO(:,:,:,ICART,IDIM),POINT &
     &           ,ADJGRAD(ICART,IDIM))
          END DO
        END DO
      END DO
      IF(IP.NE.NPOINT) THEN
        CALL ERROR$MSG('SKALA ADJOINT GRID COUNT CHANGED')
        CALL ERROR$I4VAL('COUNTED',NPOINT)
        CALL ERROR$I4VAL('MAPPED',IP)
        CALL ERROR$STOP('SKALA$ATOMFORWARD')
      END IF
      FORWARD_ENERGY=FORWARD_ENERGY+ENERGY
      FORWARD_ELECTRONS=FORWARD_ELECTRONS &
     &                 +SUM(GRIDWEIGHTS*SUM(DENSITY,DIM=2))
      FORWARD_TAU=FORWARD_TAU+SUM(GRIDWEIGHTS*SUM(KIN,DIM=2))
      FORWARD_NPOINT=FORWARD_NPOINT+NPOINT

      DEALLOCATE(ATOMCOORD,ATOMCOORD3,PARTITION,RELCOORD,GRIDCOORDS)
      DEALLOCATE(LOCALCOORD,LOCALWEIGHT,GRIDWEIGHTS)
      DEALLOCATE(ATOMICGRIDWEIGHTS,DENSITY,GRAD,KIN)
      DEALLOCATE(AERHO,PSRHO,AEGRAD,PSGRAD,AETAU,PSTAU)
      DEALLOCATE(DDENSITY,DGRAD,DKIN,DGRIDCOORDS,DGRIDWEIGHTS)
      DEALLOCATE(DATOMCOORDS,DATOMICGRIDWEIGHTS)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA_ONECENTER_MODELCHECK(GID,NR,LNX,LOX,LMNX,NDIMD &
     &       ,DENMAT,AEPHI,PSPHI,RCUT,NPOINT,RELCOORD,DENSITY,GRAD,KIN &
     &       ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS,ATOMICGRIDWEIGHTS &
     &       ,ATOMICGRIDSIZES,DDENSITY,DGRAD,DKIN,DHDM)
      USE PAW_SKALA_PRIMITIVES_MODULE, ONLY: PAW_SKALA_ONECENTER_POINTS
      IMPLICIT NONE
      REAL(8),PARAMETER :: EPSLIST(3)=(/1.D-2,3.D-3,1.D-3/)
      INTEGER(4),INTENT(IN) :: GID,NR,LNX,LOX(LNX),LMNX,NDIMD,NPOINT
      COMPLEX(8),INTENT(IN) :: DENMAT(LMNX,LMNX,NDIMD)
      COMPLEX(8),INTENT(IN) :: DHDM(LMNX,LMNX,NDIMD)
      REAL(8),INTENT(IN) :: AEPHI(NR,LNX),PSPHI(NR,LNX),RCUT
      REAL(8),INTENT(IN) :: RELCOORD(NPOINT,3),DENSITY(NPOINT,2)
      REAL(8),INTENT(IN) :: GRAD(NPOINT,3,2),KIN(NPOINT,2)
      REAL(8),INTENT(IN) :: GRIDCOORDS(NPOINT,3),GRIDWEIGHTS(NPOINT)
      REAL(8),INTENT(IN) :: ATOMCOORDS(1,3),ATOMICGRIDWEIGHTS(NPOINT)
      INTEGER(8),INTENT(IN) :: ATOMICGRIDSIZES(1)
      REAL(8),INTENT(IN) :: DDENSITY(NPOINT,2),DGRAD(NPOINT,3,2)
      REAL(8),INTENT(IN) :: DKIN(NPOINT,2)
      COMPLEX(8),ALLOCATABLE :: DENMATR(:,:,:)
      REAL(8),ALLOCATABLE :: ZEROCORE(:),AERHO(:,:),PSRHO(:,:)
      REAL(8),ALLOCATABLE :: AEGRAD(:,:,:),PSGRAD(:,:,:)
      REAL(8),ALLOCATABLE :: AETAU(:,:),PSTAU(:,:)
      REAL(8),ALLOCATABLE :: DENSITY1(:,:),GRAD1(:,:,:),KIN1(:,:)
      REAL(8),ALLOCATABLE :: DDUMMY(:,:),GDUMMY(:,:,:),TDUMMY(:,:)
      REAL(8),ALLOCATABLE :: XCDUMMY(:,:),XWDUMMY(:),ACDUMMY(:,:)
      REAL(8),ALLOCATABLE :: AWDUMMY(:)
      REAL(8),ALLOCATABLE :: HMAT(:,:),EIG(:),EIGVEC(:,:)
      REAL(8) :: EPLUS,EMINUS,FD,PRIMITIVE,MATRIX,ERROR,EPS
      INTEGER(4) :: NFIL,IDIM,ISTEP

      ALLOCATE(DENMATR(LMNX,LMNX,NDIMD),ZEROCORE(NR))
      ALLOCATE(AERHO(NPOINT,2),PSRHO(NPOINT,2))
      ALLOCATE(AEGRAD(NPOINT,3,2),PSGRAD(NPOINT,3,2))
      ALLOCATE(AETAU(NPOINT,2),PSTAU(NPOINT,2))
      DENMATR=CMPLX(REAL(DENMAT,KIND=8),0.D0,KIND=8)
      ZEROCORE=0.D0
      CALL PAW_SKALA_ONECENTER_POINTS(GID,NR,LNX,LOX,LMNX,NDIMD &
     &       ,DENMATR,AEPHI,PSPHI,ZEROCORE,ZEROCORE,RCUT,NPOINT &
     &       ,RELCOORD,AERHO,AEGRAD,AETAU,PSRHO,PSGRAD,PSTAU)
      ALLOCATE(DENSITY1(NPOINT,2),GRAD1(NPOINT,3,2),KIN1(NPOINT,2))
      ALLOCATE(DDUMMY(NPOINT,2),GDUMMY(NPOINT,3,2),TDUMMY(NPOINT,2))
      ALLOCATE(XCDUMMY(NPOINT,3),XWDUMMY(NPOINT),ACDUMMY(1,3))
      ALLOCATE(AWDUMMY(NPOINT))
      PRIMITIVE=SUM(DDENSITY*(AERHO-PSRHO)) &
     &         +SUM(DGRAD*(AEGRAD-PSGRAD))+SUM(DKIN*(AETAU-PSTAU))
      MATRIX=REAL(SUM(CONJG(DENMATR)*DHDM),KIND=8)
      ERROR=ABS(PRIMITIVE-MATRIX)
      CALL FILEHANDLER$UNIT('PROT',NFIL)
      WRITE(NFIL,FMT='(/"SKALA ONE-CENTER MODEL CHECK"/28("="))')
      WRITE(NFIL,FMT='("PRIMITIVE ADJOINT CONTRACTION",T36,ES24.14)')PRIMITIVE
      WRITE(NFIL,FMT='("DENSITY-MATRIX CONTRACTION",T36,ES24.14)')MATRIX
      DO ISTEP=1,SIZE(EPSLIST)
        EPS=EPSLIST(ISTEP)
        DENSITY1=DENSITY+EPS*(AERHO-PSRHO)
        GRAD1=GRAD+EPS*(AEGRAD-PSGRAD)
        KIN1=KIN+EPS*(AETAU-PSTAU)
        CALL SKALA$EVALUATE(NPOINT,1,DENSITY1,GRAD1,KIN1 &
     &         ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS,ATOMICGRIDWEIGHTS &
     &         ,ATOMICGRIDSIZES,EPLUS,DDUMMY,GDUMMY,TDUMMY,XCDUMMY &
     &         ,XWDUMMY,ACDUMMY,AWDUMMY)
        DENSITY1=DENSITY-EPS*(AERHO-PSRHO)
        GRAD1=GRAD-EPS*(AEGRAD-PSGRAD)
        KIN1=KIN-EPS*(AETAU-PSTAU)
        CALL SKALA$EVALUATE(NPOINT,1,DENSITY1,GRAD1,KIN1 &
     &         ,GRIDCOORDS,GRIDWEIGHTS,ATOMCOORDS,ATOMICGRIDWEIGHTS &
     &         ,ATOMICGRIDSIZES,EMINUS,DDUMMY,GDUMMY,TDUMMY,XCDUMMY &
     &         ,XWDUMMY,ACDUMMY,AWDUMMY)
        FD=(EPLUS-EMINUS)/(2.D0*EPS)
        ERROR=MAX(ERROR,ABS(FD-PRIMITIVE))
        WRITE(NFIL,FMT='("FD STEP AND DERIVATIVE",T31,ES12.4,ES24.14)') &
     &       EPS,FD
        WRITE(NFIL,FMT='("FD-ADJOINT DIFFERENCE",T36,ES24.14)') &
     &       FD-PRIMITIVE
      END DO
      WRITE(NFIL,FMT='("MAXIMUM DIFFERENCE",T36,ES24.14)')ERROR
      ALLOCATE(HMAT(LMNX,LMNX),EIG(LMNX),EIGVEC(LMNX,LMNX))
      DO IDIM=1,NDIMD
        HMAT=REAL(DHDM(:,:,IDIM),KIND=8)
        CALL LIB$DIAGR8(LMNX,HMAT,EIG,EIGVEC)
        WRITE(NFIL,FMT='("ONE-CENTER CHANNEL",T36,I8)')IDIM
        WRITE(NFIL,FMT='("MATRIX MAX ABS",T36,ES24.14)')MAXVAL(ABS(HMAT))
        WRITE(NFIL,FMT='("EIGENVALUE MIN",T36,ES24.14)')MINVAL(EIG)
        WRITE(NFIL,FMT='("EIGENVALUE MAX",T36,ES24.14)')MAXVAL(EIG)
      END DO
      DEALLOCATE(HMAT,EIG,EIGVEC)
      DEALLOCATE(DENMATR,ZEROCORE,AERHO,PSRHO,AEGRAD,PSGRAD,AETAU,PSTAU)
      DEALLOCATE(DENSITY1,GRAD1,KIN1,DDUMMY,GDUMMY,TDUMMY)
      DEALLOCATE(XCDUMMY,XWDUMMY,ACDUMMY,AWDUMMY)
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$FORWARDEND
      USE PAW_SKALA_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) :: NTASKS,THISTASK,NFIL
      REAL(8) :: RHONORM,GRADNORM,TAUNORM

      IF(.NOT.TON) RETURN
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ENERGY)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SMOOTH_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_CORRECTION_ELECTRONS)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_SMOOTH_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_CORRECTION_TAU)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_ONECENTER_ADJOINT_NORM2)
      CALL MPE$COMBINE('MONOMER','+',FORWARD_NPOINT)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_RHO)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_GRHO)
      CALL MPE$COMBINE('MONOMER','+',SMOOTH_ADJ_TAU)
      IF(SMOOTH_DVOL.LE.0.D0) THEN
        CALL ERROR$MSG('SKALA SMOOTH GRID VOLUME IS INVALID')
        CALL ERROR$STOP('SKALA$FORWARDEND')
      END IF
      SMOOTH_ADJ_RHO=SMOOTH_ADJ_RHO/SMOOTH_DVOL
      SMOOTH_ADJ_GRHO=SMOOTH_ADJ_GRHO/SMOOTH_DVOL
      SMOOTH_ADJ_TAU=SMOOTH_ADJ_TAU/SMOOTH_DVOL
      RHONORM=SQRT(SUM(SMOOTH_ADJ_RHO**2))
      GRADNORM=SQRT(SUM(SMOOTH_ADJ_GRHO**2))
      TAUNORM=SQRT(SUM(SMOOTH_ADJ_TAU**2))
      IF(CONFIG_APPLY) THEN
        CALL ENERGYLIST$ADD('TOTAL ENERGY',FORWARD_ENERGY)
        CALL ENERGYLIST$ADD('AE  EXCHANGE-CORRELATION',FORWARD_ENERGY)
        CALL ENERGYLIST$ADD('PS  EXCHANGE-CORRELATION',FORWARD_ENERGY)
      END IF
      CALL MPE$QUERY('MONOMER',NTASKS,THISTASK)
      IF(THISTASK.EQ.1.AND..NOT.TFORWARDREPORTED) THEN
        CALL FILEHANDLER$UNIT('PROT',NFIL)
        WRITE(NFIL,FMT='(/"SKALA COMPLETE PAW ATOM BLOCKS"/30("="))')
        WRITE(NFIL,FMT='("HYBRID-GRID ROWS",T34,I12)')FORWARD_NPOINT
        WRITE(NFIL,FMT='("SMOOTH ELECTRONS",T34,ES24.14)') &
     &       FORWARD_SMOOTH_ELECTRONS
        WRITE(NFIL,FMT='("AE-PS ELECTRONS",T34,ES24.14)') &
     &       FORWARD_CORRECTION_ELECTRONS
        WRITE(NFIL,FMT='("COMPOSITE ELECTRONS",T34,ES24.14)')FORWARD_ELECTRONS
        WRITE(NFIL,FMT='("SMOOTH POSITIVE TAU",T34,ES24.14)')FORWARD_SMOOTH_TAU
        WRITE(NFIL,FMT='("AE-PS POSITIVE TAU",T34,ES24.14)') &
     &       FORWARD_CORRECTION_TAU
        WRITE(NFIL,FMT='("COMPOSITE POSITIVE TAU",T34,ES24.14)')FORWARD_TAU
        WRITE(NFIL,FMT='("MODEL XC ENERGY",T34,ES24.14)')FORWARD_ENERGY
        WRITE(NFIL,FMT='("SMOOTH GRID DVOL",T34,ES24.14)')SMOOTH_DVOL
        WRITE(NFIL,FMT='("SMOOTH RHO ADJOINT L2",T34,ES24.14)')RHONORM
        WRITE(NFIL,FMT='("SMOOTH GRAD ADJOINT L2",T34,ES24.14)')GRADNORM
        WRITE(NFIL,FMT='("SMOOTH TAU ADJOINT L2",T34,ES24.14)')TAUNORM
        WRITE(NFIL,FMT='("ONE-CENTER ADJOINT L2",T34,ES24.14)') &
     &       SQRT(FORWARD_ONECENTER_ADJOINT_NORM2)
      END IF
      TFORWARDREPORTED=.TRUE.
      RETURN
      END

!     ..................................................................
      SUBROUTINE SKALA$SMOOTHADJOINTGET(NR1START,NR1L,NR1,NR2,NR3 &
     &                                  ,NDIMD,VRHO,VGRAD,VTAU)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NR1START,NR1L,NR1,NR2,NR3,NDIMD
      REAL(8),INTENT(OUT) :: VRHO(NR1L*NR2*NR3,NDIMD)
      REAL(8),INTENT(OUT) :: VGRAD(NR1L*NR2*NR3,3,NDIMD)
      REAL(8),INTENT(OUT) :: VTAU(NR1L*NR2*NR3,NDIMD)
      INTEGER(4) :: IEND,IDIM,ICART

      IF(.NOT.ALLOCATED(SMOOTH_ADJ_RHO) &
     &   .OR..NOT.ALLOCATED(SMOOTH_ADJ_GRHO) &
     &   .OR..NOT.ALLOCATED(SMOOTH_ADJ_TAU)) THEN
        CALL ERROR$MSG('SKALA SMOOTH ADJOINTS ARE NOT AVAILABLE')
        CALL ERROR$STOP('SKALA$SMOOTHADJOINTGET')
      END IF
      IEND=NR1START+NR1L-1
      IF(NR1.NE.SMOOTH_NR1.OR.NR2.NE.SMOOTH_NR2 &
     &   .OR.NR3.NE.SMOOTH_NR3.OR.NDIMD.NE.SMOOTH_NDIMD &
     &   .OR.NR1START.LT.1.OR.IEND.GT.NR1) THEN
        CALL ERROR$MSG('SKALA SMOOTH ADJOINT GRID IS INCONSISTENT')
        CALL ERROR$I4VAL('NR1',NR1)
        CALL ERROR$I4VAL('CACHED NR1',SMOOTH_NR1)
        CALL ERROR$I4VAL('NR1START',NR1START)
        CALL ERROR$I4VAL('NR1L',NR1L)
        CALL ERROR$STOP('SKALA$SMOOTHADJOINTGET')
      END IF
      DO IDIM=1,NDIMD
        VRHO(:,IDIM)=RESHAPE(SMOOTH_ADJ_RHO(NR1START:IEND,:,:,IDIM) &
     &                      ,(/NR1L*NR2*NR3/))
        VTAU(:,IDIM)=RESHAPE(SMOOTH_ADJ_TAU(NR1START:IEND,:,:,IDIM) &
     &                      ,(/NR1L*NR2*NR3/))
        DO ICART=1,3
          VGRAD(:,ICART,IDIM)=RESHAPE &
     &       (SMOOTH_ADJ_GRHO(NR1START:IEND,:,:,ICART,IDIM) &
     &       ,(/NR1L*NR2*NR3/))
        END DO
      END DO
      RETURN
      END

