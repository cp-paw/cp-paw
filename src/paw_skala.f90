      SUBROUTINE SKALA$SMOOTHVALIDATE(NRL,NDIMD,RHO,GRHO,TAUPOS &
     &                               ,NGRIDGLOBAL,CELLVOL)
      USE PAW_SKALA_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NRL,NDIMD,NGRIDGLOBAL
      REAL(8),INTENT(IN) :: RHO(NRL,NDIMD)
      REAL(8),INTENT(IN) :: GRHO(NRL,3,NDIMD)
      REAL(8),INTENT(IN) :: TAUPOS(NRL,NDIMD)
      REAL(8),INTENT(IN) :: CELLVOL
      REAL(8) :: RWEIGHT,RHOINT,SPININT,TAUINT,GRADNORM
      INTEGER(4) :: NTASKS,THISTASK,NFIL

      IF(.NOT.TON.OR.TSMOOTHREPORTED) RETURN
      IF(NDIMD.NE.1.AND.NDIMD.NE.2) THEN
        CALL ERROR$MSG('SKALA SMOOTH PRIMITIVES REQUIRE COLLINEAR SPIN')
        CALL ERROR$I4VAL('NDIMD',NDIMD)
        CALL ERROR$STOP('SKALA$SMOOTHVALIDATE')
      END IF
      RWEIGHT=CELLVOL/REAL(NGRIDGLOBAL,KIND=8)
      RHOINT=SUM(RHO(:,1))*RWEIGHT
      TAUINT=SUM(TAUPOS(:,1))*RWEIGHT
      GRADNORM=SUM(GRHO(:,:,1)**2)*RWEIGHT
      SPININT=0.D0
      IF(NDIMD.EQ.2) SPININT=SUM(RHO(:,2))*RWEIGHT
      CALL MPE$COMBINE('MONOMER','+',RHOINT)
      CALL MPE$COMBINE('MONOMER','+',TAUINT)
      CALL MPE$COMBINE('MONOMER','+',GRADNORM)
      CALL MPE$COMBINE('MONOMER','+',SPININT)
      CALL MPE$QUERY('MONOMER',NTASKS,THISTASK)
      IF(THISTASK.EQ.1) THEN
        CALL FILEHANDLER$UNIT('PROT',NFIL)
        WRITE(NFIL,FMT='(/"SKALA SMOOTH PRIMITIVES"/23("="))')
        WRITE(NFIL,FMT='("GRID POINTS",T34,I12)')NGRIDGLOBAL
        WRITE(NFIL,FMT='("SMOOTH ELECTRONS WITH CORE",T34,ES24.14)')RHOINT
        IF(NDIMD.EQ.2) THEN
          WRITE(NFIL,FMT='("SMOOTH SPIN",T34,ES24.14)')SPININT
        END IF
        WRITE(NFIL,FMT='("POSITIVE TAU",T34,ES24.14)')TAUINT
        WRITE(NFIL,FMT='("DENSITY GRADIENT L2",T34,ES24.14)')SQRT(GRADNORM)
      END IF
      TSMOOTHREPORTED=.TRUE.
      RETURN
      END

