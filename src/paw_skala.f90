      REAL(8),ALLOCATABLE,SAVE :: SMOOTH_RHO(:,:,:,:)
      REAL(8),ALLOCATABLE,SAVE :: SMOOTH_GRHO(:,:,:,:,:)
      REAL(8),ALLOCATABLE,SAVE :: SMOOTH_TAU(:,:,:,:)
      REAL(8),SAVE :: FORWARD_ENERGY=0.D0
      REAL(8),SAVE :: FORWARD_ELECTRONS=0.D0
      REAL(8),SAVE :: FORWARD_TAU=0.D0
      REAL(8),SAVE :: FORWARD_SMOOTH_ELECTRONS=0.D0
      REAL(8),SAVE :: FORWARD_CORRECTION_ELECTRONS=0.D0
      REAL(8),SAVE :: FORWARD_SMOOTH_TAU=0.D0
      REAL(8),SAVE :: FORWARD_CORRECTION_TAU=0.D0
      INTEGER(4),SAVE :: FORWARD_NPOINT=0
      LOGICAL(4),SAVE :: TFORWARDREPORTED=.FALSE.
      END MODULE PAW_SKALA_MODULE

!     ..................................................................
      SUBROUTINE SKALA$SETL4(ID,VAL)
      USE PAW_SKALA_MODULE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN) :: ID
      LOGICAL(4),INTENT(IN)   :: VAL
      IF(ID.EQ.'ON') THEN
        TON=VAL
      ELSE
        CALL ERROR$MSG('ID NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID',ID)
        CALL ERROR$STOP('SKALA$SETL4')
      END IF
      RETURN
      END

