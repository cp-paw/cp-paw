  IMPLICIT NONE
  PRIVATE
  INTEGER(4),PARAMETER :: INTERP_MIN=-3
  INTEGER(4),PARAMETER :: INTERP_MAX=4
  INTEGER(4),PARAMETER :: INTERP_N=INTERP_MAX-INTERP_MIN+1
  LOGICAL(4),SAVE :: GRID_BACK_CONFIG_READY=.FALSE.
  LOGICAL(4),SAVE :: GRID_BACK_ACC_ENABLED=.FALSE.
  INTEGER(8),SAVE :: GRID_BACK_ACC_MIN_POINTS=32768_8

  PUBLIC :: PAW_SKALA_SMOOTH_PARTITION
