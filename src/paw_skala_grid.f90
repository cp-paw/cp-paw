    ELSE
      X=(DISTANCE-INNER)/(RCUT-INNER)
      PAW_SKALA_RADIAL_BLEND_DERIVATIVE= &
 &       -30.D0*X**2*(1.D0-X)**2/(RCUT-INNER)
    END IF
  END FUNCTION PAW_SKALA_RADIAL_BLEND_DERIVATIVE

  SUBROUTINE PAW_SKALA_NEAREST_IMAGE(POINT,ATOM,RBAS,IMAGE,DISTANCE,AINV_IN)
    IMPLICIT NONE
    REAL(8),INTENT(IN) :: POINT(3),ATOM(3),RBAS(3,3)
    REAL(8),INTENT(OUT) :: IMAGE(3),DISTANCE
    REAL(8),INTENT(IN),OPTIONAL :: AINV_IN(3,3)
    REAL(8) :: AINV(3,3),DR(3),TRIAL(3),BEST2,R2
    INTEGER(4) :: CENTER(3),SHIFT(3),I1,I2,I3

    IF(PRESENT(AINV_IN)) THEN
      AINV=AINV_IN
    ELSE
      CALL PAW_SKALA_INVERSE3(RBAS,AINV)
    END IF
    DR=ATOM-POINT
    CENTER=NINT(MATMUL(AINV,DR))
    BEST2=HUGE(BEST2)
    DO I3=-1,1
      DO I2=-1,1
        DO I1=-1,1
          SHIFT=CENTER+(/I1,I2,I3/)
          TRIAL=DR-MATMUL(RBAS,REAL(SHIFT,KIND=8))
          R2=DOT_PRODUCT(TRIAL,TRIAL)
          IF(R2.LT.BEST2) THEN
            BEST2=R2
            IMAGE=POINT+TRIAL
          END IF
        END DO
      END DO
    END DO
    DISTANCE=SQRT(BEST2)
  END SUBROUTINE PAW_SKALA_NEAREST_IMAGE

  SUBROUTINE PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD,RBAS,WEIGHT)
    IMPLICIT NONE
    INTEGER(4),INTENT(IN) :: NAT
    REAL(8),INTENT(IN) :: POINT(3),ATOMCOORD(NAT,3),RBAS(3,3)
    REAL(8),INTENT(OUT) :: WEIGHT(NAT)
    REAL(8) :: IMAGE(NAT,3),DISTANCE(NAT),PAIR(3),RAB,MU,SWITCH,TOTAL
    REAL(8) :: AINV(3,3)
    INTEGER(4) :: I,J,IMIN

    CALL PAW_SKALA_INVERSE3(RBAS,AINV)
    DO I=1,NAT
      CALL PAW_SKALA_NEAREST_IMAGE(POINT,ATOMCOORD(I,:),RBAS &
 &                                 ,IMAGE(I,:),DISTANCE(I),AINV)
    END DO
    WEIGHT=1.D0
    DO I=1,NAT-1
      DO J=I+1,NAT
        PAIR=IMAGE(I,:)-IMAGE(J,:)
        RAB=SQRT(DOT_PRODUCT(PAIR,PAIR))
        IF(RAB.LE.1.D-14) CYCLE
        MU=(DISTANCE(I)-DISTANCE(J))/RAB
        MU=MAX(-1.D0,MIN(1.D0,MU))
        SWITCH=0.5D0*(1.D0-PAW_SKALA_BECKE_SHAPE(MU))
        WEIGHT(I)=WEIGHT(I)*SWITCH
        WEIGHT(J)=WEIGHT(J)*(1.D0-SWITCH)
      END DO
    END DO
    TOTAL=SUM(WEIGHT)
    IF(TOTAL.GT.0.D0) THEN
      WEIGHT=WEIGHT/TOTAL
    ELSE
      IMIN=MINLOC(DISTANCE,DIM=1)
      WEIGHT=0.D0
      WEIGHT(IMIN)=1.D0
    END IF
  END SUBROUTINE PAW_SKALA_SMOOTH_PARTITION

  SUBROUTINE PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES(POINT,NAT,ATOMCOORD &
 &                                                  ,RBAS,WEIGHT &
 &                                                  ,DWEIGHT_DATOM &
 &                                                  ,DWEIGHT_DPOINT &
 &                                                  ,DWEIGHT_DSTRAIN &
 &                                                  ,POINT_STRAIN_COORD)
    IMPLICIT NONE
    INTEGER(4),INTENT(IN) :: NAT
    REAL(8),INTENT(IN) :: POINT(3),ATOMCOORD(NAT,3),RBAS(3,3)
    REAL(8),INTENT(OUT) :: WEIGHT(NAT),DWEIGHT_DATOM(3,NAT,NAT)
    REAL(8),INTENT(OUT) :: DWEIGHT_DPOINT(3,NAT)
    REAL(8),INTENT(OUT),OPTIONAL :: DWEIGHT_DSTRAIN(3,3,NAT)
    REAL(8),INTENT(IN),OPTIONAL :: POINT_STRAIN_COORD(3)
    REAL(8) :: AINV(3,3),IMAGE(NAT,3),DISTANCE(NAT),RVECS(NAT,3)
    REAL(8) :: UNIT_RVEC(NAT,3),RAW_WEIGHT(NAT),DLOG(3,NAT,NAT)
    REAL(8) :: MEAN_DLOG(3,NAT),PAIR(3),UNIT_PAIR(3)
    REAL(8) :: RAB,DIST_DIFF,MU_RAW,MU,SWITCH,ONE_MINUS_SWITCH,DS_DMU
    REAL(8) :: DMU_I(3),DMU_J(3),DS_I(3),DS_J(3),TOTAL
    REAL(8) :: POINT_RESPONSE(3)
    INTEGER(4) :: I,J,K,IMIN,IDIR,JDIR

    WEIGHT=0.D0
    DWEIGHT_DATOM=0.D0
    DWEIGHT_DPOINT=0.D0
    IF(PRESENT(DWEIGHT_DSTRAIN)) DWEIGHT_DSTRAIN=0.D0
    RAW_WEIGHT=1.D0
    DLOG=0.D0
    CALL PAW_SKALA_INVERSE3(RBAS,AINV)
    DO I=1,NAT
      CALL PAW_SKALA_NEAREST_IMAGE(POINT,ATOMCOORD(I,:),RBAS &
 &                                 ,IMAGE(I,:),DISTANCE(I),AINV)
      RVECS(I,:)=POINT-IMAGE(I,:)
      IF(DISTANCE(I).GT.1.D-14) THEN
        UNIT_RVEC(I,:)=RVECS(I,:)/DISTANCE(I)
      ELSE
        UNIT_RVEC(I,:)=0.D0
      END IF
    END DO

    DO I=1,NAT-1
      DO J=I+1,NAT
        PAIR=IMAGE(I,:)-IMAGE(J,:)
        RAB=SQRT(DOT_PRODUCT(PAIR,PAIR))
        IF(RAB.LE.1.D-14) CYCLE
        UNIT_PAIR=PAIR/RAB
        DIST_DIFF=DISTANCE(I)-DISTANCE(J)
        MU_RAW=DIST_DIFF/RAB
        MU=MAX(-1.D0,MIN(1.D0,MU_RAW))
        SWITCH=0.5D0*(1.D0-PAW_SKALA_BECKE_SHAPE(MU))
        ONE_MINUS_SWITCH=1.D0-SWITCH
        DS_DMU=0.D0
        IF(ABS(MU_RAW).LT.1.D0) THEN
          DS_DMU=-0.5D0*PAW_SKALA_BECKE_SHAPE_DERIVATIVE(MU)
        END IF
        IF(ABS(DS_DMU).GT.0.D0.AND.SWITCH.GT.TINY(SWITCH) &
 &         .AND.ONE_MINUS_SWITCH.GT.TINY(ONE_MINUS_SWITCH)) THEN
          DMU_I=(-UNIT_RVEC(I,:)*RAB-DIST_DIFF*UNIT_PAIR)/RAB**2
          DMU_J=( UNIT_RVEC(J,:)*RAB+DIST_DIFF*UNIT_PAIR)/RAB**2
          DS_I=DS_DMU*DMU_I
          DS_J=DS_DMU*DMU_J
          DLOG(:,I,I)=DLOG(:,I,I)+DS_I/SWITCH
          DLOG(:,I,J)=DLOG(:,I,J)-DS_I/ONE_MINUS_SWITCH
          DLOG(:,J,I)=DLOG(:,J,I)+DS_J/SWITCH
          DLOG(:,J,J)=DLOG(:,J,J)-DS_J/ONE_MINUS_SWITCH
        END IF
        RAW_WEIGHT(I)=RAW_WEIGHT(I)*SWITCH
        RAW_WEIGHT(J)=RAW_WEIGHT(J)*ONE_MINUS_SWITCH
      END DO
    END DO

    TOTAL=SUM(RAW_WEIGHT)
    IF(TOTAL.LE.0.D0) THEN
      IMIN=MINLOC(DISTANCE,DIM=1)
      WEIGHT(IMIN)=1.D0
      RETURN
    END IF
    WEIGHT=RAW_WEIGHT/TOTAL
    MEAN_DLOG=0.D0
    DO I=1,NAT
      DO J=1,NAT
        MEAN_DLOG(:,J)=MEAN_DLOG(:,J)+WEIGHT(I)*DLOG(:,J,I)
      END DO
    END DO
    DO I=1,NAT
      DO J=1,NAT
        DWEIGHT_DATOM(:,J,I)=WEIGHT(I) &
 &                          *(DLOG(:,J,I)-MEAN_DLOG(:,J))
      END DO
      DO J=1,NAT
        DWEIGHT_DPOINT(:,I)=DWEIGHT_DPOINT(:,I) &
 &                         -DWEIGHT_DATOM(:,J,I)
      END DO
    END DO
    IF(PRESENT(DWEIGHT_DSTRAIN)) THEN
      POINT_RESPONSE=POINT
      IF(PRESENT(POINT_STRAIN_COORD)) POINT_RESPONSE=POINT_STRAIN_COORD
      DO I=1,NAT
        DO IDIR=1,3
          DO JDIR=1,3
            DWEIGHT_DSTRAIN(IDIR,JDIR,I)= &
 &              DWEIGHT_DPOINT(IDIR,I)*POINT_RESPONSE(JDIR)
            DO J=1,NAT
              DWEIGHT_DSTRAIN(IDIR,JDIR,I)= &
 &              DWEIGHT_DSTRAIN(IDIR,JDIR,I) &
 &             +DWEIGHT_DATOM(IDIR,J,I)*IMAGE(J,JDIR)
            END DO
          END DO
        END DO
      END DO
    END IF
  END SUBROUTINE PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES

  SUBROUTINE PAW_SKALA_GRID_TEST(MAXERROR)
    IMPLICIT NONE
    REAL(8),INTENT(OUT) :: MAXERROR
    INTEGER(4),PARAMETER :: NR1=12,NR2=11,NR3=10,NAT=2,NDIMD=2
    INTEGER(4),PARAMETER :: NBACK=4,NSBACK=2
    REAL(8) :: RBAS(3,3),FIELD(NR1,NR2,NR3),ADJOINT(NR1,NR2,NR3)
    REAL(8) :: RHO(NR1,NR2,NR3,NDIMD),TAU(NR1,NR2,NR3,NDIMD)
    REAL(8) :: GRHO(NR1,NR2,NR3,3,NDIMD)
    REAL(8) :: ADJRHO(NR1,NR2,NR3,NDIMD)
    REAL(8) :: ADJTAU(NR1,NR2,NR3,NDIMD)
    REAL(8) :: ADJGRHO(NR1,NR2,NR3,3,NDIMD)
    REAL(8) :: BACKRHO(NR1,NR2,NR3,NDIMD)
    REAL(8) :: BACKTAU(NR1,NR2,NR3,NDIMD)
    REAL(8) :: BACKGRHO(NR1,NR2,NR3,3,NDIMD)
    REAL(8) :: REFRHO(NR1,NR2,NR3,NDIMD)
    REAL(8) :: REFTAU(NR1,NR2,NR3,NDIMD)
    REAL(8) :: REFGRHO(NR1,NR2,NR3,3,NDIMD)
    REAL(8) :: BACKPOINT(NBACK,3),BACKDENSITY(NBACK,2)
    REAL(8) :: BACKGRAD(NBACK,3,2),BACKKIN(NBACK,2)
    REAL(8) :: POINT(3),POINT2(3),ATOMCOORD(NAT,3),WEIGHT(NAT),WEIGHT2(NAT)
    REAL(8) :: ATOMPERT(NAT,3),WEIGHTP(NAT),WEIGHTM(NAT)
    REAL(8) :: DWEIGHT_DATOM(3,NAT,NAT),DWEIGHT_DPOINT(3,NAT)
    REAL(8) :: DWEIGHT_DSTRAIN(3,3,NAT),DWEIGHT_DSTRAIN_LOCAL(3,3,NAT)
    REAL(8) :: RBASPERT(3,3),DEFORM(3,3),LOCALCENTER(3),LOCALOFFSET(3)
    REAL(8),ALLOCATABLE :: LOCALCOORD(:,:),LOCALWEIGHT(:)
    REAL(8) :: VALUE,VALUE1,LHS,RHS,GRAD(3),GRADFD(3),STEP,RCUT,VOLUME
    REAL(8) :: RHOVAL(NDIMD),TAUVAL(NDIMD),GRADVAL(3,NDIMD)
    REAL(8) :: RHOVALP(NDIMD),TAUVALP(NDIMD),GRADVALP(3,NDIMD)
    REAL(8) :: RHOVALM(NDIMD),TAUVALM(NDIMD),GRADVALM(3,NDIMD)
    REAL(8) :: DRHOVAL(3,NDIMD),DTAUVAL(3,NDIMD)
    REAL(8) :: DGRADVAL(3,3,NDIMD)
    REAL(8) :: RHOBAR(NDIMD),TAUBAR(NDIMD),GRADBAR(3,NDIMD)
    INTEGER(4) :: I1,I2,I3,IDIR,JDIR,IDIM,ICART,IAT,NANG,NLOCAL
    INTEGER(4) :: IP,IWORK,BACKINDEX(NSBACK)
    LOGICAL(4) :: TBACKACC

    RBAS=RESHAPE((/8.D0,0.D0,0.D0,1.2D0,7.D0,0.D0 &
 &                ,0.4D0,0.8D0,6.D0/),(/3,3/))
    DO I3=1,NR3
      DO I2=1,NR2
        DO I1=1,NR1
          FIELD(I1,I2,I3)=SIN(0.31D0*REAL(I1,KIND=8)) &
 &                       +COS(0.27D0*REAL(I2,KIND=8)) &
 &                       +0.03D0*REAL(I3**2,KIND=8)
        END DO
      END DO
    END DO
    POINT=MATMUL(RBAS,(/3.D0/NR1,4.D0/NR2,2.D0/NR3/))
    CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS,FIELD,POINT,VALUE)
    MAXERROR=ABS(VALUE-FIELD(4,5,3))
    MAXERROR=MAX(MAXERROR,ABS(9.D-12 &
 &      *PAW_SKALA_PARTITION_TAPER_DERIVATIVE(5.5D-12)-1.875D0))
    RCUT=4.D0
    STEP=1.D-6
    VALUE=PAW_SKALA_RADIAL_BLEND(3.6D0,RCUT)
    LHS=PAW_SKALA_RADIAL_BLEND(3.6D0+STEP,RCUT)
    RHS=PAW_SKALA_RADIAL_BLEND(3.6D0-STEP,RCUT)
    MAXERROR=MAX(MAXERROR,ABS(PAW_SKALA_RADIAL_BLEND_DERIVATIVE &
 &                 (3.6D0,RCUT)-(LHS-RHS)/(2.D0*STEP)))
    MAXERROR=MAX(MAXERROR,ABS(VALUE-0.5D0))
    MAXERROR=MAX(MAXERROR,ABS(PAW_SKALA_RADIAL_BLEND(3.2D0,RCUT)-1.D0))
    MAXERROR=MAX(MAXERROR,ABS(PAW_SKALA_RADIAL_BLEND(4.D0,RCUT)))

    POINT=MATMUL(RBAS,(/0.237D0,0.419D0,0.713D0/))
    VALUE1=-0.371D0
    CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS,FIELD,POINT,VALUE)
    ADJOINT=0.D0
    CALL PAW_SKALA_GRID_INTERPOLATION_ADJOINT(NR1,NR2,NR3,RBAS &
 &                                            ,ADJOINT,POINT,VALUE1)
    LHS=VALUE*VALUE1
    RHS=SUM(FIELD*ADJOINT)
    MAXERROR=MAX(MAXERROR,ABS(LHS-RHS))

    CALL PAW_SKALA_GRID_INTERPOLATE_GRADIENT(NR1,NR2,NR3,RBAS &
 &                                            ,FIELD,POINT,GRAD)
    STEP=1.D-5
    DO IDIR=1,3
      POINT2=POINT
      POINT2(IDIR)=POINT2(IDIR)+STEP
      CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS,FIELD,POINT2,LHS)
      POINT2(IDIR)=POINT(IDIR)-STEP
      CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS,FIELD,POINT2,RHS)
      GRADFD(IDIR)=(LHS-RHS)/(2.D0*STEP)
    END DO
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(GRAD-GRADFD)))

    DO IDIM=1,NDIMD
      RHO(:,:,:,IDIM)=(0.2D0+0.3D0*REAL(IDIM,KIND=8))*FIELD+0.1D0
      TAU(:,:,:,IDIM)=(-0.4D0+0.2D0*REAL(IDIM,KIND=8))*FIELD-0.3D0
      DO ICART=1,3
        GRHO(:,:,:,ICART,IDIM)=REAL(ICART+2*IDIM,KIND=8)*FIELD/7.D0
      END DO
    END DO
    CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES(NR1,NR2,NR3,RBAS,NDIMD &
 &                                             ,RHO,GRHO,TAU,POINT &
 &                                             ,RHOVAL,GRADVAL,TAUVAL &
 &                                             ,DRHOVAL,DGRADVAL,DTAUVAL)
    DO IDIM=1,NDIMD
      CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS &
 &                                   ,RHO(:,:,:,IDIM),POINT,VALUE)
      MAXERROR=MAX(MAXERROR,ABS(RHOVAL(IDIM)-VALUE))
      CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS &
 &                                   ,TAU(:,:,:,IDIM),POINT,VALUE)
      MAXERROR=MAX(MAXERROR,ABS(TAUVAL(IDIM)-VALUE))
      DO ICART=1,3
        CALL PAW_SKALA_GRID_INTERPOLATE(NR1,NR2,NR3,RBAS &
 &                              ,GRHO(:,:,:,ICART,IDIM),POINT,VALUE)
        MAXERROR=MAX(MAXERROR,ABS(GRADVAL(ICART,IDIM)-VALUE))
      END DO
    END DO
    STEP=1.D-5
    DO IDIR=1,3
      POINT2=POINT
      POINT2(IDIR)=POINT2(IDIR)+STEP
      CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
 &         (NR1,NR2,NR3,RBAS,NDIMD,RHO,GRHO,TAU,POINT2 &
 &         ,RHOVALP,GRADVALP,TAUVALP)
      POINT2(IDIR)=POINT(IDIR)-STEP
      CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
 &         (NR1,NR2,NR3,RBAS,NDIMD,RHO,GRHO,TAU,POINT2 &
 &         ,RHOVALM,GRADVALM,TAUVALM)
      MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DRHOVAL(IDIR,:) &
 &                                  -(RHOVALP-RHOVALM)/(2.D0*STEP))))
      MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DTAUVAL(IDIR,:) &
 &                                  -(TAUVALP-TAUVALM)/(2.D0*STEP))))
      MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DGRADVAL(:,IDIR,:) &
 &                                  -(GRADVALP-GRADVALM)/(2.D0*STEP))))
    END DO
    LOCALCENTER=MATMUL(RBAS,(/0.19D0,0.37D0,0.43D0/))
    LOCALOFFSET=(/0.17D0,-0.11D0,0.09D0/)
    POINT=LOCALCENTER+LOCALOFFSET
    CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES(NR1,NR2,NR3,RBAS,NDIMD &
 &                                             ,RHO,GRHO,TAU,POINT &
 &                                             ,RHOVAL,GRADVAL,TAUVAL &
 &                                             ,DRHOVAL,DGRADVAL,DTAUVAL)
    STEP=3.D-6
    DO IDIR=1,3
      DO JDIR=1,3
        DEFORM=0.D0
        DEFORM(1,1)=1.D0
        DEFORM(2,2)=1.D0
        DEFORM(3,3)=1.D0
        DEFORM(IDIR,JDIR)=DEFORM(IDIR,JDIR)+STEP
        RBASPERT=MATMUL(DEFORM,RBAS)
        POINT2=MATMUL(DEFORM,LOCALCENTER)+LOCALOFFSET
        CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
 &           (NR1,NR2,NR3,RBASPERT,NDIMD,RHO,GRHO,TAU,POINT2 &
 &           ,RHOVALP,GRADVALP,TAUVALP)
        DEFORM(IDIR,JDIR)=DEFORM(IDIR,JDIR)-2.D0*STEP
        RBASPERT=MATMUL(DEFORM,RBAS)
        POINT2=MATMUL(DEFORM,LOCALCENTER)+LOCALOFFSET
        CALL PAW_SKALA_GRID_INTERPOLATE_PRIMITIVES &
 &           (NR1,NR2,NR3,RBASPERT,NDIMD,RHO,GRHO,TAU,POINT2 &
 &           ,RHOVALM,GRADVALM,TAUVALM)
        MAXERROR=MAX(MAXERROR,MAXVAL(ABS(-DRHOVAL(IDIR,:) &
 &                    *LOCALOFFSET(JDIR)-(RHOVALP-RHOVALM)/(2.D0*STEP))))
        MAXERROR=MAX(MAXERROR,MAXVAL(ABS(-DTAUVAL(IDIR,:) &
 &                    *LOCALOFFSET(JDIR)-(TAUVALP-TAUVALM)/(2.D0*STEP))))
        MAXERROR=MAX(MAXERROR,MAXVAL(ABS(-DGRADVAL(:,IDIR,:) &
 &                    *LOCALOFFSET(JDIR)-(GRADVALP-GRADVALM)/(2.D0*STEP))))
      END DO
    END DO
    RHOBAR=(/0.31D0,-0.27D0/)
    TAUBAR=(/-0.19D0,0.23D0/)
    GRADBAR=RESHAPE((/0.11D0,-0.13D0,0.17D0,-0.29D0,0.37D0,-0.41D0/) &
 &                 ,SHAPE(GRADBAR))
    ADJRHO=0.D0
    ADJGRHO=0.D0
    ADJTAU=0.D0
    CALL PAW_SKALA_GRID_PRIMITIVES_ADJOINT(NR1,NR2,NR3,RBAS,NDIMD &
 &                                         ,ADJRHO,ADJGRHO,ADJTAU,POINT &
 &                                         ,RHOBAR,GRADBAR,TAUBAR)
    LHS=SUM(RHOVAL*RHOBAR)+SUM(GRADVAL*GRADBAR)+SUM(TAUVAL*TAUBAR)
    RHS=SUM(RHO*ADJRHO)+SUM(GRHO*ADJGRHO)+SUM(TAU*ADJTAU)
    MAXERROR=MAX(MAXERROR,ABS(LHS-RHS))

    BACKINDEX(1)=1
    BACKINDEX(2)=2+NR1*((3-1)+NR2*(4-1))
    BACKPOINT=0.D0
    BACKPOINT(3,:)=MATMUL(RBAS,(/0.237D0,0.419D0,0.713D0/))
    BACKPOINT(4,:)=MATMUL(RBAS,(/0.913D0,0.071D0,0.337D0/))
    DO IP=1,NBACK
      BACKDENSITY(IP,1)=0.07D0*REAL(IP,KIND=8)-0.19D0
      BACKDENSITY(IP,2)=-0.05D0*REAL(IP,KIND=8)+0.11D0
      BACKKIN(IP,1)=0.03D0*REAL(IP,KIND=8)+0.13D0
      BACKKIN(IP,2)=-0.09D0*REAL(IP,KIND=8)+0.17D0
      DO ICART=1,3
        BACKGRAD(IP,ICART,1)=0.01D0*REAL(IP+2*ICART,KIND=8)
        BACKGRAD(IP,ICART,2)=-0.02D0*REAL(2*IP+ICART,KIND=8)
      END DO
    END DO
    REFRHO=0.D0
    REFGRHO=0.D0
    REFTAU=0.D0
    DO IP=1,NSBACK
      IWORK=BACKINDEX(IP)-1
      I1=MOD(IWORK,NR1)+1
      IWORK=IWORK/NR1
      I2=MOD(IWORK,NR2)+1
      I3=IWORK/NR2+1
      DO IDIM=1,NDIMD
        VALUE=MERGE(1.D0,-1.D0,IDIM.EQ.1)
        REFRHO(I1,I2,I3,IDIM)=REFRHO(I1,I2,I3,IDIM) &
 &        +0.5D0*(BACKDENSITY(IP,1)+VALUE*BACKDENSITY(IP,2))
        REFTAU(I1,I2,I3,IDIM)=REFTAU(I1,I2,I3,IDIM) &
 &        +0.5D0*(BACKKIN(IP,1)+VALUE*BACKKIN(IP,2))
        DO ICART=1,3
          REFGRHO(I1,I2,I3,ICART,IDIM)= &
 &          REFGRHO(I1,I2,I3,ICART,IDIM) &
 &          +0.5D0*(BACKGRAD(IP,ICART,1) &
 &                  +VALUE*BACKGRAD(IP,ICART,2))
        END DO
      END DO
    END DO
    DO IP=NSBACK+1,NBACK
      DO IDIM=1,NDIMD
        VALUE=MERGE(1.D0,-1.D0,IDIM.EQ.1)
        RHOBAR(IDIM)=0.5D0*(BACKDENSITY(IP,1) &
 &                                +VALUE*BACKDENSITY(IP,2))
        TAUBAR(IDIM)=0.5D0*(BACKKIN(IP,1)+VALUE*BACKKIN(IP,2))
        DO ICART=1,3
          GRADBAR(ICART,IDIM)=0.5D0*(BACKGRAD(IP,ICART,1) &
 &                                         +VALUE*BACKGRAD(IP,ICART,2))
        END DO
      END DO
      CALL PAW_SKALA_GRID_PRIMITIVES_ADJOINT(NR1,NR2,NR3,RBAS,NDIMD &
 &                                           ,REFRHO,REFGRHO,REFTAU &
 &                                           ,BACKPOINT(IP,:),RHOBAR &
 &                                           ,GRADBAR,TAUBAR)
    END DO
    BACKRHO=0.D0
    BACKGRHO=0.D0
    BACKTAU=0.D0
    CALL PAW_SKALA_GRID_BACK_BEGIN(NR1,NR2,NR3,NDIMD &
 &                                ,BACKRHO,BACKGRHO,BACKTAU,TBACKACC)
    CALL PAW_SKALA_GRID_BACKPROJECT(NR1,NR2,NR3,RBAS,NDIMD &
 &                                 ,NSBACK,NBACK,BACKINDEX,BACKPOINT &
 &                                 ,BACKDENSITY,BACKGRAD,BACKKIN &
 &                                 ,BACKRHO,BACKGRHO,BACKTAU,TBACKACC)
    CALL PAW_SKALA_GRID_BACK_END(NR1,NR2,NR3,NDIMD &
 &                              ,BACKRHO,BACKGRHO,BACKTAU,TBACKACC)
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(BACKRHO-REFRHO)))
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(BACKGRHO-REFGRHO)))
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(BACKTAU-REFTAU)))

    ATOMCOORD(1,:)=MATMUL(RBAS,(/0.1D0,0.2D0,0.3D0/))
    ATOMCOORD(2,:)=MATMUL(RBAS,(/0.6D0,0.2D0,0.3D0/))
    POINT=0.5D0*(ATOMCOORD(1,:)+ATOMCOORD(2,:))
    CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMCOORD,RBAS,WEIGHT)
    POINT2=POINT+RBAS(:,1)
    CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMCOORD,RBAS,WEIGHT2)
    MAXERROR=MAX(MAXERROR,ABS(SUM(WEIGHT)-1.D0))
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(WEIGHT-WEIGHT2)))
    MAXERROR=MAX(MAXERROR,ABS(WEIGHT(1)-0.5D0),ABS(WEIGHT(2)-0.5D0))
    MAXERROR=MAX(MAXERROR,ABS(PAW_SKALA_PARTITION_TAPER(0.D0)))
    MAXERROR=MAX(MAXERROR,ABS(PAW_SKALA_PARTITION_TAPER(1.D0)-1.D0))

    POINT=MATMUL(RBAS,(/0.31D0,0.23D0,0.37D0/))
    CALL PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES(POINT,NAT,ATOMCOORD,RBAS &
 &                                             ,WEIGHT,DWEIGHT_DATOM &
 &                                             ,DWEIGHT_DPOINT &
 &                                             ,DWEIGHT_DSTRAIN)
    STEP=1.D-6
    DO IAT=1,NAT
      DO IDIR=1,3
        ATOMPERT=ATOMCOORD
        ATOMPERT(IAT,IDIR)=ATOMPERT(IAT,IDIR)+STEP
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMPERT,RBAS,WEIGHTP)
        ATOMPERT(IAT,IDIR)=ATOMPERT(IAT,IDIR)-2.D0*STEP
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT,NAT,ATOMPERT,RBAS,WEIGHTM)
        MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DWEIGHT_DATOM(IDIR,IAT,:) &
 &                                -(WEIGHTP-WEIGHTM)/(2.D0*STEP))))
      END DO
    END DO
    DO IDIR=1,3
      POINT2=POINT
      POINT2(IDIR)=POINT2(IDIR)+STEP
      CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMCOORD,RBAS,WEIGHTP)
      POINT2(IDIR)=POINT(IDIR)-STEP
      CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMCOORD,RBAS,WEIGHTM)
      MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DWEIGHT_DPOINT(IDIR,:) &
 &                              -(WEIGHTP-WEIGHTM)/(2.D0*STEP))))
    END DO
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(SUM(DWEIGHT_DATOM,DIM=3))))
    MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DWEIGHT_DPOINT &
 &                                 +SUM(DWEIGHT_DATOM,DIM=2))))
    DO IDIR=1,3
      DO JDIR=1,3
        DEFORM=0.D0
        DEFORM(1,1)=1.D0
        DEFORM(2,2)=1.D0
        DEFORM(3,3)=1.D0
        DEFORM(IDIR,JDIR)=DEFORM(IDIR,JDIR)+STEP
        RBASPERT=MATMUL(DEFORM,RBAS)
        ATOMPERT=TRANSPOSE(MATMUL(DEFORM,TRANSPOSE(ATOMCOORD)))
        POINT2=MATMUL(DEFORM,POINT)
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMPERT,RBASPERT &
 &                                     ,WEIGHTP)
        DEFORM(IDIR,JDIR)=DEFORM(IDIR,JDIR)-2.D0*STEP
        RBASPERT=MATMUL(DEFORM,RBAS)
        ATOMPERT=TRANSPOSE(MATMUL(DEFORM,TRANSPOSE(ATOMCOORD)))
        POINT2=MATMUL(DEFORM,POINT)
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMPERT,RBASPERT &
 &                                     ,WEIGHTM)
        MAXERROR=MAX(MAXERROR,MAXVAL(ABS(DWEIGHT_DSTRAIN(IDIR,JDIR,:) &
 &                              -(WEIGHTP-WEIGHTM)/(2.D0*STEP))))
      END DO
    END DO

    LOCALOFFSET=(/0.17D0,-0.11D0,0.09D0/)
    POINT=ATOMCOORD(1,:)+LOCALOFFSET
    CALL PAW_SKALA_SMOOTH_PARTITION_DERIVATIVES(POINT,NAT,ATOMCOORD,RBAS &
 &                                             ,WEIGHT,DWEIGHT_DATOM &
 &                                             ,DWEIGHT_DPOINT &
 &                                             ,DWEIGHT_DSTRAIN_LOCAL &
 &                                             ,ATOMCOORD(1,:))
    DO IDIR=1,3
      DO JDIR=1,3
        DEFORM=0.D0
        DEFORM(1,1)=1.D0
        DEFORM(2,2)=1.D0
        DEFORM(3,3)=1.D0
        DEFORM(IDIR,JDIR)=DEFORM(IDIR,JDIR)+STEP
        RBASPERT=MATMUL(DEFORM,RBAS)
        ATOMPERT=TRANSPOSE(MATMUL(DEFORM,TRANSPOSE(ATOMCOORD)))
        POINT2=ATOMPERT(1,:)+LOCALOFFSET
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMPERT,RBASPERT &
 &                                     ,WEIGHTP)
        DEFORM(IDIR,JDIR)=DEFORM(IDIR,JDIR)-2.D0*STEP
        RBASPERT=MATMUL(DEFORM,RBAS)
        ATOMPERT=TRANSPOSE(MATMUL(DEFORM,TRANSPOSE(ATOMCOORD)))
        POINT2=ATOMPERT(1,:)+LOCALOFFSET
        CALL PAW_SKALA_SMOOTH_PARTITION(POINT2,NAT,ATOMPERT,RBASPERT &
 &                                     ,WEIGHTM)
        MAXERROR=MAX(MAXERROR &
 &            ,MAXVAL(ABS(DWEIGHT_DSTRAIN_LOCAL(IDIR,JDIR,:) &
 &                        -(WEIGHTP-WEIGHTM)/(2.D0*STEP))))
      END DO
    END DO

    RCUT=2.3D0
    CALL PAW_SKALA_LOCAL_GRID_SIZE(20,17,NANG,NLOCAL,3)
    ALLOCATE(LOCALCOORD(NLOCAL,3),LOCALWEIGHT(NLOCAL))
    CALL PAW_SKALA_LOCAL_GRID(20,RCUT,17,NLOCAL,LOCALCOORD,LOCALWEIGHT,3)
    VOLUME=4.D0*ACOS(-1.D0)*RCUT**3/3.D0
    MAXERROR=MAX(MAXERROR,ABS(SUM(LOCALWEIGHT)-VOLUME))
    MAXERROR=MAX(MAXERROR,ABS(SUM(LOCALWEIGHT*LOCALCOORD(:,1)**2) &
 &                              -4.D0*ACOS(-1.D0)*RCUT**5/15.D0))
    DEALLOCATE(LOCALCOORD,LOCALWEIGHT)
  END SUBROUTINE PAW_SKALA_GRID_TEST

END MODULE PAW_SKALA_GRID_MODULE
