MODULE PAW_SPIN_QUADRATURE_MODULE
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: PAW_SPIN_POLAR_GRID,PAW_SPIN_FRAME_PREPARE,PAW_SPIN_FRAME_PULLBACK
  PUBLIC :: PAW_SPIN_MOMENT,PAW_SPIN_MOMENT_PULLBACK,PAW_SPIN_FRAME
  PUBLIC :: PAW_SPIN_POLAR_IBP_GRID
  INTEGER,PARAMETER,PUBLIC :: PAW_SPIN_MAX_AZIMUTHAL=1024
  INTEGER,PARAMETER,PUBLIC :: PAW_SPIN_GAUGES=2
  REAL(8),PARAMETER :: DENSITY_FLOOR=1.D-12,AMPLITUDE_SCALE=1.D-4,CONDITION_SCALE=1.D-4
  TYPE PAW_SPIN_FRAME
    REAL(8) :: ROTATION(3,3,PAW_SPIN_GAUGES),AXIS(3),RESOLVENT(3,3)
    REAL(8) :: BASIS_RESPONSE(3,3,3,PAW_SPIN_GAUGES)
    REAL(8) :: GAUGE_WEIGHT(PAW_SPIN_GAUGES),GAUGE_RESPONSE(3,PAW_SPIN_GAUGES)
    REAL(8) :: BLEND,BLEND_COV(3,3),BLEND_NORM
  END TYPE
CONTAINS
  RECURSIVE PURE FUNCTION WEIGHT_SUM(WEIGHT) RESULT(TOTAL)
    REAL(8),INTENT(IN) :: WEIGHT(:)
    REAL(8) :: TOTAL
    INTEGER :: N
    N=SIZE(WEIGHT)
    ! Pairwise reduction avoids false normalization failures on fine product grids.
    IF(N.LE.32) THEN
      TOTAL=SUM(WEIGHT)
    ELSE
      TOTAL=WEIGHT_SUM(WEIGHT(:N/2))+WEIGHT_SUM(WEIGHT(N/2+1:))
    END IF
  END FUNCTION

  PURE FUNCTION OUTER(A,B) RESULT(C)
    REAL(8),INTENT(IN) :: A(3),B(3)
    REAL(8) :: C(3,3)
    INTEGER :: I
    DO I=1,3
      C(:,I)=A*B(I)
    END DO
  END FUNCTION

  PURE FUNCTION CROSS(A,B) RESULT(C)
    REAL(8),INTENT(IN) :: A(3),B(3)
    REAL(8) :: C(3)
    C=[A(2)*B(3)-A(3)*B(2),A(3)*B(1)-A(1)*B(3),A(1)*B(2)-A(2)*B(1)]
  END FUNCTION

  PURE SUBROUTINE SWITCH(X,Y,DY)
    REAL(8),INTENT(IN) :: X
    REAL(8),INTENT(OUT) :: Y,DY
    IF(X.LE.0.D0) THEN
      Y=0.D0
      DY=0.D0
    ELSE IF(X.GE.1.D0) THEN
      Y=1.D0
      DY=0.D0
    ELSE
      Y=X**3*(10.D0-15.D0*X+6.D0*X**2)
      DY=30.D0*X**2*(1.D0-X)**2
    END IF
  END SUBROUTINE

  SUBROUTINE PAW_SPIN_POLAR_GRID(NPOL,NPHI,AXIS,WEIGHT)
    INTEGER,INTENT(IN) :: NPOL,NPHI
    REAL(8),ALLOCATABLE,INTENT(OUT) :: AXIS(:,:),WEIGHT(:)
    REAL(8),ALLOCATABLE :: JACOBI(:,:),NODES(:),VECTORS(:,:)
    REAL(8) :: U,MU,W,PHI,RADIUS,BETA,PI
    INTEGER :: I,J,S,Q
    IF(NPOL.LT.8.OR.NPOL.GT.1024.OR.NPHI.LT.8.OR.NPHI.GT.PAW_SPIN_MAX_AZIMUTHAL.OR.MOD(NPHI,4).NE.0) &
      ERROR STOP 'Polar spin grid requires 8..1024 polar and azimuthal points, azimuthal in multiples of four'
    ALLOCATE(JACOBI(NPOL,NPOL),NODES(NPOL),VECTORS(NPOL,NPOL))
    JACOBI=0.D0
    DO I=1,NPOL-1
      BETA=REAL(I,8)/SQRT(4.D0*REAL(I,8)**2-1.D0)
      JACOBI(I,I+1)=BETA
      JACOBI(I+1,I)=BETA
    END DO
    ! Golub-Welsch Gauss-Legendre rule. Each hemisphere uses mu=+/- (1-u^3).
    ! The cubic map resolves the fractional-power end-point spin response.
    CALL LIB_LAPACK_DSYEV(NPOL,JACOBI,NODES,VECTORS)
    ALLOCATE(AXIS(3,2*NPOL*NPHI),WEIGHT(2*NPOL*NPHI))
    PI=ACOS(-1.D0)
    Q=0
    DO S=-1,1,2
      DO I=1,NPOL
        U=0.5D0*(NODES(I)+1.D0)
        MU=REAL(S,8)*(1.D0-U**3)
        W=1.5D0*VECTORS(1,I)**2*U**2/REAL(NPHI,8)
        RADIUS=SQRT(MAX(0.D0,1.D0-MU**2))
        DO J=0,NPHI-1
          Q=Q+1
          PHI=2.D0*PI*REAL(J,8)/REAL(NPHI,8)
          AXIS(:,Q)=[RADIUS*COS(PHI),RADIUS*SIN(PHI),MU]
          WEIGHT(Q)=W
        END DO
      END DO
    END DO
    IF(ANY(.NOT.IEEE_IS_FINITE(AXIS)).OR.ANY(.NOT.IEEE_IS_FINITE(WEIGHT)) &
       .OR.ANY(WEIGHT.LE.0.D0).OR.ABS(WEIGHT_SUM(WEIGHT)-1.D0).GT.1.D-12) &
      ERROR STOP 'Invalid normalized polar spin quadrature'
  END SUBROUTINE

  SUBROUTINE PAW_SPIN_POLAR_IBP_GRID(NPOL,NPHI,AXIS,WEIGHT,COEFFICIENT,RESPONSE)
    INTEGER,INTENT(IN) :: NPOL,NPHI
    REAL(8),ALLOCATABLE,INTENT(OUT) :: AXIS(:,:),WEIGHT(:),COEFFICIENT(:),RESPONSE(:,:)
    REAL(8),ALLOCATABLE :: JACOBI(:,:),NODES(:),VECTORS(:,:)
    REAL(8) :: THETA,PHI,BETA,PI
    INTEGER :: I,J,S,Q,NQ
    IF(NPOL.LT.8.OR.NPOL.GT.1024.OR.NPHI.LT.8.OR.NPHI.GT.PAW_SPIN_MAX_AZIMUTHAL.OR.MOD(NPHI,4).NE.0) &
      ERROR STOP 'Polar IBP grid requires 8..1024 polar and azimuthal points, azimuthal in multiples of four'
    ALLOCATE(JACOBI(NPOL,NPOL),NODES(NPOL),VECTORS(NPOL,NPOL))
    JACOBI=0.D0
    DO I=1,NPOL-1
      BETA=REAL(I,8)/SQRT(4.D0*REAL(I,8)**2-1.D0)
      JACOBI(I,I+1)=BETA
      JACOBI(I+1,I)=BETA
    END DO
    CALL LIB_LAPACK_DSYEV(NPOL,JACOBI,NODES,VECTORS)
    NQ=2+2*NPOL*NPHI
    ALLOCATE(AXIS(3,NQ),WEIGHT(NQ),COEFFICIENT(NQ),RESPONSE(3,NQ))
    AXIS=0.D0
    AXIS(3,1)=1.D0
    AXIS(3,2)=-1.D0
    WEIGHT(:2)=0.25D0
    COEFFICIENT=0.D0
    COEFFICIENT(:2)=2.D0
    RESPONSE=0.D0
    PI=ACOS(-1.D0)
    Q=2
    ! The two poles give [F(z)+F(-z)]/2. The remaining nodes integrate
    ! n(phi).grad_e F in dtheta dphi/(4 pi), not the original sphere measure.
    DO S=-1,1,2
      DO I=1,NPOL
        THETA=0.25D0*PI*(NODES(I)+1.D0)
        DO J=0,NPHI-1
          Q=Q+1
          PHI=2.D0*PI*REAL(J,8)/REAL(NPHI,8)
          AXIS(:,Q)=[SIN(THETA)*COS(PHI),SIN(THETA)*SIN(PHI),REAL(S,8)*COS(THETA)]
          WEIGHT(Q)=0.25D0*VECTORS(1,I)**2/REAL(NPHI,8)
          RESPONSE(:,Q)=PI*[COS(PHI),SIN(PHI),0.D0]
        END DO
      END DO
    END DO
    IF(ANY(.NOT.IEEE_IS_FINITE(AXIS)).OR.ANY(.NOT.IEEE_IS_FINITE(WEIGHT)) &
       .OR.ANY(.NOT.IEEE_IS_FINITE(RESPONSE)).OR.ANY(WEIGHT.LE.0.D0) &
       .OR.ABS(WEIGHT_SUM(WEIGHT)-1.D0).GT.1.D-12) ERROR STOP 'Invalid polar IBP spin quadrature'
  END SUBROUTINE

  SUBROUTINE ROW_MOMENT(R,G,T,N,U,V,Z,A,S,B)
    REAL(8),INTENT(IN) :: R(4),G(3,4),T(4)
    REAL(8),INTENT(OUT) :: N,U(3),V(3,3),Z(3),A,S(3,3),B(3,3)
    INTEGER :: J
    N=MAX(R(1),DENSITY_FLOOR)
    U=R(2:4)/N
    V=G(:,2:4)/N**(4.D0/3.D0)
    Z=T(2:4)/N**(5.D0/3.D0)
    A=MAX(0.D0,1.D0-SUM(U**2))
    S=OUTER(Z,Z)
    DO J=1,3
      S=S+OUTER(V(J,:),V(J,:))
    END DO
    B=OUTER(U,U)+A**2*S
  END SUBROUTINE

  SUBROUTINE PAW_SPIN_MOMENT(NP,R,G,T,W,C,NORM)
    INTEGER,INTENT(IN) :: NP
    REAL(8),INTENT(IN) :: R(NP,4),G(NP,3,4),T(NP,4),W(NP)
    REAL(8),INTENT(OUT) :: C(3,3),NORM
    REAL(8) :: N,U(3),V(3,3),Z(3),A,S(3,3),B(3,3)
    INTEGER :: I
    C=0.D0
    NORM=0.D0
    DO I=1,NP
      CALL ROW_MOMENT(R(I,:),G(I,:,:),T(I,:),N,U,V,Z,A,S,B)
      C=C+ABS(W(I))*N*B
      NORM=NORM+ABS(W(I))*N
    END DO
    IF(ANY(.NOT.IEEE_IS_FINITE(C)).OR..NOT.IEEE_IS_FINITE(NORM)) ERROR STOP 'Nonfinite spin-frame moment'
  END SUBROUTINE

  SUBROUTINE PAW_SPIN_MOMENT_PULLBACK(NP,R,G,T,W,BC,BNORM,DR,DG,DT,DW)
    INTEGER,INTENT(IN) :: NP
    REAL(8),INTENT(IN) :: R(NP,4),G(NP,3,4),T(NP,4),W(NP),BC(3,3),BNORM
    REAL(8),INTENT(INOUT) :: DR(NP,4),DG(NP,3,4),DT(NP,4),DW(NP)
    REAL(8) :: N,U(3),V(3,3),Z(3),A,S(3,3),B(3,3),H(3,3),MASS,L,DN,DA
    REAL(8) :: DU(3),DV(3,3),DZ(3)
    INTEGER :: I,J
    H=0.5D0*(BC+TRANSPOSE(BC))
    DO I=1,NP
      CALL ROW_MOMENT(R(I,:),G(I,:,:),T(I,:),N,U,V,Z,A,S,B)
      MASS=ABS(W(I))*N
      L=SUM(H*B)
      DU=2.D0*MASS*MATMUL(H,U)
      IF(A.GT.0.D0) THEN
        DA=2.D0*MASS*A*SUM(H*S)
        DU=DU-2.D0*DA*U
      END IF
      DO J=1,3
        DV(J,:)=2.D0*MASS*A**2*MATMUL(H,V(J,:))
      END DO
      DZ=2.D0*MASS*A**2*MATMUL(H,Z)
      DR(I,2:4)=DR(I,2:4)+DU/N
      DG(I,:,2:4)=DG(I,:,2:4)+DV/N**(4.D0/3.D0)
      DT(I,2:4)=DT(I,2:4)+DZ/N**(5.D0/3.D0)
      DN=ABS(W(I))*(L+BNORM)-(SUM(DU*U)+(4.D0/3.D0)*SUM(DV*V)+(5.D0/3.D0)*SUM(DZ*Z))/N
      IF(R(I,1).GT.DENSITY_FLOOR) DR(I,1)=DR(I,1)+DN
      IF(W(I).NE.0.D0) DW(I)=DW(I)+SIGN(1.D0,W(I))*N*(L+BNORM)
    END DO
  END SUBROUTINE

  SUBROUTINE PAW_SPIN_FRAME_PREPARE(NP,R,G,T,W,FRAME)
    INTEGER,INTENT(IN) :: NP
    REAL(8),INTENT(IN) :: R(NP,4),G(NP,3,4),T(NP,4),W(NP)
    TYPE(PAW_SPIN_FRAME),INTENT(OUT) :: FRAME
    REAL(8) :: C(3,3),NORM,SCALE,E(3),U(3,3),CONDITION,AMPLITUDE,FAMP,DAMP,FCOND,DCOND
    REAL(8) :: DERIV(3),REF(3),X(3),Y(3),Z(3),DZ(3),DV(3),DX(3),V(3),VN
    REAL(8) :: LENGTH2(2),DLENGTH2(3,2),POWER(2),DPOWER(3,2),DENOMINATOR
    INTEGER :: I,J,K
    FRAME%ROTATION=0.D0
    FRAME%AXIS=0.D0
    FRAME%RESOLVENT=0.D0
    FRAME%BASIS_RESPONSE=0.D0
    FRAME%GAUGE_WEIGHT=0.D0
    FRAME%GAUGE_RESPONSE=0.D0
    FRAME%BLEND=0.D0
    FRAME%BLEND_COV=0.D0
    FRAME%BLEND_NORM=0.D0
    DO I=1,3
      FRAME%ROTATION(I,I,:)=1.D0
    END DO
    CALL PAW_SPIN_MOMENT(NP,R,G,T,W,C,NORM)
    SCALE=MAXVAL(ABS(C))
    IF(SCALE.EQ.0.D0.OR.NORM.EQ.0.D0) RETURN
    CALL LIB_LAPACK_DSYEV(3,C/SCALE,E,U)
    IF(E(3).LE.0.D0) RETURN
    AMPLITUDE=(C(1,1)+C(2,2)+C(3,3))/NORM
    CONDITION=(1.D0-E(1)/E(3))*(1.D0-E(2)/E(3))
    CALL SWITCH(AMPLITUDE/AMPLITUDE_SCALE,FAMP,DAMP)
    CALL SWITCH(CONDITION/CONDITION_SCALE,FCOND,DCOND)
    DAMP=DAMP/AMPLITUDE_SCALE
    DCOND=DCOND/CONDITION_SCALE
    FRAME%BLEND=FAMP*FCOND
    IF(FRAME%BLEND.EQ.0.D0) RETURN
    DERIV(1)=-(1.D0-E(2)/E(3))/E(3)
    DERIV(2)=-(1.D0-E(1)/E(3))/E(3)
    DERIV(3)=(E(1)+E(2))/E(3)**2-2.D0*E(1)*E(2)/E(3)**3
    DO I=1,3
      FRAME%BLEND_COV=FRAME%BLEND_COV+FAMP*DCOND*DERIV(I)*OUTER(U(:,I),U(:,I))/SCALE
      FRAME%BLEND_COV(I,I)=FRAME%BLEND_COV(I,I)+FCOND*DAMP/NORM
    END DO
    FRAME%BLEND_NORM=-FCOND*DAMP*AMPLITUDE/NORM
    Z=U(:,3)
    FRAME%AXIS=Z
    DO I=1,2
      FRAME%RESOLVENT=FRAME%RESOLVENT+OUTER(U(:,I),U(:,I))/(SCALE*(E(3)-E(I)))
    END DO
    ! Only the principal eigenvector is differentiated. A degenerate lower
    ! pair is harmless; a closing principal gap is smoothly switched off.
    ! Average two smooth azimuthal gauges. Their weights vanish quartically
    ! at their respective poles, avoiding a discontinuous least-axis pivot.
    DO K=1,PAW_SPIN_GAUGES
      REF=0.D0
      REF(K)=1.D0
      V=REF-Z*Z(K)
      LENGTH2(K)=SUM(V**2)
      DO J=1,3
        DZ=0.D0
        DZ(J)=1.D0
        DV=-Z(K)*DZ-Z*REF(J)
        DLENGTH2(J,K)=2.D0*SUM(V*DV)
      END DO
      POWER(K)=LENGTH2(K)**2
      DPOWER(:,K)=2.D0*LENGTH2(K)*DLENGTH2(:,K)
      IF(LENGTH2(K).EQ.0.D0) CYCLE
      VN=SQRT(LENGTH2(K))
      X=V/VN
      Y=CROSS(Z,X)
      FRAME%ROTATION(:,1,K)=X
      FRAME%ROTATION(:,2,K)=Y
      FRAME%ROTATION(:,3,K)=Z
      DO J=1,3
        DZ=0.D0
        DZ(J)=1.D0
        DV=-Z(K)*DZ-Z*REF(J)
        DX=(DV-X*SUM(X*DV))/VN
        FRAME%BASIS_RESPONSE(:,1,J,K)=DX
        FRAME%BASIS_RESPONSE(:,2,J,K)=CROSS(DZ,X)+CROSS(Z,DX)
        FRAME%BASIS_RESPONSE(:,3,J,K)=DZ
      END DO
    END DO
    DENOMINATOR=SUM(POWER)
    FRAME%GAUGE_WEIGHT=POWER/DENOMINATOR
    FRAME%GAUGE_RESPONSE(:,1)=(DPOWER(:,1)-FRAME%GAUGE_WEIGHT(1)*SUM(DPOWER,DIM=2))/DENOMINATOR
    FRAME%GAUGE_RESPONSE(:,2)=-FRAME%GAUGE_RESPONSE(:,1)
  END SUBROUTINE

  SUBROUTINE PAW_SPIN_FRAME_PULLBACK(NP,R,G,T,W,FRAME,BR,ENERGIES,FIXED_ENERGY,DR,DG,DT,DW)
    INTEGER,INTENT(IN) :: NP
    REAL(8),INTENT(IN) :: R(NP,4),G(NP,3,4),T(NP,4),W(NP),BR(3,3,PAW_SPIN_GAUGES)
    REAL(8),INTENT(IN) :: ENERGIES(PAW_SPIN_GAUGES),FIXED_ENERGY
    TYPE(PAW_SPIN_FRAME),INTENT(IN) :: FRAME
    REAL(8),INTENT(INOUT) :: DR(NP,4),DG(NP,3,4),DT(NP,4),DW(NP)
    REAL(8) :: GZ(3),V(3),BC(3,3),DIFFERENCE
    INTEGER :: J,K
    GZ=FRAME%BLEND*(ENERGIES(1)-ENERGIES(2))*FRAME%GAUGE_RESPONSE(:,1)
    DO J=1,3
      DO K=1,PAW_SPIN_GAUGES
        GZ(J)=GZ(J)+FRAME%BLEND*FRAME%GAUGE_WEIGHT(K)*SUM(BR(:,:,K)*FRAME%BASIS_RESPONSE(:,:,J,K))
      END DO
    END DO
    DIFFERENCE=SUM(FRAME%GAUGE_WEIGHT*ENERGIES)-FIXED_ENERGY
    V=MATMUL(FRAME%RESOLVENT,GZ)
    BC=0.5D0*(OUTER(V,FRAME%AXIS)+OUTER(FRAME%AXIS,V))+DIFFERENCE*FRAME%BLEND_COV
    CALL PAW_SPIN_MOMENT_PULLBACK(NP,R,G,T,W,BC,DIFFERENCE*FRAME%BLEND_NORM,DR,DG,DT,DW)
  END SUBROUTINE
END MODULE PAW_SPIN_QUADRATURE_MODULE
