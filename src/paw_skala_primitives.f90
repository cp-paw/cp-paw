  SUBROUTINE PAW_SKALA_SOURCE_BACK_BATCH(CACHE,S,BAR,GEOMETRY,STRESS,DX,MOMENT,CONTRACTION,COVERED)
    ! Only complete cached rows are offloaded. Remaining rows use SOURCE_IMAGES.
    TYPE(PAW_SKALA_SOURCE_CACHE),INTENT(IN) :: CACHE
    TYPE(PAW_SKALA_SOURCE),INTENT(INOUT) :: S
    REAL(8),INTENT(IN) :: BAR(:,:,:)
    LOGICAL,INTENT(IN) :: GEOMETRY,STRESS
    REAL(8),INTENT(OUT) :: DX(3),MOMENT(3,3),CONTRACTION
    INTEGER,INTENT(OUT) :: COVERED
#IF DEFINED(CPPVAR_OPENACC)
    INTEGER,PARAMETER :: TILE=128
    LOGICAL,SAVE :: INITIALIZED=.FALSE.,ENABLED=.FALSE.
    INTEGER(8),SAVE :: LIMIT=256_8*1048576_8
    INTEGER,SAVE :: MINROWS=4096
    CHARACTER(128) :: TEXT
    INTEGER :: STATUS,IOS,IP,NE,NC,N,D
    INTEGER(8) :: FIXED,ENTRY,PAYLOAD,MB
    REAL(8) :: DM(S%LMNX,S%LMNX,S%NDIMD),DH(S%LMNX,S%LMNX,S%NDIMD)
#ENDIF
    COVERED=0
    DX=0.D0
    MOMENT=0.D0
    CONTRACTION=0.D0
#IF DEFINED(CPPVAR_OPENACC)
    IF(.NOT.INITIALIZED) THEN
      INITIALIZED=.TRUE.
      CALL GET_ENVIRONMENT_VARIABLE('CPPAW_SKALA_SOURCE_BACK_ACC',TEXT,STATUS=STATUS)
      IF(STATUS.EQ.0) ENABLED=TRIM(ADJUSTL(TEXT)).EQ.'1'
      CALL GET_ENVIRONMENT_VARIABLE('CPPAW_SKALA_SOURCE_BACK_ACC_MIN_ROWS',TEXT,STATUS=STATUS)
      IF(STATUS.EQ.0) THEN
        READ(TEXT,*,IOSTAT=IOS) MINROWS
        IF(IOS.NE.0) MINROWS=4096
        MINROWS=MAX(1,MINROWS)
      END IF
      CALL GET_ENVIRONMENT_VARIABLE('CPPAW_SKALA_SOURCE_BACK_ACC_MB',TEXT,STATUS=STATUS)
      IF(STATUS.EQ.0) THEN
        MB=-1_8
        IOS=1
        IF(LEN_TRIM(TEXT).GT.0.AND.VERIFY(TRIM(ADJUSTL(TEXT)),'0123456789').EQ.0) &
 &        READ(TEXT,*,IOSTAT=IOS) MB
        IF(IOS.NE.0.OR.MB.LT.0_8.OR.MB.GT.HUGE(MB)/1048576_8) THEN
          CALL ERROR$MSG('CPPAW_SKALA_SOURCE_BACK_ACC_MB MUST BE A NONNEGATIVE INTEGER')
          CALL ERROR$STOP('PAW_SKALA_SOURCE_BACK_BATCH')
        END IF
        LIMIT=MB*1048576_8
      END IF
    END IF
    IF(.NOT.ENABLED.OR..NOT.CACHE%READY) RETURN
    IF(GEOMETRY.AND..NOT.CACHE%GEOMETRY) RETURN
    IF(STRESS.AND..NOT.GEOMETRY) RETURN
    IF(SIZE(BAR,1).NE.5.OR.SIZE(BAR,2).NE.2.OR.SIZE(BAR,3).NE.SIZE(CACHE%POINT,1)) RETURN
    IF(ACC_GET_NUM_DEVICES(ACC_DEVICE_NVIDIA).LE.0) RETURN
    N=S%LMNX
    NC=SIZE(CACHE%WAVE,1)
    ! Includes geometry, adjoints, density matrix, output matrix and tile scratch.
    FIXED=8_8*((2_8+TILE)*N*N*S%NDIMD+13_8*TILE)+4_8
    ENTRY=8_8*(INT(NC,8)*N*2_8+18_8)
    DO IP=1,CACHE%LAST
      NE=CACHE%FIRST(IP+1)-1
      PAYLOAD=FIXED+ENTRY*NE+84_8*IP
      IF(PAYLOAD.GT.LIMIT) EXIT
      COVERED=IP
    END DO
    IF(COVERED.LT.MINROWS) THEN
      COVERED=0
      RETURN
    END IF
    NE=CACHE%FIRST(COVERED+1)-1
    IF(NE.EQ.0) THEN
      COVERED=0
      RETURN
    END IF
    DO D=1,S%NDIMD
      DM(:,:,D)=0.5D0*REAL(S%DM(:,:,D)+TRANSPOSE(S%DM(:,:,D)),KIND=8)
    END DO
    CALL SOURCE_BACK_DEVICE(N,NC,S%NDIMD,COVERED,NE,TILE &
 &       ,CACHE%FIRST(1:COVERED+1),CACHE%WAVE(:,:,:,1:NE),CACHE%COREJAC(:,:,1:NE) &
 &       ,CACHE%IMAGE(:,1:NE),DM,BAR(:,:,1:COVERED),GEOMETRY,STRESS &
 &       ,DH,DX,MOMENT,CONTRACTION)
    S%DH(:,:,1:S%NDIMD)=S%DH(:,:,1:S%NDIMD)+DH
#ENDIF
  END SUBROUTINE PAW_SKALA_SOURCE_BACK_BATCH

#IF DEFINED(CPPVAR_OPENACC)
  SUBROUTINE SOURCE_BACK_DEVICE(N,NC,ND,NP,NE,NT,FIRST,WAVE,COREJAC,IMAGE,DM,BAR &
 &                              ,GEOMETRY,STRESS,DH,DX,MOMENT,CONTRACTION)
    INTEGER,INTENT(IN) :: N,NC,ND,NP,NE,NT,FIRST(NP+1)
    REAL(8),INTENT(IN) :: WAVE(NC,N,2,NE),COREJAC(5,3,NE),IMAGE(3,NE)
    REAL(8),INTENT(IN) :: DM(N,N,ND),BAR(5,2,NP)
    LOGICAL,INTENT(IN) :: GEOMETRY,STRESS
    REAL(8),INTENT(OUT) :: DH(N,N,ND),DX(3),MOMENT(3,3),CONTRACTION
    REAL(8) :: ROWDH(N,N,ND,NT),ROWDX(3,NT),ROWMOM(3,3,NT),ROWCON(NT)
    REAL(8) :: KB(5),DC,DG(3),BC,BG(3),DP(3),KERNEL,SGN,C,G(3),V
    INTEGER :: START,COUNT,IT,IP,E,Q,D,I,J,K,L
    DH=0.D0
    DX=0.D0
    MOMENT=0.D0
    CONTRACTION=0.D0
!$ACC DATA COPYIN(FIRST,WAVE,COREJAC,IMAGE,DM,BAR) &
!$ACC& CREATE(ROWDH,ROWDX,ROWMOM,ROWCON)
    DO START=1,NP,NT
      COUNT=MIN(NT,NP-START+1)
!$ACC PARALLEL LOOP GANG VECTOR &
!$ACC& PRESENT(FIRST,WAVE,COREJAC,IMAGE,DM,BAR,ROWDH,ROWDX,ROWMOM,ROWCON) &
!$ACC& PRIVATE(IP,E,Q,D,I,J,K,L,KB,DC,DG,BC,BG,DP,KERNEL,SGN,C,G,V)
      DO IT=1,COUNT
        IP=START+IT-1
        ROWDH(:,:,:,IT)=0.D0
        ROWDX(:,IT)=0.D0
        ROWMOM(:,:,IT)=0.D0
        ROWCON(IT)=0.D0
        DO E=FIRST(IP),FIRST(IP+1)-1
          DP=0.D0
          DO D=1,ND
            SGN=MERGE(1.D0,-1.D0,D.EQ.1)
            KB=0.5D0*(BAR(:,1,IP)+SGN*BAR(:,2,IP))
            IF(GEOMETRY.AND.D.EQ.1) THEN
              DO K=1,3
                DP(K)=SUM(KB*COREJAC(:,K,E))
              END DO
            END IF
            DO Q=1,2
              SGN=MERGE(1.D0,-1.D0,Q.EQ.1)
              DO I=1,N
                C=WAVE(1,I,Q,E)
                G=WAVE(2:4,I,Q,E)
                DC=0.D0
                DG=0.D0
                DO J=1,N
                  V=SGN*DM(I,J,D)
                  DC=DC+V*WAVE(1,J,Q,E)
                  DG=DG+V*WAVE(2:4,J,Q,E)
                END DO
                ROWCON(IT)=ROWCON(IT)+KB(1)*C*DC+2.D0*SUM(KB(2:4)*G)*DC &
 &                                      +0.5D0*KB(5)*SUM(G*DG)
                IF(GEOMETRY) THEN
                  BC=2.D0*(KB(1)*DC+SUM(KB(2:4)*DG))
                  BG=2.D0*KB(2:4)*DC+KB(5)*DG
                  DO K=1,3
                    DP(K)=DP(K)+BC*G(K)
                    DO L=1,3
                      DP(K)=DP(K)+BG(L)*WAVE(4+L+3*(K-1),I,Q,E)
                    END DO
                  END DO
                END IF
                DO J=I,N
                  KERNEL=KB(1)*C*WAVE(1,J,Q,E) &
 &                      +SUM(KB(2:4)*(G*WAVE(1,J,Q,E)+C*WAVE(2:4,J,Q,E))) &
 &                      +0.5D0*KB(5)*SUM(G*WAVE(2:4,J,Q,E))
                  ROWDH(I,J,D,IT)=ROWDH(I,J,D,IT)+SGN*KERNEL
                  IF(I.NE.J) ROWDH(J,I,D,IT)=ROWDH(J,I,D,IT)+SGN*KERNEL
                END DO
              END DO
            END DO
          END DO
          ROWDX(:,IT)=ROWDX(:,IT)+DP
          IF(STRESS) THEN
            DO K=1,3
              ROWMOM(:,K,IT)=ROWMOM(:,K,IT)+DP*IMAGE(K,E)
            END DO
          END IF
        END DO
      END DO
!$ACC UPDATE SELF(ROWDH(:,:,:,1:COUNT),ROWDX(:,1:COUNT),ROWMOM(:,:,1:COUNT),ROWCON(1:COUNT))
      ! Preserve row order and pre-existing host matrix contents without atomics.
      DO IT=1,COUNT
        DH=DH+ROWDH(:,:,:,IT)
        DX=DX+ROWDX(:,IT)
        MOMENT=MOMENT+ROWMOM(:,:,IT)
        CONTRACTION=CONTRACTION+ROWCON(IT)
      END DO
    END DO
!$ACC END DATA
  END SUBROUTINE SOURCE_BACK_DEVICE
#ENDIF

  FUNCTION PAW_SKALA_SOURCE_CACHE_LIMIT() RESULT(BYTES)
    INTEGER(8) :: BYTES
    INTEGER(8),SAVE :: LIMIT=-1_8
    CHARACTER(128) :: VALUE
    INTEGER :: STATUS,IOS
    IF(LIMIT.LT.0_8) THEN
      LIMIT=256_8
      CALL GET_ENVIRONMENT_VARIABLE('CPPAW_SKALA_SOURCE_CACHE_MB',VALUE,STATUS=STATUS)
      IF(STATUS.NE.1) THEN
        VALUE=ADJUSTL(VALUE)
        IOS=1
        IF(STATUS.EQ.0.AND.LEN_TRIM(VALUE).GT.0) THEN
          IF(VERIFY(TRIM(VALUE),'0123456789').EQ.0) READ(VALUE,*,IOSTAT=IOS) LIMIT
        END IF
        IF(IOS.NE.0.OR.LIMIT.LT.0_8.OR.LIMIT.GT.HUGE(LIMIT)/1048576_8) THEN
          CALL ERROR$MSG('CPPAW_SKALA_SOURCE_CACHE_MB MUST BE A NONNEGATIVE INTEGER')
          CALL ERROR$STOP('PAW_SKALA_SOURCE_CACHE_LIMIT')
        END IF
      END IF
      LIMIT=LIMIT*1048576_8
    END IF
    BYTES=LIMIT
  END FUNCTION PAW_SKALA_SOURCE_CACHE_LIMIT

  FUNCTION PAW_SKALA_SOURCE_CACHE_BYTES(CACHE) RESULT(BYTES)
    TYPE(PAW_SKALA_SOURCE_CACHE),INTENT(IN) :: CACHE
