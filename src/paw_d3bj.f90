MODULE PAW_D3BJ_MODULE
  USE, INTRINSIC :: ISO_C_BINDING
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: PAW_D3BJ_SELECT, PAW_D3BJ_ADD, PAW_D3BJ_ACTIVE
  CHARACTER(64),SAVE :: METHOD=' '
  LOGICAL,SAVE :: THREEBODY=.FALSE.
#IF DEFINED(CPPVAR_D3BJ)
  INTERFACE
    FUNCTION NEW_ERROR() BIND(C,NAME='dftd3_new_error') RESULT(P)
      IMPORT C_PTR
      TYPE(C_PTR) :: P
    END FUNCTION
    FUNCTION HAS_ERROR(P) BIND(C,NAME='dftd3_check_error') RESULT(I)
      IMPORT C_PTR,C_INT
      TYPE(C_PTR),VALUE :: P
      INTEGER(C_INT) :: I
    END FUNCTION
    SUBROUTINE MESSAGE(P,MSG,N) BIND(C,NAME='dftd3_get_error')
      IMPORT C_PTR,C_CHAR,C_INT
      TYPE(C_PTR),VALUE :: P
      CHARACTER(KIND=C_CHAR) :: MSG(*)
      INTEGER(C_INT) :: N
    END SUBROUTINE
    FUNCTION NEW_STRUCTURE(ERR,N,Z,XYZ,CELL,PBC) BIND(C,NAME='dftd3_new_structure') RESULT(P)
      IMPORT C_PTR,C_INT,C_DOUBLE,C_BOOL
      TYPE(C_PTR),VALUE :: ERR
      INTEGER(C_INT),VALUE :: N
      INTEGER(C_INT) :: Z(*)
      REAL(C_DOUBLE) :: XYZ(3,*),CELL(3,3)
      LOGICAL(C_BOOL) :: PBC(3)
      TYPE(C_PTR) :: P
    END FUNCTION
    FUNCTION NEW_MODEL(ERR,MOL) BIND(C,NAME='dftd3_new_d3_model') RESULT(P)
      IMPORT C_PTR
      TYPE(C_PTR),VALUE :: ERR,MOL
      TYPE(C_PTR) :: P
    END FUNCTION
    SUBROUTINE SET_CUTOFF(ERR,MODEL,R2,R3,RCN) BIND(C,NAME='dftd3_set_model_realspace_cutoff')
      IMPORT C_PTR,C_DOUBLE
      TYPE(C_PTR),VALUE :: ERR,MODEL
      REAL(C_DOUBLE),VALUE :: R2,R3,RCN
    END SUBROUTINE
    FUNCTION LOAD_BJ(ERR,NAME,ATM) BIND(C,NAME='dftd3_load_rational_damping') RESULT(P)
      IMPORT C_PTR,C_CHAR,C_BOOL
      TYPE(C_PTR),VALUE :: ERR
      CHARACTER(KIND=C_CHAR) :: NAME(*)
      LOGICAL(C_BOOL),VALUE :: ATM
      TYPE(C_PTR) :: P
    END FUNCTION
    SUBROUTINE DISPERSION(ERR,MOL,MODEL,PARAM,E,G,S) BIND(C,NAME='dftd3_get_dispersion')
      IMPORT C_PTR,C_DOUBLE
      TYPE(C_PTR),VALUE :: ERR,MOL,MODEL,PARAM
      REAL(C_DOUBLE) :: E,G(3,*),S(3,3)
    END SUBROUTINE
    SUBROUTINE DROP_ERROR(P) BIND(C,NAME='dftd3_delete_error')
      IMPORT C_PTR
      TYPE(C_PTR) :: P
    END SUBROUTINE
    SUBROUTINE DROP_MOL(P) BIND(C,NAME='dftd3_delete_structure')
      IMPORT C_PTR
      TYPE(C_PTR) :: P
    END SUBROUTINE
    SUBROUTINE DROP_MODEL(P) BIND(C,NAME='dftd3_delete_model')
      IMPORT C_PTR
      TYPE(C_PTR) :: P
    END SUBROUTINE
    SUBROUTINE DROP_PARAM(P) BIND(C,NAME='dftd3_delete_param')
      IMPORT C_PTR
      TYPE(C_PTR) :: P
    END SUBROUTINE
  END INTERFACE
  TYPE(C_PTR),SAVE :: PARAM=C_NULL_PTR
#ENDIF
CONTAINS
  LOGICAL FUNCTION PAW_D3BJ_ACTIVE()
    PAW_D3BJ_ACTIVE=METHOD.NE.' '
  END FUNCTION

  SUBROUTINE PAW_D3BJ_SELECT(NAME,ATM)
    CHARACTER(*),INTENT(IN) :: NAME
    LOGICAL,INTENT(IN) :: ATM
#IF DEFINED(CPPVAR_D3BJ)
    TYPE(C_PTR) :: ERR
    METHOD=NAME
    THREEBODY=ATM
    ERR=NEW_ERROR()
    IF(C_ASSOCIATED(PARAM)) CALL DROP_PARAM(PARAM)
    PARAM=LOAD_BJ(ERR,TRIM(METHOD)//C_NULL_CHAR,LOGICAL(ATM,C_BOOL))
    CALL CHECK(ERR)
    CALL DROP_ERROR(ERR)
#ELSE
    CALL ERROR$MSG('D3(BJ) REQUESTED BUT THIS BUILD HAS NO S-DFTD3 SUPPORT')
    CALL ERROR$MSG('REBUILD WITH CPPAW_USE_D3BJ=1 AND S-DFTD3 OR SET VDW=F')
    CALL ERROR$STOP('PAW_D3BJ_SELECT')
#ENDIF
  END SUBROUTINE

#IF DEFINED(CPPVAR_D3BJ)
  SUBROUTINE CHECK(ERR)
    TYPE(C_PTR) :: ERR
    CHARACTER(KIND=C_CHAR,LEN=256) :: MSG
    INTEGER :: I
    IF(HAS_ERROR(ERR)==0) RETURN
    MSG=' '
    CALL MESSAGE(ERR,MSG,INT(LEN(MSG),C_INT))
    I=INDEX(MSG,C_NULL_CHAR)
    IF(I>0) MSG(I:)=' '
    CALL ERROR$MSG(TRIM(MSG))
    CALL ERROR$CHVAL('D3(BJ) PARAMETER SET',METHOD)
    CALL ERROR$STOP('PAW_D3BJ')
  END SUBROUTINE
#ENDIF

  SUBROUTINE PAW_D3BJ_ADD(N,R,CELL,TFORCE,TSTRESS,FORCE,STRAIN)
    USE MPE_MODULE
    USE ISOLATE_MODULE, ONLY: TISOLATE
    INTEGER,INTENT(IN) :: N
    REAL(8),INTENT(IN) :: R(3,N),CELL(3,3)
    LOGICAL,INTENT(IN) :: TFORCE,TSTRESS
    REAL(8),INTENT(INOUT) :: FORCE(3,N),STRAIN(3,3)
#IF DEFINED(CPPVAR_D3BJ)
    REAL(C_DOUBLE),ALLOCATABLE :: G(:,:)
    REAL(C_DOUBLE) :: E,S(3,3),AEZ,ANG
    INTEGER(C_INT) :: Z(N)
    LOGICAL(C_BOOL) :: PBC(3)
    TYPE(C_PTR) :: ERR,MOL,MODEL
    INTEGER :: NTASKS,RANK,I,ISP,NFIL
    IF(.NOT.PAW_D3BJ_ACTIVE()) RETURN
    CALL MPE$QUERY('MONOMER',NTASKS,RANK)
    ALLOCATE(G(3,N))
    IF(RANK==1) THEN
      DO I=1,N
        CALL ATOMLIST$GETI4('ISPECIES',I,ISP)
        CALL SETUP$ISELECT(ISP)
        CALL SETUP$GETR8('AEZ',AEZ)
        CALL SETUP$UNSELECT()
        Z(I)=NINT(AEZ,C_INT)
        IF(ABS(AEZ-Z(I))>1.D-8) ERROR STOP 'D3(BJ) requires integer atomic numbers'
      END DO
      PBC=.NOT.TISOLATE
      ERR=NEW_ERROR()
      MOL=NEW_STRUCTURE(ERR,INT(N,C_INT),Z,R,CELL,PBC)
      CALL CHECK(ERR)
      MODEL=NEW_MODEL(ERR,MOL)
      CALL CHECK(ERR)
      CALL CONSTANTS('ANGSTROM',ANG)
      ! CP2K's R_CUTOFF=20 angstrom includes pairs out to twice this radius.
      CALL SET_CUTOFF(ERR,MODEL,40.D0*ANG,40.D0*ANG,40.D0)
      CALL CHECK(ERR)
      CALL DISPERSION(ERR,MOL,MODEL,PARAM,E,G,S)
      CALL CHECK(ERR)
      CALL DROP_MODEL(MODEL)
      CALL DROP_MOL(MOL)
      CALL DROP_ERROR(ERR)
      CALL FILEHANDLER$UNIT('PROT',NFIL)
      WRITE(NFIL,'(A,A,A,L1,A,L1,A,ES24.16)') 'D3(BJ) ',TRIM(METHOD),' ATM=',THREEBODY, &
          ' PERIODIC=',.NOT.TISOLATE,' ENERGY [HA] ',E
    END IF
    CALL MPE$BROADCAST('MONOMER',1,E)
    CALL ENERGYLIST$SET('VAN DER WAALS ENERGY',E)
    CALL ENERGYLIST$ADD('TOTAL ENERGY',E)
    CALL ENERGYLIST$ADD('CONSTANT ENERGY',E)
    IF(TFORCE) THEN
      CALL MPE$BROADCAST('MONOMER',1,G)
      FORCE=FORCE-G
    END IF
    IF(TSTRESS) THEN
      CALL MPE$BROADCAST('MONOMER',1,S)
      STRAIN=STRAIN+S
    END IF
#ENDIF
  END SUBROUTINE
END MODULE
